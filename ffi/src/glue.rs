//! The Rust side of the C ABI: a crate of `extern "C"` functions over the exported
//! crates, with the runtime beside it and the header in `include/`.
//!
//! Each function lifts its C arguments to Rust values, calls the Rust item by its path,
//! and lowers the result. A value is copied in from the caller's memory, which Rust
//! never frees, and lowered into memory the caller frees. A handle is borrowed as the
//! receiver or parameter is, or moved out of when taken by value.

use std::fmt::Write;
use std::path::Path;

use crate::abi::{self, Abi, Ty};
use crate::config::Package;
use crate::ir::{Access, Family, Function, Mutability, Receiver, Traits, Type};

const RUNTIME: &str = include_str!("../runtime/rt.rs");

/// The crate's build script: on macOS, a CPython extension leaves Python's symbols for the
/// interpreter that loads it to resolve.
const BUILD: &str = "// Generated by rust2-ffi. Do not edit.\n\n\
	fn main() {\n\
	\t#[cfg(feature = \"python\")]\n\
	\tpyo3_build_config::add_extension_module_link_args();\n\
	}\n";

/// The name the crate depends on an export by, its root suffixed: an export may be
/// named `bytes` or `std`, which the crate names too.
fn dependency(krate: &str) -> String {
	format!("{krate}_export")
}

/// The crate that builds the C ABI.
pub struct Crate<'a> {
	pub abi: &'a Abi<'a>,
	/// The exported packages, the configured one first, each a dependency of the crate.
	pub exports: &'a [Package],
	/// The `[patch]` table the crate's own workspace resolves the exports with, as the
	/// check did.
	pub patch: &'a str,
}

impl Crate<'_> {
	/// The exported packages, comma-separated.
	fn packages(&self) -> String {
		let names: Vec<&str> = self.exports.iter().map(|p| p.name.as_str()).collect();
		names.join(", ")
	}

	/// Write the crate into `out`: `Cargo.toml`, `src/`, `include/<prefix>.h` and `.hpp`,
	/// `kotlin/<prefix>.kt`, whose JNI functions the crate's `kotlin` feature builds, and
	/// `python/<prefix>.py`, whose CPython extension its `python` feature builds.
	pub fn write(&self, out: &Path) -> Result<(), String> {
		// Cargo unifies in what the configured package enables in each other export.
		let dependencies: String = (self.exports.iter())
			.map(|export| {
				let mut features: Vec<String> = export.features.iter().map(|f| format!("{f:?}")).collect();
				features.sort();
				format!(
					"{} = {{ package = {:?}, path = {:?}, default-features = false, features = [{}] }}\n",
					dependency(&export.root()),
					export.name,
					export.dir.display().to_string(),
					features.join(", ")
				)
			})
			.collect();
		// A foreign type, exported as an object when no export is its crate, resolves to the
		// version the exports build with, as `bytes` does: one per major version per
		// resolution.
		let foreign: String = [("url", "2"), ("serde_json", "1")]
			.into_iter()
			.filter(|(krate, _)| self.abi.api.objects.iter().any(|o| o.path[0] == *krate))
			.filter(|(krate, _)| !self.exports.iter().any(|export| export.root() == *krate))
			.map(|(krate, version)| {
				format!(
					"{} = {{ package = \"{krate}\", version = \"{version}\" }}\n",
					dependency(krate)
				)
			})
			.collect();
		let dependencies = format!("{dependencies}{foreign}");
		let manifest = format!(
			"# Generated by rust2-ffi: the C ABI of the pub API of {packages}.\n\
			[package]\n\
			name = \"{package}-ffi\"\n\
			version = \"0.0.0\"\n\
			edition = \"2024\"\n\
			publish = false\n\
			\n\
			[lib]\n\
			name = \"{lib}\"\n\
			crate-type = [\"staticlib\", \"cdylib\"]\n\
			\n\
			[dependencies]\n\
			{dependencies}\
			bytes = \"1\"\n\
			jni-sys = {{ version = \"0.4\", optional = true }}\n\
			pyo3-ffi = {{ version = \"0.30\", optional = true, features = [\"abi3-py311\", \"extension-module\"] }}\n\
			\n\
			[build-dependencies]\n\
			pyo3-build-config = {{ version = \"0.30\", optional = true }}\n\
			\n\
			[features]\n\
			# The JNI functions kotlin/{lib}.kt calls.\n\
			kotlin = [\"dep:jni-sys\"]\n\
			# The CPython extension python/{lib}.py loads.\n\
			python = [\"dep:pyo3-ffi\", \"dep:pyo3-build-config\"]\n\
			\n\
			[workspace]\n\
			{patch}",
			patch = self.patch,
			package = self.exports[0].name,
			packages = self.packages(),
			lib = self.abi.prefix,
		);
		let (header, contract) = crate::c::header(self.abi, &self.packages());
		let cpp = crate::cpp::header(self.abi, &self.packages())?;
		let kotlin = crate::kotlin::generate(self.abi, &self.packages(), contract)?;
		let python = crate::python::generate(self.abi, &self.packages(), contract)?;
		let mut generator = Gen {
			abi: self.abi,
			packages: self.packages(),
			contract,
			dependencies: self.exports.iter().map(|export| dependency(&export.root())).collect(),
			out: String::new(),
		};
		generator.lib();
		crate::driver::write(&out.join("Cargo.toml"), &manifest)?;
		crate::driver::write(&out.join("src/lib.rs"), &generator.out)?;
		crate::driver::write(&out.join("build.rs"), BUILD)?;
		crate::driver::write(&out.join("src/rt.rs"), RUNTIME)?;
		crate::driver::write(&out.join("include").join(format!("{}.h", self.abi.prefix)), &header)?;
		crate::driver::write(&out.join("include").join(format!("{}.hpp", self.abi.prefix)), &cpp)?;
		crate::driver::write(&out.join("src/jni/mod.rs"), &kotlin.glue)?;
		crate::driver::write(&out.join("src/jni/rt.rs"), crate::kotlin::GLUE_RUNTIME)?;
		crate::driver::write(
			&out.join("kotlin").join(format!("{}.kt", self.abi.prefix)),
			&kotlin.kotlin,
		)?;
		crate::driver::write(
			&out.join("kotlin").join(format!("{}.pro", self.abi.prefix)),
			&kotlin.rules,
		)?;
		crate::driver::write(&out.join("src/python/mod.rs"), &python.glue)?;
		crate::driver::write(&out.join("src/python/rt.rs"), crate::python::GLUE_RUNTIME)?;
		crate::driver::write(
			&out.join("python").join(format!("{}.py", self.abi.prefix)),
			&python.python,
		)
	}
}

struct Gen<'a> {
	abi: &'a Abi<'a>,
	/// The exported packages, for the docs.
	packages: String,
	/// The header's contract, which `<prefix>_contract` returns.
	contract: u64,
	/// The name the crate depends on each export by.
	dependencies: Vec<String>,
	out: String,
}

impl Gen<'_> {
	fn line(&mut self, line: impl AsRef<str>) {
		self.out.push_str(line.as_ref());
		self.out.push('\n');
	}

	/// A Rust path, through the crate's dependency on its export.
	fn path(&self, path: &[String]) -> String {
		format!("::{}", dependency(&path[0])) + &path[1..].iter().map(|s| format!("::{s}")).collect::<String>()
	}

	/// An object's Rust type: its lifetimes `'static`, as the handle holds it.
	fn object_path(&self, i: usize) -> String {
		self.rust(&Type::Object(i))
	}

	/// The Rust spelling of a type a callback's method takes or returns, or a type
	/// argument: a type with its instance's arguments, and an object's lifetimes `'static`.
	fn rust(&self, ty: &Type) -> String {
		let api = self.abi.api;
		let generic = |path: &[String], lifetimes: usize, args: &[Type]| {
			let path = self.path(path);
			let mut params = vec!["'static".to_string(); lifetimes];
			params.extend(args.iter().map(|arg| self.rust(arg)));
			match params.is_empty() {
				true => path,
				false => format!("{path}::<{}>", params.join(", ")),
			}
		};
		match ty {
			Type::Unit => "()".to_string(),
			Type::Bool => "bool".to_string(),
			Type::Int(int) => int.rust().to_string(),
			Type::F32 => "f32".to_string(),
			Type::F64 => "f64".to_string(),
			Type::Char => "char".to_string(),
			Type::Str => "str".to_string(),
			Type::String => "::std::string::String".to_string(),
			Type::Slice => "[u8]".to_string(),
			Type::Vec => "::std::vec::Vec<u8>".to_string(),
			Type::Bytes => "::bytes::Bytes".to_string(),
			Type::Duration => "::std::time::Duration".to_string(),
			Type::Path => "::std::path::Path".to_string(),
			Type::PathBuf => "::std::path::PathBuf".to_string(),
			Type::SocketAddr(Family::Any) => "::std::net::SocketAddr".to_string(),
			Type::SocketAddr(Family::V4) => "::std::net::SocketAddrV4".to_string(),
			Type::SocketAddr(Family::V6) => "::std::net::SocketAddrV6".to_string(),
			Type::List(inner) => format!("::std::vec::Vec<{}>", self.rust(inner)),
			Type::Option(inner) => format!("Option<{}>", self.rust(inner)),
			Type::Ref(Mutability::Not, inner) => format!("&{}", self.rust(inner)),
			Type::Ref(Mutability::Mut, inner) => format!("&mut {}", self.rust(inner)),
			Type::Record(i) => generic(&api.records[*i].path, 0, &api.records[*i].args),
			Type::Enum(i) => generic(&api.enums[*i].path, 0, &api.enums[*i].args),
			Type::Object(i) => generic(&api.objects[*i].path, api.objects[*i].lifetimes, &api.objects[*i].args),
			other => unreachable!("no callback or type argument is {other:?}"),
		}
	}

	/// The Rust spelling of a C type.
	fn rs(&self, ty: &Ty) -> String {
		match ty {
			Ty::Void => "()".to_string(),
			Ty::Bool => "bool".to_string(),
			Ty::Int(int) => int.rust().to_string(),
			Ty::F32 => "f32".to_string(),
			Ty::F64 => "f64".to_string(),
			Ty::Char => "u32".to_string(),
			Ty::Buf => "rt::Buf".to_string(),
			Ty::Duration => "rt::Duration".to_string(),
			Ty::SocketAddr => "rt::SocketAddr".to_string(),
			Ty::Struct(name) => name.clone(),
			// A C enum is an `int`.
			Ty::Enum(_) | Ty::Poll => "i32".to_string(),
			Ty::Handle { .. } => "*const c_void".to_string(),
			Ty::Future(_) => "*mut rt::Future".to_string(),
			Ty::Waker => "rt::Waker".to_string(),
			Ty::Out(inner) => format!("*mut {}", self.rs(inner)),
			Ty::In(inner) => format!("*const {}", self.rs(inner)),
			Ty::Fn(params, ret) => {
				let params: Vec<String> = std::iter::once("*mut c_void".to_string())
					.chain(params.iter().map(|p| self.rs(p)))
					.collect();
				format!(
					"Option<unsafe extern \"C\" fn({}) -> {}>",
					params.join(", "),
					self.rs(ret)
				)
			}
			Ty::Data => "*mut c_void".to_string(),
		}
	}

	/// The Rust value of type `ty` that the C value `e` holds, copied out of it.
	fn lift(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Unit => e.to_string(),
			Type::Bool | Type::Int(_) | Type::F32 | Type::F64 => e.to_string(),
			Type::Char => format!("rt::char({e}, w)"),
			Type::Str | Type::String => format!("unsafe {{ {e}.str(w) }}.to_owned()"),
			Type::Slice | Type::Vec => format!("unsafe {{ {e}.bytes(w) }}.to_vec()"),
			Type::Bytes => format!("::bytes::Bytes::copy_from_slice(unsafe {{ {e}.bytes(w) }})"),
			Type::Path | Type::PathBuf => format!("unsafe {{ {e}.path(w) }}.to_path_buf()"),
			Type::Duration | Type::SocketAddr(Family::Any) => format!("{e}.lift(w)"),
			Type::SocketAddr(Family::V4) => format!("{e}.lift_v4(w)"),
			Type::SocketAddr(Family::V6) => format!("{e}.lift_v6(w)"),
			Type::Waker => format!("{e}.lift()"),
			Type::List(inner) => format!(
				"unsafe {{ {e}.items(w) }}.iter().map(|c| {}).collect::<::std::vec::Vec<_>>()",
				self.lift(inner, "(*c)")
			),
			Type::Option(inner) => match inner.base() {
				Type::Object(_) => format!("if {e}.is_null() {{ None }} else {{ Some({}) }}", self.lift(inner, e)),
				base if Abi::nullable(base) => {
					format!("if {e}.is_none() {{ None }} else {{ Some({}) }}", self.lift(inner, e))
				}
				_ => format!(
					"if {e}.some {{ Some({}) }} else {{ None }}",
					self.lift(inner, &format!("{e}.value"))
				),
			},
			Type::Box(inner) => format!("::std::boxed::Box::new({})", self.lift(inner, e)),
			Type::Ref(_, inner) => self.lift(inner, e),
			Type::Record(i) => format!("lift_{}(&{e}, w)", self.abi.record(*i)),
			Type::Enum(i) => match self.abi.api.enums[*i].plain() {
				true => format!("lift_{}({e}, w)", self.abi.enumeration(*i)),
				false => format!("lift_{}(&{e}, w)", self.abi.enumeration(*i)),
			},
			Type::Object(i) => match self.abi.api.objects[*i].copy {
				true => format!(
					"*unsafe {{ rt::Object::<{}>::{}({e}, w) }}",
					self.object_path(*i),
					self.shared(*i)
				),
				false => format!("unsafe {{ rt::Object::<{}>::take({e}, w) }}", self.object_path(*i)),
			},
			Type::Callback(i, form) => abi::dyn_wrap(*form, &format!("Foreign_{}({e})", self.abi.callback(*i))),
			Type::Closure(params, ret) => self.closure(params, ret, e),
			Type::Range(_) => format!("{e}.lift()"),
			Type::Bound(_) | Type::Bounds(_) => format!("{e}.lift(w)"),
			Type::Tuple(elements) => {
				// The trailing comma makes `(x,)` a tuple, not parentheses.
				let lifted: Vec<String> = (elements.iter().enumerate())
					.map(|(n, ty)| format!("{},", self.lift(ty, &format!("{e}._{n}"))))
					.collect();
				format!("({})", lifted.concat())
			}
		}
	}

	/// The Rust closure calling the function C lends as `e`, with its data `e_data`, which
	/// lends each object the closure takes as a handle for that call.
	fn closure(&self, params: &[Type], ret: &Type, e: &str) -> String {
		let typed: Vec<String> = (params.iter().enumerate())
			.map(|(n, ty)| format!("c{n}: {}", self.rust(ty)))
			.collect();
		// Each object the closure takes, and how it is lent.
		let lent = |ty: &Type| match ty {
			Type::Ref(m, inner) => match (&**inner, m) {
				(&Type::Object(i), Mutability::Mut) => Some((i, "lend_mut")),
				(&Type::Object(i), Mutability::Not) if self.abi.api.objects[i].sync => Some((i, "lend")),
				(&Type::Object(i), Mutability::Not) => Some((i, "lend_local")),
				_ => None,
			},
			_ => None,
		};
		let args: Vec<String> = std::iter::once("data.get()".to_string())
			.chain(params.iter().enumerate().map(|(n, ty)| match lent(ty) {
				Some(_) => format!("h{n}"),
				None => self.view(ty, &format!("c{n}")),
			}))
			.collect();
		let mut call = format!("unsafe {{ f({}) }}", args.join(", "));
		for (n, ty) in params.iter().enumerate().rev() {
			if let Some((i, lend)) = lent(ty) {
				call = format!("rt::Object::<{}>::{lend}(c{n}, w, |h{n}| {call})", self.object_path(i));
			}
		}
		format!(
			"{{\n\t\tlet f = {e}.unwrap_or_else(|| rt::fail(w, \"a function is null\"));\n\t\tlet data = rt::Data::new({e}_data);\n\t\tmove |{}| -> {} {{\n\t\t\tlet result = {call};\n\t\t\t{}\n\t\t}}\n\t}}",
			typed.join(", "),
			self.rust(ret),
			self.lift(ret, "result"),
		)
	}

	/// How a call borrows object `i` shared: across threads if it is `Sync`, else on one.
	fn shared(&self, i: usize) -> &'static str {
		match self.abi.api.objects[i].sync {
			true => "borrow",
			false => "borrow_local",
		}
	}

	/// The C value of the Rust value `e` of type `ty`, which the caller frees.
	fn lower(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Unit => "()".to_string(),
			Type::Bool | Type::Int(_) | Type::F32 | Type::F64 => e.to_string(),
			Type::Char => format!("{e} as u32"),
			Type::Str => format!("rt::Buf::string({e}.to_owned())"),
			Type::String => format!("rt::Buf::string({e})"),
			Type::Slice => format!("rt::Buf::vec({e}.to_vec())"),
			Type::Vec => format!("rt::Buf::vec({e})"),
			Type::Bytes => format!("rt::Buf::owned({e})"),
			Type::Path => format!("rt::Buf::path_buf({e}.to_path_buf())"),
			Type::PathBuf => format!("rt::Buf::path_buf({e})"),
			Type::Duration => format!("rt::Duration::lower({e})"),
			Type::SocketAddr(_) => format!("rt::SocketAddr::lower(::std::net::SocketAddr::from({e}))"),
			Type::List(inner) => format!(
				"rt::List::owned(::std::iter::IntoIterator::into_iter({e}).map(|v| {}).collect())",
				self.lower(inner, "v")
			),
			Type::Option(inner) => {
				let none = match inner.base() {
					Type::Object(_) => "::std::ptr::null()".to_string(),
					base if Abi::is_buf(base) => "rt::Buf::NONE".to_string(),
					Type::List(_) => "rt::List::NONE".to_string(),
					_ => {
						let name = self.abi.option(inner);
						return format!(
							"match {e} {{ Some(v) => {name} {{ some: true, value: {} }}, None => {name} {{ some: false, value: unsafe {{ ::std::mem::zeroed() }} }} }}",
							self.lower(inner, "v")
						);
					}
				};
				format!("match {e} {{ Some(v) => {}, None => {none} }}", self.lower(inner, "v"))
			}
			Type::Box(inner) => self.lower(inner, &format!("*{e}")),
			Type::Ref(_, inner) => match &**inner {
				Type::Str | Type::Slice | Type::Path => self.lower(inner, e),
				// A handle in the clone is a new handle, and a slice's clone a `Vec`.
				inner => self.lower(inner, &format!("::std::borrow::ToOwned::to_owned({e})")),
			},
			Type::Record(i) => format!("lower_{}({e})", self.abi.record(*i)),
			Type::Enum(i) => format!("lower_{}({e})", self.abi.enumeration(*i)),
			Type::Object(_) => format!("rt::Object::new({e})"),
			Type::Callback(..) | Type::Closure(..) => unreachable!("a callback is never returned"),
			Type::Waker => unreachable!("a waker is never returned"),
			Type::Range(_) => format!("rt::Range::lower({e})"),
			Type::Bound(_) => format!("rt::Bound::lower({e})"),
			Type::Bounds(_) => format!("rt::Bounds::lower({e})"),
			Type::Tuple(elements) => {
				let names: Vec<String> = (0..elements.len()).map(|n| format!("t{n},")).collect();
				let fields: Vec<String> = (elements.iter().enumerate())
					.map(|(n, ty)| format!("_{n}: {}", self.lower(ty, &format!("t{n}"))))
					.collect();
				format!(
					"match {e} {{ ({}) => {} {{ {} }} }}",
					names.concat(),
					self.abi.tuple(elements),
					fields.join(", ")
				)
			}
		}
	}

	/// What frees the parts of the C value `e` that Rust allocated, if any.
	fn free(&self, ty: &Type, e: &str) -> Option<String> {
		match ty {
			_ if Abi::is_buf(ty) => Some(format!("unsafe {{ {e}.free() }};")),
			Type::List(inner) => {
				let each = self.free(inner, "c").unwrap_or_default();
				Some(format!(
					"unsafe {{ {e}.free(\"{}_free\", |c| {{ let _ = c; {each} }}) }};",
					self.abi.list(inner)
				))
			}
			Type::Option(inner) => match inner.base() {
				base if Abi::is_buf(base) => Some(format!("unsafe {{ {e}.free() }};")),
				// A null handle or array frees nothing.
				Type::Object(_) | Type::List(_) => self.free(inner, e),
				_ => self
					.free(inner, &format!("{e}.value"))
					.map(|free| format!("if {e}.some {{ {free} }}")),
			},
			Type::Box(inner) => self.free(inner, e),
			Type::Tuple(elements) => {
				let frees: Vec<String> = (elements.iter().enumerate())
					.filter_map(|(n, ty)| self.free(ty, &format!("{e}._{n}")))
					.collect();
				(!frees.is_empty()).then(|| frees.join(" "))
			}
			Type::Object(i) => Some(format!(
				"unsafe {{ rt::Object::<{}>::free({e}) }};",
				self.object_path(*i)
			)),
			Type::Record(i) if self.owns(ty) => Some(format!("free_{}({e});", self.abi.record(*i))),
			Type::Enum(i) if self.owns(ty) => Some(format!("free_{}({e});", self.abi.enumeration(*i))),
			_ => None,
		}
	}

	/// Whether a value of `ty` holds memory Rust allocated.
	fn owns(&self, ty: &Type) -> bool {
		match ty {
			_ if Abi::is_buf(ty) => true,
			Type::Object(_) | Type::List(_) => true,
			Type::Option(inner) | Type::Box(inner) => self.owns(inner),
			Type::Tuple(elements) => elements.iter().any(|ty| self.owns(ty)),
			Type::Record(i) => self.abi.api.records[*i].fields.iter().any(|f| self.owns(&f.ty)),
			Type::Enum(i) => self.abi.api.enums[*i]
				.variants
				.iter()
				.any(|v| v.fields.iter().any(|f| self.owns(&f.ty))),
			_ => false,
		}
	}

	fn lib(&mut self) {
		let api = self.abi.api;
		self.line(format!(
			"//! Generated by rust2-ffi: the C ABI of the pub API of {}. Do not edit.\n",
			self.packages
		));
		self.line("#![allow(non_camel_case_types, reason = \"the C names\")]");
		self.line("#![allow(unused_unsafe, reason = \"every conversion is in its own block\")]");
		self.line("#![allow(unused_parens, reason = \"each element is lifted from `(*c)`\")]");
		self.line("#![allow(clippy::all, reason = \"generated\")]");
		self.line("#![allow(dead_code, reason = \"the runtime serves every API\")]\n");
		self.line("mod rt;\n");
		self.line("#[cfg(feature = \"kotlin\")]\nmod jni;\n");
		self.line("#[cfg(feature = \"python\")]\nmod python;\n");
		self.line("use std::ffi::c_void;\n");
		// An export may export nothing and only enable features in the others, as a
		// package standing in for a binding crate does, which cargo would call unused.
		for dependency in self.dependencies.clone() {
			self.line(format!("use {dependency} as _;"));
		}
		self.line("");

		let p = self.abi.prefix.clone();
		self.line(format!(
			"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {p}_buf_free(buf: rt::Buf) {{\n\tunsafe {{ buf.free() }}\n}}\n"
		));
		self.line(format!(
			"#[unsafe(no_mangle)]\npub extern \"C\" fn {p}_contract() -> u64 {{\n\t0x{:016x}\n}}\n",
			self.contract
		));

		for (name, ty) in &self.abi.ranges {
			let (kind, int) = match ty {
				Type::Range(int) => ("Range", int),
				Type::Bound(int) => ("Bound", int),
				Type::Bounds(int) => ("Bounds", int),
				other => unreachable!("{other:?} is no range"),
			};
			self.line(format!("pub type {name} = rt::{kind}<{}>;\n", int.rust()));
		}
		for (name, elem) in &self.abi.lists.clone() {
			let c = self.rs(&self.abi.ty(elem));
			self.line(format!("pub type {name} = rt::List<{c}>;\n"));
			let free = self
				.free(&Type::List(Box::new(elem.clone())), "this")
				.expect("an array is freed");
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: {name}) {{\n\t{free}\n}}\n"
			));
		}
		for (name, elements) in &self.abi.tuples.clone() {
			let fields: String = (elements.iter().enumerate())
				.map(|(n, ty)| format!("\tpub _{n}: {},\n", self.rs(&self.abi.ty(ty))))
				.collect();
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n{fields}}}\n"
			));
		}
		for (name, inner) in &self.abi.options.clone() {
			let value = self.rs(&self.abi.ty(inner));
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub some: bool,\n\tpub value: {value},\n}}\n"
			));
		}
		for i in 0..api.records.len() {
			self.record(i);
		}
		for i in 0..api.enums.len() {
			self.enumeration(i);
		}
		for i in 0..api.callbacks.len() {
			self.callback(i);
		}
		for (i, object) in api.objects.iter().enumerate() {
			let name = self.abi.object(i);
			let path = self.object_path(i);
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: *const c_void) {{\n\tunsafe {{ rt::Object::<{path}>::free(this) }}\n}}\n"
			));
			let borrow = self.shared(i);
			self.traits(&name, &path, object.traits, |e| {
				format!("unsafe {{ rt::Object::<{path}>::{borrow}({e}, w) }}")
			});
			let owner = Ty::Handle {
				name: name.clone(),
				constant: false,
			};
			for method in &object.methods {
				self.function(method, Some((&owner, Type::Object(i))));
			}
		}
		for function in &api.functions {
			self.function(function, None);
		}
	}

	/// The functions a type's std traits export; `borrow` reads the receiver `e`.
	fn traits(&mut self, name: &str, path: &str, traits: Traits, borrow: impl Fn(&str) -> String) {
		let handle = "*const c_void";
		if traits.clone {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_clone(this: {handle}) -> {handle} {{\n\tlet w = \"{name}_clone\";\n\tlet this = {};\n\trt::Object::new(<{path} as ::std::clone::Clone>::clone(&*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.eq {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_eq(a: {handle}, b: {handle}) -> bool {{\n\tlet w = \"{name}_eq\";\n\tlet a = {};\n\tlet b = {};\n\t<{path} as ::std::cmp::PartialEq>::eq(&*a, &*b)\n}}\n",
				borrow("a"),
				borrow("b")
			));
		}
		if traits.display {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_to_string(this: {handle}) -> rt::Buf {{\n\tlet w = \"{name}_to_string\";\n\tlet this = {};\n\trt::Buf::string(::std::string::ToString::to_string(&*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.debug {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_debug(this: {handle}) -> rt::Buf {{\n\tlet w = \"{name}_debug\";\n\tlet this = {};\n\trt::Buf::string(format!(\"{{:?}}\", &*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.default {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_default() -> {handle} {{\n\trt::Object::new(<{path} as ::std::default::Default>::default())\n}}\n"
			));
		}
	}

	/// The functions every value type has: its std traits, read through a pointer, and
	/// `free`.
	fn value_traits(&mut self, name: &str, path: &str, ty: &Type, traits: Traits) {
		let lift = self.lift(ty, "unsafe { *this }");
		let lift_a = self.lift(ty, "unsafe { *a }");
		let lift_b = self.lift(ty, "unsafe { *b }");
		let c = self.rs(&self.abi.ty(ty));
		if traits.eq {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_eq(a: *const {c}, b: *const {c}) -> bool {{\n\tlet w = \"{name}_eq\";\n\t<{path} as ::std::cmp::PartialEq>::eq(&{lift_a}, &{lift_b})\n}}\n"
			));
		}
		if traits.display {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_to_string(this: *const {c}) -> rt::Buf {{\n\tlet w = \"{name}_to_string\";\n\trt::Buf::string(::std::string::ToString::to_string(&{lift}))\n}}\n"
			));
		}
		if traits.debug {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_debug(this: *const {c}) -> rt::Buf {{\n\tlet w = \"{name}_debug\";\n\trt::Buf::string(format!(\"{{:?}}\", &{lift}))\n}}\n"
			));
		}
		if traits.default {
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_default() -> {c} {{\n\t{}\n}}\n",
				self.lower(ty, &format!("<{path} as ::std::default::Default>::default()"))
			));
		}
		if !matches!(self.abi.ty(ty), Ty::Enum(_)) {
			let free = self.free(ty, "unsafe { this.read() }").unwrap_or_default();
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: *mut {c}) {{\n\tif this.is_null() {{\n\t\treturn;\n\t}}\n\t{free}\n}}\n"
			));
		}
	}

	fn record(&mut self, i: usize) {
		let record = &self.abi.api.records[i];
		let name = self.abi.record(i);
		let path = self.rust(&Type::Record(i));
		let ty = Type::Record(i);
		let mut fields = String::new();
		for (n, field) in record.fields.iter().enumerate() {
			let _ = writeln!(fields, "\tpub f{n}: {},", self.rs(&self.abi.ty(&field.ty)));
		}
		self.line(format!(
			"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n{fields}}}\n"
		));
		let lifted: Vec<String> = record
			.fields
			.iter()
			.enumerate()
			.map(|(n, f)| self.lift(&f.ty, &format!("c.f{n}")))
			.collect();
		let build = match record.tuple {
			true => format!("{path}({})", lifted.join(", ")),
			false => {
				let fields: Vec<String> = record
					.fields
					.iter()
					.zip(&lifted)
					.map(|(f, l)| format!("{}: {l}", f.name))
					.collect();
				format!("{path} {{ {} }}", fields.join(", "))
			}
		};
		self.line(format!(
			"fn lift_{name}(c: &{name}, w: &str) -> {path} {{\n\tlet _ = w;\n\t{build}\n}}\n"
		));
		let bindings: Vec<String> = (0..record.fields.len()).map(|n| format!("f{n}")).collect();
		let pattern = match record.tuple {
			true => format!("{path}({})", bindings.join(", ")),
			false => {
				let fields: Vec<String> = record
					.fields
					.iter()
					.zip(&bindings)
					.map(|(f, b)| format!("{}: {b}", f.name))
					.collect();
				format!("{path} {{ {} }}", fields.join(", "))
			}
		};
		let lowered: Vec<String> = record
			.fields
			.iter()
			.enumerate()
			.map(|(n, f)| format!("f{n}: {}", self.lower(&f.ty, &format!("f{n}"))))
			.collect();
		self.line(format!(
			"fn lower_{name}(v: {path}) -> {name} {{\n\tlet {pattern} = v;\n\t{name} {{ {} }}\n}}\n",
			lowered.join(", ")
		));
		if self.owns(&ty) {
			let frees: Vec<String> = record
				.fields
				.iter()
				.enumerate()
				.filter_map(|(n, f)| self.free(&f.ty, &format!("c.f{n}")))
				.collect();
			self.line(format!("fn free_{name}(c: {name}) {{\n\t{}\n}}\n", frees.join("\n\t")));
		}
		self.value_traits(&name, &path, &ty, record.traits);
		let owner = Ty::Struct(name.clone());
		for method in &record.methods {
			self.function(method, Some((&owner, ty.clone())));
		}
	}

	fn enumeration(&mut self, i: usize) {
		let e = &self.abi.api.enums[i];
		let name = self.abi.enumeration(i);
		let path = self.rust(&Type::Enum(i));
		let ty = Type::Enum(i);
		let wildcard = match e.exhaustive {
			true => "",
			false => "\n\t\t_ => unreachable!(\"a variant this export does not know\"),",
		};
		if e.plain() {
			let lift: Vec<String> = e
				.variants
				.iter()
				.map(|v| format!("\n\t\t{} => {path}::{},", v.discriminant, v.name))
				.collect();
			let lower: Vec<String> = e
				.variants
				.iter()
				.map(|v| format!("\n\t\t{path}::{} => {},", v.name, v.discriminant))
				.collect();
			self.line(format!(
				"fn lift_{name}(c: i32, w: &str) -> {path} {{\n\tmatch c {{{}\n\t\t_ => rt::fail(w, \"an enum value is invalid\"),\n\t}}\n}}\n",
				lift.concat()
			));
			self.line(format!(
				"fn lower_{name}(v: {path}) -> i32 {{\n\tmatch v {{{}{wildcard}\n\t}}\n}}\n",
				lower.concat()
			));
		} else {
			let mut members = String::new();
			for (n, variant) in e.variants.iter().enumerate().filter(|(_, v)| !v.fields.is_empty()) {
				let payload = format!("{name}_{}", abi::snake(&variant.name));
				let mut fields = String::new();
				for (k, field) in variant.fields.iter().enumerate() {
					let _ = writeln!(fields, "\tpub f{k}: {},", self.rs(&self.abi.ty(&field.ty)));
				}
				self.line(format!(
					"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {payload} {{\n{fields}}}\n"
				));
				let _ = writeln!(members, "\tpub v{n}: {payload},");
			}
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub union {name}_union {{\n{members}}}\n"
			));
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub tag: i32,\n\tpub u: {name}_union,\n}}\n"
			));
			let mut lift = String::new();
			let mut lower = String::new();
			let mut free = String::new();
			for (n, variant) in e.variants.iter().enumerate() {
				let bindings: Vec<String> = (0..variant.fields.len()).map(|k| format!("f{k}")).collect();
				let pattern = match (variant.fields.is_empty(), variant.tuple) {
					(true, _) => format!("{path}::{}", variant.name),
					(false, true) => format!("{path}::{}({})", variant.name, bindings.join(", ")),
					(false, false) => {
						let fields: Vec<String> = variant
							.fields
							.iter()
							.zip(&bindings)
							.map(|(f, b)| format!("{}: {b}", f.name))
							.collect();
						format!("{path}::{} {{ {} }}", variant.name, fields.join(", "))
					}
				};
				if variant.fields.is_empty() {
					let _ = write!(lift, "\n\t\t{n} => {pattern},");
					let _ = write!(
						lower,
						"\n\t\t{pattern} => {name} {{ tag: {n}, u: unsafe {{ ::std::mem::zeroed() }} }},"
					);
					continue;
				}
				let payload = format!("{name}_{}", abi::snake(&variant.name));
				let lifted: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.map(|(k, f)| self.lift(&f.ty, &format!("p.f{k}")))
					.collect();
				let build = match variant.tuple {
					true => format!("{path}::{}({})", variant.name, lifted.join(", ")),
					false => {
						let fields: Vec<String> = variant
							.fields
							.iter()
							.zip(&lifted)
							.map(|(f, l)| format!("{}: {l}", f.name))
							.collect();
						format!("{path}::{} {{ {} }}", variant.name, fields.join(", "))
					}
				};
				let _ = write!(
					lift,
					"\n\t\t{n} => {{\n\t\t\tlet p = unsafe {{ c.u.v{n} }};\n\t\t\t{build}\n\t\t}}"
				);
				let lowered: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.map(|(k, f)| format!("f{k}: {}", self.lower(&f.ty, &format!("f{k}"))))
					.collect();
				let _ = write!(
					lower,
					"\n\t\t{pattern} => {name} {{ tag: {n}, u: {name}_union {{ v{n}: {payload} {{ {} }} }} }},",
					lowered.join(", ")
				);
				let frees: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.filter_map(|(k, f)| self.free(&f.ty, &format!("p.f{k}")))
					.collect();
				if !frees.is_empty() {
					let _ = write!(
						free,
						"\n\t\t{n} => {{\n\t\t\tlet p = unsafe {{ c.u.v{n} }};\n\t\t\t{}\n\t\t}}",
						frees.join("\n\t\t\t")
					);
				}
			}
			self.line(format!(
				"fn lift_{name}(c: &{name}, w: &str) -> {path} {{\n\tmatch c.tag {{{lift}\n\t\t_ => rt::fail(w, \"an enum tag is invalid\"),\n\t}}\n}}\n"
			));
			self.line(format!(
				"fn lower_{name}(v: {path}) -> {name} {{\n\tmatch v {{{lower}{wildcard}\n\t}}\n}}\n"
			));
			if self.owns(&ty) {
				self.line(format!(
					"fn free_{name}(c: {name}) {{\n\tmatch c.tag {{{free}\n\t\t_ => {{}}\n\t}}\n}}\n"
				));
			}
		}
		self.value_traits(&name, &path, &ty, e.traits);
		let owner = self.abi.ty(&ty);
		for method in &e.methods {
			self.function(method, Some((&owner, ty.clone())));
		}
	}

	/// A callback: its table of foreign functions, and the Rust type that implements the
	/// trait by calling them.
	fn callback(&mut self, i: usize) {
		let callback = &self.abi.api.callbacks[i];
		let name = self.abi.callback(i);
		let path = self.path(&callback.path);
		let mut table = String::from("\tpub free: Option<unsafe extern \"C\" fn(*mut c_void)>,\n");
		let mut methods = String::new();
		for method in &callback.methods {
			let method_name = method.name();
			let c_params: Vec<String> = std::iter::once("*mut c_void".to_string())
				.chain(method.params.iter().map(|p| self.rs(&self.abi.ty(&p.ty))))
				.collect();
			let ret = self.rs(&self.abi.ty(&method.ok));
			let _ = writeln!(
				table,
				"\tpub {method_name}: Option<unsafe extern \"C\" fn({}) -> {ret}>,",
				c_params.join(", ")
			);
			let receiver = match method.receiver {
				Some(Receiver::Mut) => "&mut self",
				_ => "&self",
			};
			let params: Vec<String> = method
				.params
				.iter()
				.enumerate()
				.map(|(n, p)| format!("p{n}: {}", self.rust(&p.ty)))
				.collect();
			let args: Vec<String> = std::iter::once("self.0.data".to_string())
				.chain(
					method
						.params
						.iter()
						.enumerate()
						.map(|(n, p)| self.view(&p.ty, &format!("p{n}"))),
				)
				.collect();
			let _ = write!(
				methods,
				"\tfn {method_name}({receiver}{}) -> {} {{\n\t\tlet w = \"{name}_vtable.{method_name}\";\n\t\tlet f = unsafe {{ (*self.0.vtable).{method_name} }}.unwrap_or_else(|| rt::fail(w, \"the function is null\"));\n\t\tlet result = unsafe {{ f({}) }};\n\t\t{}\n\t}}\n",
				params.iter().map(|p| format!(", {p}")).collect::<String>(),
				self.rust(&method.ok),
				args.join(", "),
				self.lift(&method.ok, "result"),
			);
		}
		self.line(format!("#[repr(C)]\npub struct {name}_vtable {{\n{table}}}\n"));
		self.line(format!(
			"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub vtable: *const {name}_vtable,\n\tpub data: *mut c_void,\n}}\n"
		));
		self.line(format!(
			"/// The foreign implementation, which frees its data when dropped.\npub struct Foreign_{name}({name});\n\n// SAFETY: the callback's contract: its functions may be called from any thread.\nunsafe impl Send for Foreign_{name} {{}}\n// SAFETY: as above.\nunsafe impl Sync for Foreign_{name} {{}}\n\nimpl Drop for Foreign_{name} {{\n\tfn drop(&mut self) {{\n\t\tif let Some(free) = unsafe {{ (*self.0.vtable).free }} {{\n\t\t\tunsafe {{ free(self.0.data) }};\n\t\t}}\n\t}}\n}}\n"
		));
		self.line(format!("impl {path} for Foreign_{name} {{\n{methods}}}\n"));
	}

	/// The C value lending the Rust value `e` of type `ty` to a callback for its call.
	fn view(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Ref(_, inner) => match &**inner {
				Type::Str => format!("rt::Buf::view({e}.as_bytes())"),
				Type::Path => format!("rt::Buf::view({e}.as_os_str().as_encoded_bytes())"),
				_ => format!("rt::Buf::view({e})"),
			},
			Type::String => format!("rt::Buf::view({e}.as_bytes())"),
			Type::Vec | Type::Bytes => format!("rt::Buf::view(&{e}[..])"),
			Type::PathBuf => format!("rt::Buf::view({e}.as_os_str().as_encoded_bytes())"),
			Type::Option(inner) => match &**inner {
				inner if Abi::is_buf(inner) => format!(
					"match &{e} {{ Some(v) => {}, None => rt::Buf::NONE }}",
					self.view(inner, "v")
				),
				inner => format!(
					"match {e} {{ Some(v) => {name} {{ some: true, value: {} }}, None => {name} {{ some: false, value: unsafe {{ ::std::mem::zeroed() }} }} }}",
					self.view(inner, "v"),
					name = self.abi.option(inner)
				),
			},
			_ => self.lower(ty, e),
		}
	}

	/// An argument: the statement binding it from its C parameter `c` to `local`, and
	/// the expression passing it. A future owns its arguments, so it borrows nothing
	/// from the caller.
	fn arg(&self, ty: &Type, c: &str, local: &str, future: bool) -> (String, String) {
		match ty {
			Type::Ref(m, inner) => match (&**inner, m, future) {
				(Type::Object(i), _, _) => {
					let sync = self.abi.api.objects[*i].sync;
					// A future may be polled on any thread, so it holds a value that is not
					// `Sync` exclusively.
					let exclusive = *m == Mutability::Mut || (future && !sync);
					let borrow = match (exclusive, future) {
						(false, false) => self.shared(*i),
						(true, false) => "borrow_mut",
						(false, true) => "borrow_arc",
						(true, true) => "borrow_mut_arc",
					};
					let binding = match exclusive {
						true => "let mut",
						false => "let",
					};
					let pass = match m {
						Mutability::Mut => format!("&mut *{local}"),
						Mutability::Not => format!("&*{local}"),
					};
					(
						format!(
							"{binding} {local} = unsafe {{ rt::Object::<{}>::{borrow}({c}, w) }};",
							self.object_path(*i)
						),
						pass,
					)
				}
				(Type::Str, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.str(w) }};"), local.to_string())
				}
				(Type::Slice, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.bytes(w) }};"), local.to_string())
				}
				(Type::Path, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.path(w) }};"), local.to_string())
				}
				(inner, m, _) => {
					let (binding, pass) = match m {
						Mutability::Mut => ("let mut", format!("&mut {local}")),
						Mutability::Not => ("let", format!("&{local}")),
					};
					(format!("{binding} {local} = {};", self.lift(inner, c)), pass)
				}
			},
			_ => (format!("let {local} = {};", self.lift(ty, c)), local.to_string()),
		}
	}

	/// The out pointers a call's value is written through: one per element of a tuple.
	fn outs(function: &Function) -> Vec<String> {
		match &function.ok {
			Type::Unit => Vec::new(),
			Type::Tuple(elements) => (0..elements.len()).map(|n| format!("out{n}")).collect(),
			_ => vec!["out".to_string()],
		}
	}

	/// The statements that hand a call's `result` to C: return it, or for a fallible
	/// function or a tuple, write it through its out pointers or `err`, and return whether
	/// it succeeded.
	fn finish(&self, function: &Function, ret: (&str, &str, &str)) -> String {
		let (ok_value, ready, error) = ret;
		let write = |ty: &Type, out: &str, v: &str| {
			format!(
				"unsafe {{ rt::write::<{}>({out}.cast(), || {}) }};",
				self.rs(&self.abi.ty(ty)),
				self.lower(ty, v)
			)
		};
		let write_ok = match &function.ok {
			Type::Unit => String::new(),
			Type::Tuple(elements) => {
				let names: Vec<String> = (0..elements.len()).map(|n| format!("v{n}")).collect();
				let writes: Vec<String> = elements
					.iter()
					.zip(Self::outs(function))
					.zip(&names)
					.map(|((ty, out), v)| write(ty, &out, v))
					.collect();
				// The trailing comma makes `(v0,)` a tuple pattern, not parentheses.
				format!("let ({},) = v;\n\t{}", names.join(", "), writes.join("\n\t"))
			}
			ok => write(ok, "out", "v"),
		};
		match &function.err {
			None if ok_value.is_empty() => match function.ok {
				Type::Unit => "result".to_string(),
				Type::Tuple(_) => format!("let v = result;\n\t{write_ok}"),
				_ => self.lower(&function.ok, "result"),
			},
			None => match function.ok {
				Type::Unit => format!("let _ = result;\n\t{ready}"),
				_ => format!("let v = result;\n\t{write_ok}\n\t{ready}"),
			},
			Some(err) => format!(
				"match result {{\n\t\tOk(v) => {{\n\t\t\tlet _ = &v;\n\t\t\t{write_ok}\n\t\t\t{ready}\n\t\t}}\n\t\tErr(e) => {{\n\t\t\tunsafe {{ rt::write::<{}>(err.cast(), || {}) }};\n\t\t\t{error}\n\t\t}}\n\t}}",
				self.rs(&self.abi.ty(err)),
				self.lower(err, "e")
			),
		}
	}

	/// An exported function, a method of `owner` if it has one: its C type, and its type.
	fn function(&mut self, function: &Function, owner: Option<(&Ty, Type)>) {
		let export = self.abi.export(function, owner.as_ref().map(|(ty, _)| *ty));
		let name = export.call.name.clone();
		// An eager call borrows its arguments only for the call, as a synchronous one does.
		let future = function.future && !function.eager;
		let mut stmts = Vec::new();
		let mut args = Vec::new();
		let mut params = Vec::new();
		let mut c_params = export.call.params.iter();
		let receiver_ty = owner.as_ref().zip(function.receiver);
		if let Some(((_, owner_type), receiver)) = &receiver_ty {
			let (_, c_ty) = c_params.next().expect("a method takes self");
			params.push(format!("this: {}", self.rs(c_ty)));
			match owner_type {
				Type::Object(i) => {
					let ty = match receiver {
						Receiver::Ref => Type::Ref(Mutability::Not, Box::new(Type::Object(*i))),
						Receiver::Mut => Type::Ref(Mutability::Mut, Box::new(Type::Object(*i))),
						Receiver::Owned => Type::Object(*i),
					};
					let (stmt, arg) = self.arg(&ty, "this", "a_self", future);
					stmts.push(stmt);
					args.push(arg);
				}
				value => {
					stmts.push(format!("let a_self = {};", self.lift(value, "unsafe { *this }")));
					args.push(match receiver {
						Receiver::Owned => "a_self".to_string(),
						_ => "&a_self".to_string(),
					});
				}
			}
		}
		for (n, param) in function.params.iter().enumerate() {
			let (_, c_ty) = c_params.next().expect("a C parameter for each");
			params.push(format!("p{n}: {}", self.rs(c_ty)));
			if let Type::Closure(..) = param.ty {
				let (_, data) = c_params.next().expect("a lent function's data");
				params.push(format!("p{n}_data: {}", self.rs(data)));
			}
			let (stmt, arg) = self.arg(&param.ty, &format!("p{n}"), &format!("a{n}"), future);
			stmts.push(stmt);
			args.push(arg);
		}
		let mut callee = match &owner {
			Some((_, owner_type)) => format!("<{}>::{}", self.rust(owner_type), function.name()),
			None => self.path(&function.path),
		};
		if let Some(instance) = function.instance.as_ref().filter(|i| !i.args.is_empty()) {
			let args: Vec<String> = (instance.args.iter())
				.map(|ty| ty.as_ref().map_or_else(|| "_".to_string(), |ty| self.rust(ty)))
				.collect();
			callee = format!("{callee}::<{}>", args.join(", "));
		}
		let call = match function.access {
			Access::Call => format!("{callee}({})", args.join(", ")),
			Access::Field { set: false, .. } => format!("&({}).{}", args[0], function.name()),
			Access::Field { set: true, .. } => format!("({}).{} = {}", args[0], function.name(), args[1]),
			Access::Const => callee,
			Access::Parse => format!(
				"<{} as ::std::str::FromStr>::from_str({}).map_err(|e| ::std::string::ToString::to_string(&e))",
				self.rust(&owner.as_ref().expect("a parse has its type").1),
				args[0]
			),
			Access::Text => format!("::std::string::ToString::to_string({})", args[0]),
		};
		let body = stmts.join("\n\t");
		if let Some((_, poll, free)) = &export.future {
			// A function that is not `async` runs when called, and what it returns
			// borrows nothing, so it is called now; an `async fn` runs when polled.
			let (now, later) = match function.eager {
				true => (format!("\n\tlet future = {call};"), "future".to_string()),
				false => (String::new(), call),
			};
			let bind: String = Self::outs(function)
				.iter()
				.enumerate()
				.map(|(n, out)| format!("let {out} = outs[{n}];\n\t\t\t"))
				.collect();
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({}) -> *mut rt::Future {{\n\tlet w = \"{name}\";\n\tlet _ = w;\n\t{body}{now}\n\trt::Future::new(async move {{\n\t\tlet result = {later}.await;\n\t\t::std::boxed::Box::new(move |outs: &[*mut c_void], err: *mut c_void| -> i32 {{\n\t\t\tlet _ = (outs, err);\n\t\t\t{bind}{}\n\t\t}}) as rt::Done\n\t}})\n}}\n",
				params.join(", "),
				self.finish(function, ("v", "rt::READY", "rt::ERROR"))
			));
			let poll_params: Vec<String> = poll.params[2..]
				.iter()
				.map(|(n, ty)| format!("{n}: {}", self.rs(ty)))
				.collect();
			let outs: Vec<String> = Self::outs(function).iter().map(|out| format!("{out}.cast()")).collect();
			let outs = outs.join(", ");
			let err = match function.err {
				Some(_) => "err.cast()",
				None => "::std::ptr::null_mut()",
			};
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(future: *mut rt::Future, waker: rt::Waker{}) -> i32 {{\n\tunsafe {{ rt::Future::poll(future, waker, &[{outs}], {err}, \"{}\") }}\n}}\n",
				poll.name,
				poll_params.iter().map(|p| format!(", {p}")).collect::<String>(),
				poll.name
			));
			self.line(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(future: *mut rt::Future) {{\n\tunsafe {{ rt::Future::free(future) }}\n}}\n",
				free.name
			));
			return;
		}
		let outs: Vec<String> = export.call.params[params.len()..]
			.iter()
			.map(|(n, ty)| format!("{n}: {}", self.rs(ty)))
			.collect();
		params.extend(outs);
		let ret = self.rs(&export.call.ret);
		let finish = match function.err {
			Some(_) => self.finish(function, ("v", "true", "false")),
			None => self.finish(function, ("", "", "")),
		};
		self.line(format!(
			"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({}) -> {ret} {{\n\tlet w = \"{name}\";\n\tlet _ = w;\n\t{body}\n\tlet result = {};\n\t{finish}\n}}\n",
			params.join(", "),
			match function.collect {
				// An iterator's items, all taken now.
				true => format!("::std::iter::Iterator::collect::<::std::vec::Vec<_>>({call})"),
				false => call,
			},
		));
	}
}
