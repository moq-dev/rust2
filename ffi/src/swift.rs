//! Swift over the C ABI: `swift/<prefix>.swift`, which imports the C header as the clang
//! module `swift/module.modulemap` declares, beside the atomics its runtime needs.
//!
//! Each name is its C name without the prefix, as Swift spells it: `moq_track_producer`
//! is `TrackProducer`, and its method `moq_track_producer_append_group` is
//! `TrackProducer.appendGroup`. A keyword is quoted in backticks, and a member named as one
//! Swift gives its type takes a trailing `_`. An object is a final class owning its handle,
//! freed in `deinit` or sooner by `close`; a record a struct; an enum a Swift enum, with
//! its data as associated values; a trait a protocol; a closure a function type; a future
//! an `async` function; an error a thrown `Swift.Error`. The runtime they share,
//! [`runtime/rt.swift`](../runtime/rt.swift), holds the handles, the arena a call lowers
//! nested values into, and the signal a future parks on.
//!
//! A call passes bytes and text at its top level as views of Swift's own memory, and
//! returned bytes are `Data` lending Rust's buffer, so neither is copied; nested in another
//! value, bytes passed in are copied into the call's arena.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use crate::abi::{self, Abi, Ty};
use crate::ir::{Access, Function, Int, Literal, Receiver, Type};

const RUNTIME: &str = include_str!("../runtime/rt.swift");

/// What the generator writes: the Swift file, the clang module map it imports the C
/// header through, and the header of atomics that module adds.
pub struct Output {
	pub swift: String,
	pub modulemap: String,
	pub atomics: String,
}

/// The name of the clang module of the C header: `api` is `ApiFFI`.
pub fn module(prefix: &str) -> String {
	format!("{}FFI", pascal(prefix))
}

/// The Swift for `abi`, whose header's contract is `contract`, or the names two items
/// claim alike.
pub fn generate(abi: &Abi<'_>, packages: &str, contract: u64) -> Result<Output, String> {
	let mut g = Gen {
		abi,
		types: String::new(),
		top: String::new(),
		natives: String::new(),
		names: BTreeMap::new(),
		errors: Vec::new(),
		thrown: BTreeMap::new(),
		conforms: BTreeSet::new(),
		fresh: 0,
	};
	g.write();
	if !g.errors.is_empty() {
		return Err(g.errors.join("\n"));
	}
	let p = &abi.prefix;
	let upper = p.to_uppercase();
	let module = module(p);
	let mut swift = format!(
		"// Generated by rust2-ffi: Swift over the C ABI of the pub API of {packages}. Do not edit.\n\n\
		#if canImport(FoundationEssentials)\nimport FoundationEssentials\n#else\nimport Foundation\n#endif\nimport {module}\n\n"
	);
	let _ = write!(
		swift,
		"/// The runtime, and its names for the export's C types and functions.\nenum Native {{\n\
		\tstatic let file = \"{p}.swift\"\n\n\
		\ttypealias Buf = {p}_buf\n\
		\ttypealias CWaker = {p}_waker\n\
		\ttypealias CDuration = {p}_duration\n\
		\ttypealias CAddr = {p}_socket_addr\n\n\
		\tstatic func contract() -> Swift.Bool {{\n\t\t{p}_contract() == 0x{contract:016x} && {upper}_CONTRACT == 0x{contract:016x}\n\t}}\n\n\
		\tstatic func free(_ buf: Buf) {{\n\t\t{p}_buf_free(buf)\n\t}}\n\n\
		\tstatic func load(_ state: UnsafeMutablePointer<Swift.Int>) -> Swift.Int {{\n\t\t{p}_atomic_load(state)\n\t}}\n\n\
		\tstatic func store(_ state: UnsafeMutablePointer<Swift.Int>, _ value: Swift.Int) {{\n\t\t{p}_atomic_store(state, value)\n\t}}\n\n\
		\tstatic func add(_ state: UnsafeMutablePointer<Swift.Int>, _ value: Swift.Int) -> Swift.Int {{\n\t\t{p}_atomic_add(state, value)\n\t}}\n\n\
		\tstatic func exchange(_ state: UnsafeMutablePointer<Swift.Int>, _ value: Swift.Int) -> Swift.Int {{\n\t\t{p}_atomic_exchange(state, value)\n\t}}\n\n\
		\t/// Set `state` to `new` if it is `old`, returning what it was.\n\
		\tstatic func swap(_ state: UnsafeMutablePointer<Swift.Int>, _ old: Swift.Int, _ new: Swift.Int) -> Swift.Int {{\n\t\t{p}_atomic_cas(state, old, new)\n\t}}\n}}\n\n"
	);
	swift.push_str(RUNTIME);
	swift.push('\n');
	swift.push_str(&g.types);
	swift.push_str(&g.top);
	if !g.natives.is_empty() {
		let _ = write!(swift, "extension Native {{\n{}}}\n", g.natives);
	}
	while swift.ends_with("\n\n") {
		swift.pop();
	}
	let modulemap = format!(
		"// Generated by rust2-ffi: the C ABI of {packages} as a clang module, which {p}.swift imports. Do not edit.\n\n\
		module {module} {{\n\theader \"../include/{p}.h\"\n\theader \"{p}_atomics.h\"\n\texport *\n}}\n"
	);
	let atomics = format!(
		"/* Generated by rust2-ffi: the atomics {p}.swift's runtime uses, which Swift's standard\n * library lacks before macOS 15 and iOS 18. Do not edit. */\n\n\
		#ifndef {upper}_ATOMICS_H\n#define {upper}_ATOMICS_H\n\n#include <stdint.h>\n\n\
		static inline intptr_t {p}_atomic_load(const intptr_t *p) {{\n\treturn __atomic_load_n(p, __ATOMIC_ACQUIRE);\n}}\n\n\
		static inline void {p}_atomic_store(intptr_t *p, intptr_t v) {{\n\t__atomic_store_n(p, v, __ATOMIC_RELEASE);\n}}\n\n\
		static inline intptr_t {p}_atomic_add(intptr_t *p, intptr_t v) {{\n\treturn __atomic_add_fetch(p, v, __ATOMIC_ACQ_REL);\n}}\n\n\
		static inline intptr_t {p}_atomic_exchange(intptr_t *p, intptr_t v) {{\n\treturn __atomic_exchange_n(p, v, __ATOMIC_ACQ_REL);\n}}\n\n\
		static inline intptr_t {p}_atomic_cas(intptr_t *p, intptr_t old, intptr_t new_) {{\n\t__atomic_compare_exchange_n(p, &old, new_, 0, __ATOMIC_ACQ_REL, __ATOMIC_ACQUIRE);\n\treturn old;\n}}\n\n\
		#endif\n"
	);
	Ok(Output {
		swift: swift + "\n",
		modulemap,
		atomics,
	})
}

/// The names the generated code uses unqualified, which no exported type or function may
/// take. The runtime's own are the C ABI's: `Native` and `SocketAddr` are claimed as
/// `<prefix>_native` and `<prefix>_socket_addr`.
const TAKEN: &[&str] = &[
	"Data",
	"Int",
	"UInt",
	"UInt8",
	"Bool",
	"Void",
	"Never",
	"Array",
	"Optional",
	"OpaquePointer",
	"UnsafePointer",
	"UnsafeMutablePointer",
	"UnsafeBufferPointer",
	"UnsafeRawBufferPointer",
	"UnsafeMutableRawPointer",
	"Unmanaged",
	"ManagedBuffer",
	"UnsafeContinuation",
	"StaticString",
	"Sendable",
	"Equatable",
	"CustomStringConvertible",
	"CustomDebugStringConvertible",
	"Task",
	"fatalError",
];

/// One parameter, as the call passes it: the closure it runs inside, holding what it
/// passes until it returns, the C arguments, and what closes once the call returns.
#[derive(Default)]
struct Arg {
	open: Option<(String, String)>,
	exprs: Vec<String>,
	after: Vec<String>,
}

struct Gen<'a> {
	abi: &'a Abi<'a>,
	/// The types, then the top-level functions and constants, then `Native`'s additions.
	types: String,
	top: String,
	natives: String,
	/// Each top-level Swift name, with what claimed it.
	names: BTreeMap<String, String>,
	errors: Vec<String>,
	/// The struct each error type that is no exported type throws as, by name.
	thrown: BTreeMap<String, Type>,
	/// The exported types thrown as errors, which conform to `Swift.Error`.
	conforms: BTreeSet<String>,
	fresh: usize,
}

impl<'a> Gen<'a> {
	fn fresh(&mut self, base: &str) -> String {
		self.fresh += 1;
		format!("{base}{}_", self.fresh)
	}

	/// A C name without the prefix.
	fn bare<'n>(&self, c: &'n str) -> &'n str {
		&c[self.abi.prefix.len() + 1..]
	}

	/// The Swift name of the C type `c`.
	fn class(&self, c: &str) -> String {
		pascal(self.bare(c))
	}

	/// Claim the top-level Swift name `name` for `what`.
	fn claim(&mut self, name: &str, what: String) {
		if TAKEN.contains(&name) {
			self.errors.push(format!(
				"{what} is `{name}` in Swift, which its runtime names: rename it in the config"
			));
		} else if let Some(first) = self.names.insert(name.to_string(), what.clone()) {
			self.errors.push(format!(
				"{first} and {what} are both `{name}` in Swift: rename one in the config"
			));
		}
	}

	/// Check that no two members of the type `rust` share a Swift name.
	fn distinct(&mut self, rust: &str, members: &[String]) {
		let mut seen = BTreeSet::new();
		for member in members {
			if !seen.insert(member) {
				self.errors.push(format!(
					"two members of `{rust}` are both `{member}` in Swift: rename one in the config"
				));
			}
		}
	}

	/// The Swift type of `ty`, as a value, a parameter, or a result.
	fn sw(&self, ty: &Type) -> String {
		let abi = self.abi;
		match ty {
			Type::Unit => "Void".to_string(),
			Type::Bool => "Swift.Bool".to_string(),
			Type::Int(int) => sw_int(*int).to_string(),
			Type::F32 => "Swift.Float".to_string(),
			Type::F64 => "Swift.Double".to_string(),
			Type::Char => "Swift.Unicode.Scalar".to_string(),
			Type::Str | Type::String | Type::Path | Type::PathBuf => "Swift.String".to_string(),
			Type::Slice | Type::Vec | Type::Bytes => "Data".to_string(),
			Type::Duration => "Swift.Duration".to_string(),
			Type::SocketAddr(_) => "SocketAddr".to_string(),
			Type::List(inner) => format!("[{}]", self.sw(inner)),
			Type::Waker => "@escaping @Sendable () -> Void".to_string(),
			Type::Option(inner) => format!("{}?", self.sw(inner)),
			Type::Box(inner) | Type::Ref(_, inner) => self.sw(inner),
			Type::Record(i) => self.class(&abi.record(*i)),
			Type::Enum(i) => self.class(&abi.enumeration(*i)),
			Type::Object(i) => self.class(&abi.object(*i)),
			Type::Callback(i, _) => format!("any {}", self.class(&abi.callback(*i))),
			Type::Closure(params, ret) => {
				let params: Vec<String> = params.iter().map(|p| self.sw(p)).collect();
				format!("@Sendable ({}) -> {}", params.join(", "), self.sw(ret))
			}
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => self.class(&abi.range(ty)),
			Type::Tuple(elements) => match &elements[..] {
				// Swift has no tuple of one: it is its element, which loses nothing.
				[element] => self.sw(element),
				elements => {
					let elements: Vec<String> = elements.iter().map(|e| self.sw(e)).collect();
					format!("({})", elements.join(", "))
				}
			},
		}
	}

	/// The Swift spelling of a C type, for a local the call writes.
	fn c_sw(&self, ty: &Ty) -> String {
		let abi = self.abi;
		match ty {
			Ty::Bool => "Swift.Bool".to_string(),
			Ty::Int(int) => c_int(*int).to_string(),
			Ty::F32 => "Swift.Float".to_string(),
			Ty::F64 => "Swift.Double".to_string(),
			Ty::Char => "Swift.UInt32".to_string(),
			Ty::Buf => abi.rt("buf"),
			Ty::Duration => abi.rt("duration"),
			Ty::SocketAddr => abi.rt("socket_addr"),
			Ty::Struct(n) | Ty::Enum(n) => n.clone(),
			Ty::Handle { .. } | Ty::Future(_) => "OpaquePointer?".to_string(),
			Ty::Waker => abi.rt("waker"),
			other => unreachable!("no local is {other:?}"),
		}
	}

	/// The zero a local of C type `ty` starts as.
	fn zero(&self, ty: &Ty) -> String {
		match ty {
			Ty::Bool => "false".to_string(),
			Ty::Int(_) | Ty::F32 | Ty::F64 | Ty::Char => "0".to_string(),
			Ty::Handle { .. } | Ty::Future(_) => "nil".to_string(),
			Ty::Enum(n) => format!("{n}(rawValue: 0)"),
			other => format!("{}()", self.c_sw(other)),
		}
	}

	/// Whether lowering a `ty` nested in another value needs the call's arena: to copy
	/// bytes, build an array, or hold a handle.
	fn arena(&self, ty: &Type) -> bool {
		let api = self.abi.api;
		match ty {
			ty if Abi::is_buf(ty) => true,
			Type::List(_) | Type::Object(_) => true,
			Type::Option(inner) | Type::Box(inner) | Type::Ref(_, inner) => self.arena(inner),
			Type::Tuple(elements) => elements.iter().any(|e| self.arena(e)),
			Type::Record(i) => api.records[*i].fields.iter().any(|f| self.arena(&f.ty)),
			Type::Enum(i) => (api.enums[*i].variants.iter()).any(|v| v.fields.iter().any(|f| self.arena(&f.ty))),
			_ => false,
		}
	}

	/// The arena argument a value's `_lower` takes, if it needs one.
	fn arena_arg(&self, ty: &Type) -> &'static str {
		match self.arena(ty) {
			true => "a_",
			false => "",
		}
	}

	/// The C value of the Swift value `e` of type `ty`, nested in a value the call passes:
	/// bytes copied into the arena `a_`, and handles held by it.
	fn lower(&mut self, ty: &Type, e: &str) -> String {
		let abi = self.abi;
		if Abi::is_buf(ty) {
			return format!("a_.buf({e})");
		}
		match ty {
			Type::Unit => unreachable!("no value is unit"),
			Type::Bool | Type::F32 | Type::F64 => e.to_string(),
			Type::Int(Int::Usize) => format!("Swift.Int(bitPattern: {e})"),
			Type::Int(_) => e.to_string(),
			Type::Char => format!("{e}.value"),
			Type::Duration => format!("Native.duration({e})"),
			Type::SocketAddr(_) => format!("Native.socketAddr({e})"),
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => format!("{e}._lower()"),
			Type::Waker => format!("Native.waker({e})"),
			Type::List(inner) => {
				let x = self.fresh("x");
				let item = self.lower(inner, &x);
				format!(
					"Native.vec(a_.list({e}) {{ {x} in {item} }}, {}.init(ptr:len:owner:))",
					abi.list(inner)
				)
			}
			Type::Option(inner) => match inner.base() {
				Type::Object(_) => format!("a_.hold({e}?.handle)"),
				_ if Abi::is_buf(inner) => format!("a_.buf({e})"),
				Type::List(elem) => {
					let v = self.fresh("v");
					let some = self.lower(inner, &v);
					format!("({e}.map {{ {v} in {some} }} ?? {}())", abi.list(elem))
				}
				_ => {
					let c = abi.option(inner);
					let v = self.fresh("v");
					let some = self.lower(inner, &v);
					format!("({e}.map {{ {v} in {c}(some: true, value: {some}) }} ?? {c}())")
				}
			},
			Type::Box(inner) | Type::Ref(_, inner) => self.lower(inner, e),
			Type::Record(_) | Type::Enum(_) => format!("{e}._lower({})", self.arena_arg(ty)),
			Type::Object(_) => format!("a_.hold({e}.handle)"),
			Type::Callback(i, _) => format!("Native.lower_{}({e})", abi.callback(*i)),
			Type::Tuple(elements) => {
				let c = abi.tuple(elements);
				let fields: Vec<String> = match &elements[..] {
					[element] => vec![format!("_0: {}", self.lower(element, e))],
					elements => (elements.iter().enumerate())
						.map(|(n, ty)| format!("_{n}: {}", self.lower(ty, &format!("{e}.{n}"))))
						.collect(),
				};
				format!("{c}({})", fields.join(", "))
			}
			Type::Closure(..) => unreachable!("a closure lowers to its trampoline"),
			_ => unreachable!("a buffer is above"),
		}
	}

	/// The Swift value of the C value `e` of type `ty`, which it takes ownership of. `e`
	/// is named, so it may be read more than once.
	fn lift(&mut self, ty: &Type, e: &str) -> String {
		let abi = self.abi;
		match ty {
			Type::Str | Type::String => format!("Native.string({e})"),
			Type::Path | Type::PathBuf => format!("Native.path({e})"),
			Type::Slice | Type::Vec | Type::Bytes => format!("Native.data({e})"),
			Type::Bool | Type::F32 | Type::F64 => e.to_string(),
			Type::Int(Int::Usize) => format!("Swift.UInt(bitPattern: {e})"),
			Type::Int(_) => e.to_string(),
			Type::Char => format!("Native.scalar({e})"),
			Type::Duration => format!("Native.duration({e})"),
			Type::SocketAddr(_) => format!("Native.socketAddr({e})"),
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => format!("{}._lift({e})", self.sw(ty)),
			Type::List(inner) => {
				let (v, c) = (self.fresh("v"), self.fresh("c"));
				let item = self.lift(inner, &c);
				format!(
					"{{ () -> {} in var {v} = {e}; defer {{ {v}.len = 0; {}_free({v}) }}; return Native.list({v}.ptr, {v}.len) {{ {c} in {item} }} }}()",
					self.sw(ty),
					abi.list(inner)
				)
			}
			Type::Option(inner) => match inner.base() {
				Type::Object(_) => format!("{e}.map {{ {}(raw: $0) }}", self.sw(inner)),
				Type::Str | Type::String => format!("Native.string(option: {e})"),
				Type::Path | Type::PathBuf => format!("Native.path(option: {e})"),
				Type::Slice | Type::Vec | Type::Bytes => format!("Native.data(option: {e})"),
				Type::List(_) => format!(
					"({e}.ptr == nil ? nil : {} as {}?)",
					self.lift(inner, e),
					self.sw(inner)
				),
				_ => format!(
					"({e}.some ? {} as {}? : nil)",
					self.lift(inner, &format!("{e}.value")),
					self.sw(inner)
				),
			},
			Type::Box(inner) | Type::Ref(_, inner) => self.lift(inner, e),
			Type::Record(_) | Type::Enum(_) => format!("{}._lift({e})", self.sw(ty)),
			Type::Object(_) => format!("{}(raw: {e})", self.sw(ty)),
			Type::Tuple(elements) => match &elements[..] {
				[element] => self.lift(element, &format!("{e}._0")),
				elements => {
					let lifted: Vec<String> = (elements.iter().enumerate())
						.map(|(n, ty)| self.lift(ty, &format!("{e}._{n}")))
						.collect();
					format!("({})", lifted.join(", "))
				}
			},
			other => unreachable!("{other:?} is never returned"),
		}
	}

	/// The Swift value of the C value `e` of type `ty`, which C lends a callback or closure
	/// for its call: bytes and text copied, and a scalar as it is.
	fn lift_lent(&mut self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Str | Type::String | Type::Path | Type::PathBuf => format!("Native.string(lent: {e})"),
			Type::Slice | Type::Vec | Type::Bytes => format!("Native.data(lent: {e})"),
			Type::Option(inner) => match inner.base() {
				Type::Str | Type::String | Type::Path | Type::PathBuf => format!("Native.string(lentOption: {e})"),
				Type::Slice | Type::Vec | Type::Bytes => format!("Native.data(lentOption: {e})"),
				_ => self.lift(ty, e),
			},
			Type::Ref(_, inner) => self.lift_lent(inner, e),
			ty => self.lift(ty, e),
		}
	}

	fn write(&mut self) {
		let abi = self.abi;
		let api = abi.api;
		for (c, ty) in &abi.ranges.clone() {
			self.range(c, ty);
		}
		for constant in &api.constants {
			let name = self.bare(&abi.name(&constant.path)).to_uppercase();
			self.claim(&name, format!("const `{}`", constant.path.join("::")));
			let (ty, value) = match constant.value {
				Literal::Bool(b) => ("Swift.Bool".to_string(), b.to_string()),
				Literal::Int(int, v) => (sw_int(int).to_string(), v.to_string()),
			};
			let _ = write!(
				self.top,
				"{}public let {name}: {ty} = {value}\n\n",
				docs(&constant.docs, "")
			);
		}
		for i in 0..api.records.len() {
			self.record(i);
		}
		for i in 0..api.enums.len() {
			self.enumeration(i);
		}
		for i in 0..api.objects.len() {
			self.object(i);
		}
		for i in 0..api.callbacks.len() {
			self.callback(i);
		}
		for function in &api.functions {
			if let Some((code, name)) = self.function(function, None, None) {
				self.claim(&name, format!("fn `{}`", function.path.join("::")));
				self.top.push_str(&code);
				self.top.push('\n');
			}
		}
		for (name, ty) in &self.thrown.clone() {
			let sw = self.sw(ty);
			let _ = write!(
				self.types,
				"/// A `{}` Rust returned as an error.\npublic struct {name}: Swift.Error, CustomStringConvertible {{\n\tpublic let error: {sw}\n\n\tpublic var description: Swift.String {{\n\t\t\"\\(error)\"\n\t}}\n}}\n\n",
				sw.trim_start_matches("Swift.")
			);
		}
		for name in &self.conforms.clone() {
			let _ = write!(self.types, "extension {name}: Swift.Error {{}}\n\n");
		}
	}

	/// A struct for a range or pair of bounds, or an enum for a bound, and its conversions.
	fn range(&mut self, c: &str, ty: &Type) {
		let name = self.class(c);
		self.claim(&name, format!("`{c}`"));
		let p = &self.abi.prefix;
		let upper = format!("{}_BOUND", p.to_uppercase());
		let code = match ty {
			Type::Range(int) => {
				let sw = sw_int(*int);
				let lower = |e: &str| self_lower_int(*int, e);
				let lift = |e: &str| self_lift_int(*int, e);
				format!(
					"/// Rust's `Range`: from `start`, up to but not including `end`.\npublic struct {name}: Hashable, Sendable {{\n\tpublic var start: {sw}\n\tpublic var end: {sw}\n\n\tpublic init(start: {sw}, end: {sw}) {{\n\t\tself.start = start\n\t\tself.end = end\n\t}}\n\n\tstatic func _lift(_ c: {c}) -> {name} {{\n\t\t{name}(start: {}, end: {})\n\t}}\n\n\tfunc _lower() -> {c} {{\n\t\t{c}(start: {}, end: {})\n\t}}\n}}\n\n",
					lift("c.start"),
					lift("c.end"),
					lower("start"),
					lower("end"),
				)
			}
			Type::Bound(int) => {
				let sw = sw_int(*int);
				format!(
					"/// Rust's `Bound`: what a range's start or end bound does.\npublic enum {name}: Hashable, Sendable {{\n\tcase unbounded\n\tcase included({sw})\n\tcase excluded({sw})\n\n\tstatic func _lift(_ c: {c}) -> {name} {{\n\t\tswitch c.kind {{\n\t\tcase {upper}_UNBOUNDED: return .unbounded\n\t\tcase {upper}_INCLUDED: return .included({})\n\t\tcase {upper}_EXCLUDED: return .excluded({})\n\t\tdefault: fatalError(\"{c}: a bound's kind is invalid\")\n\t\t}}\n\t}}\n\n\tfunc _lower() -> {c} {{\n\t\tswitch self {{\n\t\tcase .unbounded: return {c}(kind: {upper}_UNBOUNDED, value: 0)\n\t\tcase .included(let value): return {c}(kind: {upper}_INCLUDED, value: {})\n\t\tcase .excluded(let value): return {c}(kind: {upper}_EXCLUDED, value: {})\n\t\t}}\n\t}}\n}}\n\n",
					self_lift_int(*int, "c.value"),
					self_lift_int(*int, "c.value"),
					self_lower_int(*int, "value"),
					self_lower_int(*int, "value"),
				)
			}
			Type::Bounds(int) => {
				let bound = self.class(&self.abi.range(&Type::Bound(*int)));
				format!(
					"/// A range's start and end bounds, as Rust's `RangeBounds` gives them.\npublic struct {name}: Hashable, Sendable {{\n\tpublic var start: {bound}\n\tpublic var end: {bound}\n\n\tpublic init(start: {bound}, end: {bound}) {{\n\t\tself.start = start\n\t\tself.end = end\n\t}}\n\n\tstatic func _lift(_ c: {c}) -> {name} {{\n\t\t{name}(start: {bound}._lift(c.start), end: {bound}._lift(c.end))\n\t}}\n\n\tfunc _lower() -> {c} {{\n\t\t{c}(start: start._lower(), end: end._lower())\n\t}}\n}}\n\n"
				)
			}
			other => unreachable!("{other:?} is no range"),
		};
		self.types.push_str(&code);
	}

	/// The members a type's std traits export, with the protocols they conform it to:
	/// `Display` is `description`, `Debug` `debugDescription`, `PartialEq` `==`, `Default`
	/// a static `default()`, and `Clone` an object's `clone()`.
	fn traits(
		&mut self,
		ty: &Type,
		c: &str,
		t: crate::ir::Traits,
		body: &mut Vec<String>,
		members: &mut Vec<String>,
		protocols: &mut Vec<&'static str>,
	) {
		let name = self.sw(ty);
		let object = matches!(ty, Type::Object(_));
		// The receiver: a held handle, or the value lowered.
		let (open, this, close) = match object {
			true => ("self.handle.with { h_ in ".to_string(), "h_", " }"),
			false => {
				let arena = match self.arena(ty) {
					true => "let a_ = Native.Arena()\n\t\tdefer { a_.finish() }\n\t\t",
					false => "",
				};
				(
					format!(
						"Native.check()\n\t\t{arena}var c_ = self._lower({})\n\t\treturn ",
						self.arena_arg(ty)
					),
					"&c_",
					"",
				)
			}
		};
		let text = |open: &str, call: &str| match object {
			true => format!("Native.string({open}{call}{close})"),
			false => format!("{open}Native.string({call})"),
		};
		if t.display {
			protocols.push("CustomStringConvertible");
			members.push("description".to_string());
			body.push(format!(
				"\tpublic var description: Swift.String {{\n\t\t{}\n\t}}\n",
				text(&open, &format!("{c}_to_string({this})"))
			));
		}
		if t.debug {
			protocols.push("CustomDebugStringConvertible");
			members.push("debugDescription".to_string());
			body.push(format!(
				"\t/// Rust's `Debug` form.\n\tpublic var debugDescription: Swift.String {{\n\t\t{}\n\t}}\n",
				text(&open, &format!("{c}_debug({this})"))
			));
		}
		if object && t.clone {
			members.push("clone".to_string());
			body.push(format!(
				"\t/// A new handle to a clone.\n\tpublic func clone() -> {name} {{\n\t\t{name}(raw: self.handle.with {{ {c}_clone($0) }})\n\t}}\n"
			));
		}
		if t.eq {
			protocols.push("Equatable");
			let compare = match object {
				true => format!("a.handle.with {{ a_ in b.handle.with {{ b_ in {c}_eq(a_, b_) }} }}"),
				false => {
					let arena = match self.arena(ty) {
						true => "let a_ = Native.Arena()\n\t\tdefer { a_.finish() }\n\t\t",
						false => "",
					};
					let arg = self.arena_arg(ty);
					format!(
						"Native.check()\n\t\t{arena}var ca_ = a._lower({arg})\n\t\tvar cb_ = b._lower({arg})\n\t\treturn {c}_eq(&ca_, &cb_)"
					)
				}
			};
			body.push(format!(
				"\tpublic static func == (a: {name}, b: {name}) -> Swift.Bool {{\n\t\t{compare}\n\t}}\n"
			));
		}
		if t.default {
			members.push("default".to_string());
			let lift = match ty {
				Type::Object(_) => format!("{name}(raw: {c}_default())"),
				_ => format!("{name}._lift({c}_default())"),
			};
			body.push(format!(
				"\t/// Rust's `Default`.\n\tpublic static func `default`() -> {name} {{\n\t\tNative.check()\n\t\treturn {lift}\n\t}}\n"
			));
		}
	}

	/// Each method of a type, as members of its Swift type.
	fn methods(
		&mut self,
		methods: &[Function],
		owner: &Ty,
		ty: &Type,
		body: &mut Vec<String>,
		members: &mut Vec<String>,
	) {
		for method in methods {
			if let Some((code, member)) = self.function(method, Some(owner), Some(ty)) {
				members.push(member);
				body.push(indent(&code));
			}
		}
	}

	fn record(&mut self, i: usize) {
		let abi = self.abi;
		let record = &abi.api.records[i];
		let c = abi.record(i);
		let name = self.class(&c);
		let rust = abi.api.rust(&record.path, &record.args);
		self.claim(&name, format!("struct `{rust}`"));
		let ty = Type::Record(i);
		let fields: Vec<(String, String)> = (record.fields.iter())
			.map(|f| (field_name(&f.name), self.sw(&f.ty)))
			.collect();
		let mut members: Vec<String> = fields.iter().map(|(f, _)| unquote(f)).collect();
		let mut body: Vec<String> = (record.fields.iter().zip(&fields))
			.map(|(f, (name, sw))| format!("{}\tpublic var {name}: {sw}\n", docs(&f.docs, "\t")))
			.collect();
		let params: Vec<String> = fields
			.iter()
			.map(|(f, sw)| match record.tuple {
				true => format!("_ {f}: {sw}"),
				false => format!("{f}: {sw}"),
			})
			.collect();
		let assigns: String = fields.iter().map(|(f, _)| format!("\t\tself.{f} = {f}\n")).collect();
		body.push(format!("\tpublic init({}) {{\n{assigns}\t}}\n", params.join(", ")));
		let mut protocols = vec!["Sendable"];
		self.traits(&ty, &c, record.traits, &mut body, &mut members, &mut protocols);
		self.methods(&record.methods, &Ty::Struct(c.clone()), &ty, &mut body, &mut members);
		self.distinct(&rust, &members);
		// Its conversions.
		let lifted: Vec<String> = (record.fields.iter().zip(&fields))
			.map(|(f, (name, _))| {
				let e = format!("c.{}", abi::escape(&f.name));
				let value = self.lift(&f.ty, &e);
				match record.tuple {
					true => value,
					false => format!("{}: {value}", unquote(name)),
				}
			})
			.collect();
		let lowered: Vec<String> = (record.fields.iter().zip(&fields))
			.map(|(f, (name, _))| {
				let value = self.lower(&f.ty, &format!("self.{name}"));
				format!("{}: {value}", abi::escape(&f.name))
			})
			.collect();
		let arena = match self.arena(&ty) {
			true => "_ a_: Native.Arena",
			false => "",
		};
		body.push(format!(
			"\tstatic func _lift(_ c: {c}) -> {name} {{\n\t\t{name}({})\n\t}}\n",
			lifted.join(", ")
		));
		body.push(format!(
			"\tfunc _lower({arena}) -> {c} {{\n\t\t{c}({})\n\t}}\n",
			lowered.join(", ")
		));
		let text = format!("{rust}\n\n{}", record.docs);
		let _ = write!(
			self.types,
			"{}public struct {name}: {} {{\n{}}}\n\n",
			docs(text.trim(), ""),
			protocols.join(", "),
			body.join("\n")
		);
	}

	fn enumeration(&mut self, i: usize) {
		let abi = self.abi;
		let e = &abi.api.enums[i];
		let c = abi.enumeration(i);
		let name = self.class(&c);
		let rust = abi.api.rust(&e.path, &e.args);
		self.claim(&name, format!("enum `{rust}`"));
		let ty = Type::Enum(i);
		let upper = c.to_uppercase();
		let mut members = Vec::new();
		let mut cases = Vec::new();
		let mut lifts = Vec::new();
		let mut lowers = Vec::new();
		for variant in &e.variants {
			let snake = abi::snake(&variant.name);
			let case = kw(&camel(&snake));
			members.push(unquote(&case));
			let tag = format!("{upper}_{}", snake.to_uppercase());
			let member = abi::escape(&snake);
			let fields: Vec<String> = (variant.fields.iter())
				.map(|f| match variant.tuple {
					true => self.sw(&f.ty),
					false => format!("{}: {}", field_name(&f.name), self.sw(&f.ty)),
				})
				.collect();
			match fields.is_empty() {
				true => cases.push(format!("\tcase {case}\n")),
				false => cases.push(format!("\tcase {case}({})\n", fields.join(", "))),
			}
			if e.plain() {
				lifts.push(format!("\t\tcase {tag}: return .{case}"));
				lowers.push(format!("\t\tcase .{case}: return {tag}"));
				continue;
			}
			let lifted: Vec<String> = (variant.fields.iter())
				.map(|f| {
					let value = self.lift(&f.ty, &format!("c.{member}.{}", abi::escape(&f.name)));
					match variant.tuple {
						true => value,
						false => format!("{}: {value}", unquote(&field_name(&f.name))),
					}
				})
				.collect();
			let binds: Vec<String> = (0..variant.fields.len()).map(|k| format!("let p{k}_")).collect();
			let payload = format!("{c}_{snake}");
			let lowered: Vec<String> = (variant.fields.iter().enumerate())
				.map(|(k, f)| format!("{}: {}", abi::escape(&f.name), self.lower(&f.ty, &format!("p{k}_"))))
				.collect();
			match variant.fields.is_empty() {
				true => {
					lifts.push(format!("\t\tcase {tag}: return .{case}"));
					lowers.push(format!("\t\tcase .{case}: c.tag = {tag}"));
				}
				false => {
					lifts.push(format!("\t\tcase {tag}: return .{case}({})", lifted.join(", ")));
					lowers.push(format!(
						"\t\tcase .{case}({}):\n\t\t\tc.tag = {tag}\n\t\t\tc.{member} = {payload}({})",
						binds.join(", "),
						lowered.join(", ")
					));
				}
			}
		}
		let mut body = cases;
		let mut protocols = vec!["Sendable"];
		self.traits(&ty, &c, e.traits, &mut body, &mut members, &mut protocols);
		let owner = abi.ty(&ty);
		self.methods(&e.methods, &owner, &ty, &mut body, &mut members);
		self.distinct(&rust, &members);
		let (matched, invalid) = match e.plain() {
			true => ("c", "an invalid value"),
			false => ("c.tag", "an invalid tag"),
		};
		body.push(format!(
			"\tstatic func _lift(_ c: {c}) -> {name} {{\n\t\tswitch {matched} {{\n{}\n\t\tdefault: fatalError(\"{c}: {invalid}\")\n\t\t}}\n\t}}\n",
			lifts.join("\n")
		));
		let arena = match self.arena(&ty) {
			true => "_ a_: Native.Arena",
			false => "",
		};
		body.push(match e.plain() {
			true => format!(
				"\tfunc _lower() -> {c} {{\n\t\tswitch self {{\n{}\n\t\t}}\n\t}}\n",
				lowers.join("\n")
			),
			false => format!(
				"\tfunc _lower({arena}) -> {c} {{\n\t\tvar c = {c}()\n\t\tswitch self {{\n{}\n\t\t}}\n\t\treturn c\n\t}}\n",
				lowers.join("\n")
			),
		});
		let text = format!("{rust}\n\n{}", e.docs);
		let _ = write!(
			self.types,
			"{}public enum {name}: {} {{\n{}}}\n\n",
			docs(text.trim(), ""),
			protocols.join(", "),
			body.join("\n")
		);
	}

	fn object(&mut self, i: usize) {
		let abi = self.abi;
		let object = &abi.api.objects[i];
		let c = abi.object(i);
		let name = self.class(&c);
		let rust = abi.api.rust(&object.path, &object.args);
		self.claim(&name, format!("type `{rust}`"));
		let ty = Type::Object(i);
		let mut members = vec!["close".to_string(), "handle".to_string()];
		let mut body = vec![format!(
			"\tlet handle: Native.Handle\n\n\tinit(raw: OpaquePointer?) {{\n\t\thandle = Native.Handle(raw, {c}_free, \"{name}\")\n\t}}\n\n\tinit(lent raw: OpaquePointer?) {{\n\t\thandle = Native.Handle(raw, nil, \"{name}\")\n\t}}\n\n\tdeinit {{\n\t\thandle.drop()\n\t}}\n\n\t/// Free the handle once no call holds it, rather than once Swift releases this: a\n\t/// call after it traps.\n\tpublic func close() {{\n\t\thandle.close()\n\t}}\n"
		)];
		let mut protocols = vec!["@unchecked Sendable"];
		self.traits(&ty, &c, object.traits, &mut body, &mut members, &mut protocols);
		let owner = Ty::Handle {
			name: c.clone(),
			constant: false,
		};
		self.methods(&object.methods, &owner, &ty, &mut body, &mut members);
		self.distinct(&rust, &members);
		let text = format!("{rust}\n\n{}", object.docs);
		let _ = write!(
			self.types,
			"{}public final class {name}: {} {{\n{}}}\n\n",
			docs(text.trim(), ""),
			protocols.join(", "),
			body.join("\n")
		);
	}

	fn callback(&mut self, i: usize) {
		let abi = self.abi;
		let callback = &abi.api.callbacks[i];
		let c = abi.callback(i);
		let name = self.class(&c);
		let rust = callback.path.join("::");
		self.claim(&name, format!("trait `{rust}`"));
		let mut body = Vec::new();
		let mut members = Vec::new();
		let mut table = vec![format!("free: {{ data in Box<any {name}>.release(data) }}")];
		for method in &callback.methods {
			let member = member(&abi::snake(method.name()), &[]);
			members.push(unquote(&member));
			let params: Vec<String> = (method.params.iter())
				.map(|p| format!("_ {}: {}", kw(&camel(&p.name)), self.sw(&p.ty)))
				.collect();
			let ret = match method.ok {
				Type::Unit => String::new(),
				_ => format!(" -> {}", self.sw(&method.ok)),
			};
			body.push(format!(
				"{}\tfunc {member}({}){ret}",
				docs(&method.docs, "\t"),
				params.join(", ")
			));
			let ps: Vec<String> = (0..method.params.len()).map(|k| format!("p{k}_")).collect();
			let args: Vec<String> = (method.params.iter().zip(&ps))
				.map(|(p, e)| self.lift_lent(&p.ty, e))
				.collect();
			let call = format!("Box<any {name}>.unbox(data).{member}({})", args.join(", "));
			let call = match method.ok {
				Type::Unit => call,
				_ => self.lower(&method.ok, &call),
			};
			let mut closure_params = vec!["data".to_string()];
			closure_params.extend(ps);
			table.push(format!(
				"{}: {{ {} in {call} }}",
				method.name(),
				closure_params.join(", ")
			));
		}
		self.distinct(&rust, &members);
		let text = format!(
			"{rust}: implemented in Swift. Rust calls its methods from any thread, and releases\nthe implementation once it drops it.\n\n{}",
			callback.docs
		);
		let _ = write!(
			self.types,
			"{}public protocol {name}: Sendable {{\n{}\n}}\n\n",
			docs(text.trim(), ""),
			body.join("\n\n")
		);
		let _ = write!(
			self.natives,
			"\tnonisolated(unsafe) static let vtable_{c}: UnsafeMutablePointer<{c}_vtable> = {{\n\t\tlet vtable = UnsafeMutablePointer<{c}_vtable>.allocate(capacity: 1)\n\t\tvtable.initialize(to: {c}_vtable(\n\t\t\t{}))\n\t\treturn vtable\n\t}}()\n\n\tstatic func lower_{c}(_ implementation: any {name}) -> {c} {{\n\t\t{c}(vtable: vtable_{c}, data: Box.give(implementation))\n\t}}\n\n",
			table.join(",\n\t\t\t")
		);
	}

	/// The Swift statement closing each object the value `e` of type `ty` holds, once a
	/// call moved them out.
	fn close(&mut self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Option(inner) => {
				let v = self.fresh("v");
				let close = self.close(inner, &v);
				format!("if let {v} = {e} {{ {close} }}")
			}
			Type::Box(inner) => self.close(inner, e),
			Type::Tuple(elements) if elements.len() == 1 => self.close(&elements[0], e),
			Type::Tuple(elements) => {
				let closes: Vec<String> = (elements.iter().enumerate())
					.filter(|(_, ty)| moved(self.abi, ty))
					.map(|(k, ty)| self.close(ty, &format!("{e}.{k}")))
					.collect();
				closes.join("; ")
			}
			Type::List(inner) => {
				let v = self.fresh("v");
				let close = self.close(inner, &v);
				format!("for {v} in {e} {{ {close} }}")
			}
			_ => format!("{e}.close()"),
		}
	}

	/// How the call passes `param`, the C parameter `c`, whose Swift value is `e`, the
	/// `k`th, which `function` takes.
	fn arg(&mut self, ty: &Type, c: &Ty, e: &str, k: usize, tr: &str) -> (Arg, bool) {
		let abi = self.abi;
		let mut arg = Arg::default();
		let mut arena = false;
		if moved(abi, ty) {
			arg.after.push(self.close(ty, e));
		}
		match (ty, c) {
			(Type::Closure(lent, ret), Ty::Fn(..)) => {
				let (f, g, d) = (format!("f{k}_"), format!("g{k}_"), format!("d{k}_"));
				arg.open = Some((
					format!(
						"{tr}withoutActuallyEscaping({e}) {{ {f} in\n\tvar {g} = {f}\n\treturn {tr}withUnsafeMutablePointer(to: &{g}) {{ {d} in"
					),
					"}\n}".to_string(),
				));
				arg.exprs.push(self.trampoline(ty, lent, ret));
				arg.exprs.push(d);
			}
			(Type::Callback(i, _), _) => arg.exprs.push(format!("Native.lower_{}({e})", abi.callback(*i))),
			(Type::Waker, _) => arg.exprs.push(format!("Native.waker({e})")),
			(ty, Ty::Buf) if Abi::is_buf(ty) || matches!(ty, Type::Option(inner) if Abi::is_buf(inner)) => {
				let b = format!("b{k}_");
				arg.open = Some((format!("{tr}Native.view({e}) {{ {b} in"), "}".to_string()));
				arg.exprs.push(b);
			}
			(ty, Ty::Handle { .. }) => {
				let h = format!("h{k}_");
				let open = match ty {
					Type::Option(_) => format!("{tr}Native.with({e}?.handle) {{ {h} in"),
					_ => format!("{tr}{e}.handle.with {{ {h} in"),
				};
				arg.open = Some((open, "}".to_string()));
				arg.exprs.push(h);
			}
			(ty, _) => {
				arena = self.arena(ty);
				arg.exprs.push(self.lower(ty, e));
			}
		}
		(arg, arena)
	}

	/// The C function C calls for a closure of type `ty`, lent for a call, taking `lent`
	/// and returning `ret`: it lends each object as its class, closed once it returns.
	fn trampoline(&mut self, ty: &Type, lent: &[Type], ret: &Type) -> String {
		let ps: Vec<String> = (0..lent.len()).map(|k| format!("p{k}_")).collect();
		let mut body = vec![format!(
			"let f_ = data_!.assumingMemoryBound(to: ({}).self).pointee",
			self.sw(ty)
		)];
		let mut args = Vec::new();
		for (k, (ty, p)) in lent.iter().zip(&ps).enumerate() {
			match ty {
				Type::Ref(_, object) if matches!(**object, Type::Object(_)) => {
					let l = format!("l{k}_");
					body.push(format!("let {l} = {}(lent: {p})", self.sw(object)));
					body.push(format!("defer {{ {l}.close() }}"));
					args.push(l);
				}
				ty => args.push(self.lift_lent(ty, p)),
			}
		}
		let call = format!("f_({})", args.join(", "));
		body.push(match ret {
			Type::Unit => call,
			ret => format!("return {}", self.lower(ret, &call)),
		});
		let mut params = vec!["data_".to_string()];
		params.extend(ps);
		format!(
			"{{ {} in\n\t{}\n}}",
			params.join(", "),
			body.join("\n\t")
		)
	}

	/// `function`'s Swift form and its member name, a member of `owner` (whose IR type is
	/// `owner_ty`) if it has one.
	fn function(&mut self, function: &Function, owner: Option<&Ty>, owner_ty: Option<&Type>) -> Option<(String, String)> {
		let abi = self.abi;
		let export = abi.export(function, owner);
		let c_name = export.call.name.clone();
		let bare = self.bare(&c_name).to_string();
		let owner_c = match owner {
			Some(Ty::Struct(n) | Ty::Enum(n) | Ty::Handle { name: n, .. }) => Some(n.clone()),
			_ => None,
		};
		let own = match &owner_c {
			Some(o) => c_name.strip_prefix(o.as_str()).and_then(|r| r.strip_prefix('_')),
			None => None,
		};
		let reserved: &[&str] = match owner_ty {
			Some(Type::Object(_)) => &["close", "handle", "init", "deinit"],
			Some(_) => &["init"],
			None => &[],
		};
		let snake = own.unwrap_or(&bare);
		let mut member = member(snake, reserved);

		let receiver = function.receiver.filter(|_| owner.is_some());
		let object = matches!(owner, Some(Ty::Handle { .. })) && receiver.is_some();
		// Only a future or a `Result` throws, and a future only once it is awaited.
		let throws = function.future || function.err.is_some();
		let tr = match function.err.is_some() && !function.future {
			true => "try ",
			false => "",
		};
		let mut prelude = Vec::new();
		if !object {
			prelude.push("Native.check()".to_string());
		}
		let mut arena = false;
		let mut args: Vec<Arg> = Vec::new();
		let mut c_params = export.call.params.iter();
		if let Some(receiver) = receiver {
			let (_, c) = c_params.next().expect("a method has its receiver");
			let ty = owner_ty.expect("a method has its type").clone();
			let mut arg = Arg::default();
			match c {
				Ty::Handle { .. } => {
					arg.open = Some((format!("{tr}self.handle.with {{ h_ in"), "}".to_string()));
					arg.exprs.push("h_".to_string());
					let copy = matches!(ty, Type::Object(i) if abi.api.objects[i].copy);
					if receiver == Receiver::Owned && !copy {
						arg.after.push("self.close()".to_string());
					}
				}
				_ => {
					arena |= self.arena(&ty);
					prelude.push(format!("var c_self_ = self._lower({})", self.arena_arg(&ty)));
					arg.exprs.push("&c_self_".to_string());
				}
			}
			args.push(arg);
		}
		let mut params = Vec::new();
		for (k, param) in function.params.iter().enumerate() {
			let (_, c) = c_params.next().expect("each parameter has its C one");
			if let Type::Closure(..) = param.ty {
				c_params.next().expect("a closure has its data");
			}
			let name = kw(&camel(&param.name));
			params.push(format!("_ {name}: {}", self.sw(&param.ty)));
			let (arg, needs) = self.arg(&param.ty, c, &name, k, tr);
			arena |= needs;
			args.push(arg);
		}
		let outs: Vec<(String, Ty)> = c_params.cloned().collect();
		if arena {
			prelude.insert(1.min(prelude.len()), "let a_ = Native.Arena()\ndefer { a_.finish() }".to_string());
		}
		let after: Vec<String> = args.iter().flat_map(|a| a.after.clone()).collect();
		if !after.is_empty() {
			prelude.push(format!("defer {{ {} }}", after.join("; ")));
		}
		let exprs: Vec<String> = args.iter().flat_map(|a| a.exprs.clone()).collect();

		// A tuple of one returned whole is its element, written through its one out pointer.
		let ok = match &function.ok {
			Type::Tuple(elements) if elements.len() == 1 => strip_refs(&elements[0]),
			ok => strip_refs(ok),
		};
		let err = function.err.as_ref().map(strip_refs);
		let thrown = err.as_ref().map(|e| self.thrown(e));

		let mut inner = Vec::new();
		let tail;
		if let Some((_, poll, free)) = &export.future {
			inner.push(format!("{c_name}({})", exprs.join(", ")));
			let poll_outs: Vec<(String, Ty)> = poll.params[2..].to_vec();
			let mut body: Vec<String> = poll_outs
				.iter()
				.map(|(n, ty)| self.out_decl(n, ty))
				.collect();
			let mut call_args = vec!["f_".to_string(), "w_".to_string()];
			call_args.extend(poll_outs.iter().map(|(n, _)| format!("&c_{n}_")));
			let ready = match ok {
				Type::Unit => "()".to_string(),
				_ => self.lift_outs(&function.ok, &ok),
			};
			let upper = abi.prefix.to_uppercase();
			let mut cases = vec![format!("case {upper}_POLL_READY: return {ready}")];
			if let (Some(err), Some(thrown)) = (&err, &thrown) {
				let lifted = self.lift(err, "c_err_");
				cases.push(format!("case {upper}_POLL_ERROR: throw {}", thrown_value(thrown, &lifted)));
			}
			cases.push("default: return nil".to_string());
			body.push(format!(
				"switch {}({}) {{\n{}\n}}",
				poll.name,
				call_args.join(", "),
				cases.join("\n")
			));
			tail = Some(format!(
				"return try await Native.run(f_, {}) {{ f_, w_ in\n{}\n}}",
				free.name,
				indent(&body.join("\n"))
			));
		} else {
			tail = None;
			for (n, ty) in &outs {
				inner.push(self.out_decl(n, ty));
			}
			let mut call_args = exprs.clone();
			call_args.extend(outs.iter().map(|(n, _)| format!("&c_{n}_")));
			let call = format!("{c_name}({})", call_args.join(", "));
			match (&err, &ok) {
				(Some(err), ok) => {
					let ready = match ok {
						Type::Unit => "return".to_string(),
						_ => format!("return {}", self.lift_outs(&function.ok, ok)),
					};
					inner.push(format!("if {call} {{\n\t{ready}\n}}"));
					let lifted = self.lift(err, "c_err_");
					inner.push(format!(
						"throw {}",
						thrown_value(thrown.as_ref().expect("an error throws"), &lifted)
					));
				}
				(None, Type::Unit) => inner.push(call),
				(None, ok) if !outs.is_empty() => {
					inner.push(call);
					inner.push(format!("return {}", self.lift_outs(&function.ok, ok)));
				}
				(None, ok) => {
					inner.push(format!("let c_ret_ = {call}"));
					inner.push(format!("return {}", self.lift(ok, "c_ret_")));
				}
			}
		}
		// Wrap the call in each argument's closure, innermost last.
		let mut code = inner.join("\n");
		for arg in args.iter().rev() {
			if let Some((open, close)) = &arg.open {
				let lines = code.lines().count();
				// A closure of one line returns its value; of more, its own `return` does.
				let body = match lines > 1 || code.starts_with("return ") || code.starts_with("throw ") {
					true => code.clone(),
					false => format!("return {code}"),
				};
				code = format!("return {open}\n{}\n{close}", indent(&body));
			}
		}
		let mut body = prelude;
		match tail {
			Some(tail) => {
				let create = match code.starts_with("return ") {
					true => code["return ".len()..].to_string(),
					false => code,
				};
				body.push(format!("let f_ = {create}"));
				body.push(tail);
			}
			None => body.push(code),
		}

		let mut text = function.docs.clone();
		for param in &function.params {
			if let Type::Closure(lent, _) = &param.ty {
				let name = kw(&camel(&param.name));
				text.push_str(&format!(
					"\n\nRust calls `{}` only during the call, from any thread.",
					unquote(&name)
				));
				if lent.iter().any(|p| matches!(p.base(), Type::Object(_))) {
					text.push_str(&format!(
						"\nAn object it lends lives only for that call of `{}`: keep none past it.",
						unquote(&name)
					));
				}
			}
		}
		if function.future {
			text.push_str("\n\nA cancelled task cancels it in Rust, losing nothing, and throws `CancellationError`.");
		}
		let effects = match (function.future, throws) {
			(true, _) => " async throws",
			(false, true) => " throws",
			(false, false) => "",
		};
		let ret = match ok {
			Type::Unit => String::new(),
			_ => format!(" -> {}", self.sw(&ok)),
		};
		let is_static = receiver.is_none() && owner.is_some();
		let stat = match is_static {
			true => "static ",
			false => "",
		};
		let body = body.join("\n");
		let head = match (function.access, receiver) {
			(Access::Field { set: false, .. }, Some(_)) if function.params.is_empty() && !throws => {
				format!("public var {member}{}", ret.replacen(" -> ", ": ", 1))
			}
			(Access::Const, None) if function.params.is_empty() && !throws => {
				member = member.trim_matches('`').to_uppercase();
				format!("public {stat}var {member}{}", ret.replacen(" -> ", ": ", 1))
			}
			_ => format!("public {stat}func {member}({}){effects}{ret}", params.join(", ")),
		};
		let code = format!("{}{head} {{\n{}\n}}\n", docs(text.trim(), ""), indent(&body));
		Some((code, unquote(&member)))
	}

	/// The declaration of the local the call writes the out value `name` of C type `ty` to.
	fn out_decl(&self, name: &str, ty: &Ty) -> String {
		let Ty::Out(inner) = ty else {
			unreachable!("an out parameter is a pointer")
		};
		format!("var c_{name}_: {} = {}", self.c_sw(inner), self.zero(inner))
	}

	/// The Swift value of a call's outs, which return `ok`, or each element of a tuple.
	fn lift_outs(&mut self, declared: &Type, ok: &Type) -> String {
		match declared {
			Type::Tuple(elements) if elements.len() == 1 => self.lift(ok, "c_out0_"),
			Type::Tuple(elements) => {
				let lifted: Vec<String> = (elements.iter().enumerate())
					.map(|(n, e)| self.lift(&strip_refs(e), &format!("c_out{n}_")))
					.collect();
				format!("({})", lifted.join(", "))
			}
			_ => self.lift(ok, "c_out_"),
		}
	}

	/// How an error of type `err` is thrown: as itself if an exported type, which then
	/// conforms to `Swift.Error`, or else in a struct of its own.
	fn thrown(&mut self, err: &Type) -> Thrown {
		match err.base() {
			Type::Record(_) | Type::Enum(_) | Type::Object(_) => {
				self.conforms.insert(self.sw(err));
				Thrown::Itself
			}
			_ => {
				let sw = self.sw(err);
				let stripped: String = sw
					.trim_start_matches("Swift.")
					.chars()
					.filter(|c| c.is_ascii_alphanumeric())
					.collect();
				let name = format!("{stripped}Error");
				if !self.thrown.contains_key(&name) {
					self.claim(&name, format!("the error of `{sw}`"));
					self.thrown.insert(name.clone(), err.clone());
				}
				Thrown::Wrapped(name)
			}
		}
	}
}

/// How a function throws its error.
enum Thrown {
	Itself,
	Wrapped(String),
}

/// The error value thrown for the lifted error `lifted`.
fn thrown_value(thrown: &Thrown, lifted: &str) -> String {
	match thrown {
		Thrown::Itself => lifted.to_string(),
		Thrown::Wrapped(name) => format!("{name}(error: {lifted})"),
	}
}

/// Whether passing `ty` moves an object's value out: by value, boxed, or in an `Option`,
/// a list, or a tuple, unless `Copy`, and never through a reference.
fn moved(abi: &Abi<'_>, ty: &Type) -> bool {
	match ty {
		Type::Object(i) => !abi.api.objects[*i].copy,
		Type::Option(inner) | Type::Box(inner) | Type::List(inner) => moved(abi, inner),
		Type::Tuple(elements) => elements.iter().any(|ty| moved(abi, ty)),
		_ => false,
	}
}

/// `ty` returned: a borrow is returned as a clone, so owned.
fn strip_refs(ty: &Type) -> Type {
	match ty {
		Type::Ref(_, inner) => strip_refs(inner),
		Type::Option(inner) => Type::Option(Box::new(strip_refs(inner))),
		Type::Box(inner) => Type::Box(Box::new(strip_refs(inner))),
		Type::List(inner) => Type::List(Box::new(strip_refs(inner))),
		Type::Tuple(elements) => Type::Tuple(elements.iter().map(strip_refs).collect()),
		ty => ty.clone(),
	}
}

/// The Swift type of an integer.
fn sw_int(int: Int) -> &'static str {
	match int {
		Int::U8 => "Swift.UInt8",
		Int::U16 => "Swift.UInt16",
		Int::U32 => "Swift.UInt32",
		Int::U64 => "Swift.UInt64",
		Int::Usize => "Swift.UInt",
		Int::I8 => "Swift.Int8",
		Int::I16 => "Swift.Int16",
		Int::I32 => "Swift.Int32",
		Int::I64 => "Swift.Int64",
		Int::Isize => "Swift.Int",
	}
}

/// The Swift type Swift imports a C integer as: `size_t` is `Int`.
fn c_int(int: Int) -> &'static str {
	match int {
		Int::Usize => "Swift.Int",
		int => sw_int(int),
	}
}

/// The C integer of the Swift integer `e`.
fn self_lower_int(int: Int, e: &str) -> String {
	match int {
		Int::Usize => format!("Swift.Int(bitPattern: {e})"),
		_ => e.to_string(),
	}
}

/// The Swift integer of the C integer `e`.
fn self_lift_int(int: Int, e: &str) -> String {
	match int {
		Int::Usize => format!("Swift.UInt(bitPattern: {e})"),
		_ => e.to_string(),
	}
}

/// A snake-case name in Pascal case: `size_pair` is `SizePair`.
fn pascal(name: &str) -> String {
	name.split('_')
		.filter(|s| !s.is_empty())
		.map(|s| {
			let mut chars = s.chars();
			match chars.next() {
				Some(first) => first.to_uppercase().chain(chars).collect(),
				None => String::new(),
			}
		})
		.collect()
}

/// A snake-case name in camel case: `into_label` is `intoLabel`, and `0` is `_0`.
fn camel(name: &str) -> String {
	if name.starts_with(|c: char| c.is_ascii_digit()) {
		return format!("_{name}");
	}
	let pascal = pascal(name);
	let mut chars = pascal.chars();
	match chars.next() {
		Some(first) => first.to_lowercase().chain(chars).collect(),
		None => name.to_string(),
	}
}

/// A field's Swift name.
fn field_name(name: &str) -> String {
	kw(&camel(name))
}

/// A member's Swift name: in camel case, quoted if a keyword, or with `_` appended if
/// Swift gives every such type a member of that name.
fn member(snake: &str, reserved: &[&str]) -> String {
	let name = camel(snake);
	match reserved.contains(&name.as_str()) {
		true => format!("{name}_"),
		false => kw(&name),
	}
}

/// A name without the backticks quoting a keyword.
fn unquote(name: &str) -> String {
	name.trim_matches('`').to_string()
}

