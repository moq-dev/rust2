/// `ty` returned: a borrow is returned as a clone, so owned.
pub(crate) fn strip_refs(ty: &Type) -> Type {
	match ty {
		Type::Ref(_, inner) => strip_refs(inner),
		Type::Option(inner) => Type::Option(Box::new(strip_refs(inner))),
		Type::Box(inner) => Type::Box(Box::new(strip_refs(inner))),
		ty => ty.clone(),
	}
}

/// The name of a tuple's field `k`, as `Pair`'s and `Triple`'s go on.
fn ordinal(k: usize) -> String {
	const ORDINALS: [&str; 12] = [
		"first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth", "tenth", "eleventh",
		"twelfth",
	];
	ORDINALS
		.get(k)
		.map_or_else(|| format!("item{}", k + 1), |o| o.to_string())
}

/// A snake-case name in Pascal case: `size_pair` is `SizePair`.
pub(crate) fn pascal(name: &str) -> String {
	name.split('_')
		.filter(|s| !s.is_empty())
		.map(|s| {
			let mut chars = s.chars();
			match chars.next() {
				Some(first) => first.to_uppercase().chain(chars).collect(),
				None => String::new(),
			}
		})
		.collect()
}

/// A snake-case name in camel case: `into_label` is `intoLabel`, and `0` is `_0`.
fn camel(name: &str) -> String {
	if name.starts_with(|c: char| c.is_ascii_digit()) {
		return format!("_{name}");
	}
	let pascal = pascal(name);
	let mut chars = pascal.chars();
	match chars.next() {
		Some(first) => first.to_lowercase().chain(chars).collect(),
		None => name.to_string(),
	}
}

/// A field's Kotlin name.
fn field_name(name: &str) -> String {
	kw(&camel(name))
}

/// A member's Kotlin name: in camel case, quoted if a keyword, or with `_` appended if
/// Kotlin gives every such class a member of that name.
fn member(snake: &str, reserved: &[&str]) -> String {
	let name = camel(snake);
	match reserved.contains(&name.as_str()) {
		true => format!("{name}_"),
		false => kw(&name),
	}
}

/// A name Kotlin reads as a hard keyword, in backticks.
fn kw(name: &str) -> String {
	const KEYWORDS: &[&str] = &[
		"as",
		"break",
		"class",
		"continue",
		"do",
		"else",
		"false",
		"for",
		"fun",
		"if",
		"in",
		"interface",
		"is",
		"null",
		"object",
		"package",
		"return",
		"super",
		"this",
		"throw",
		"true",
		"try",
		"typealias",
		"typeof",
		"val",
		"var",
		"when",
		"while",
	];
	match KEYWORDS.contains(&name) {
		true => format!("`{name}`"),
		false => name.to_string(),
	}
}

/// A native method's name mangled as JNI's symbols spell it.
fn mangle(name: &str) -> String {
	let mut out = String::new();
	for c in name.chars() {
		match c {
			'_' => out.push_str("_1"),
			'/' => out.push('_'),
			c if c.is_ascii_alphanumeric() => out.push(c),
			c => {
				let _ = write!(out, "_0{:04x}", c as u32);
			}
		}
	}
	out
}

/// The kind and name a member's code declares, for [`Gen::distinct`].
fn member_name(code: &str) -> Option<String> {
	let line = code.lines().find(|l| {
		let l = l.trim_start();
		!l.starts_with("/**") && !l.starts_with('*') && !l.starts_with("@")
	})?;
	let line = line
		.trim_start()
		.trim_start_matches("final ")
		.trim_start_matches("override ")
		.trim_start_matches("suspend ");
	let (kind, rest) = line.split_once(' ')?;
	if !matches!(kind, "fun" | "val") {
		return None;
	}
	let name: String = rest
		.chars()
		.take_while(|c| *c != '(' && *c != ':' && *c != ' ')
		.collect();
	Some(format!("{kind} {name}"))
}

/// Kotlin's KDoc holding `docs`, each line indented by `indent`, or nothing for none.
/// A Kotlin block comment nests, so a `/*` or `*/` in the docs is escaped.
fn docs(docs: &str, indent: &str) -> String {
	if docs.trim().is_empty() {
		return String::new();
	}
	let escaped = docs.replace("/*", "/&#42;").replace("*/", "&#42;/");
	let mut out = format!("{indent}/**\n");
	for line in escaped.lines() {
		match line.is_empty() {
			true => {
				let _ = writeln!(out, "{indent} *");
			}
			false => {
				let _ = writeln!(out, "{indent} * {line}");
			}
		}
	}
	let _ = writeln!(out, "{indent} */");
	out
}

/// A field's docs, before it in a constructor's parameters.
fn docs_inline(text: &str, indent: &str) -> String {
	docs(text, indent)
}

/// Code indented by one tab more.
fn indent(code: &str) -> String {
	indent_by(code, 1)
}

/// Code indented by `n` tabs more, but for blank lines.
pub(crate) fn indent_by(code: &str, n: usize) -> String {
	let tabs = "\t".repeat(n);
	let mut out: String = code
		.lines()
		.map(|l| match l.is_empty() {
			true => "\n".to_string(),
			false => format!("{tabs}{l}\n"),
		})
		.collect();
	if !code.ends_with('\n') {
		out.pop();
	}
	out
}
