//! Kotlin over the C ABI, through JNI: `kotlin/<prefix>.kt`, and the JNI functions it
//! calls, which the crate builds with its `kotlin` feature.
//!
//! Each name is its C name without the prefix, in a package of the prefix, as Kotlin
//! spells it: `moq_track_producer` is `moq.TrackProducer`, and its method
//! `moq_track_producer_append_group` is `TrackProducer.appendGroup`. A keyword is quoted
//! in backticks, and a member named as one Kotlin gives every class takes a trailing `_`.
//! An object is a class owning its handle, closed by `close`; a record a data class; an
//! enum an enum class, or for one with data a sealed class of a class per variant; a trait
//! an interface; a closure a function type; a future a `suspend fun`; an error an
//! exception. The runtime they share, [`runtime/rt.kt`](../runtime/rt.kt), holds the
//! codec, the handles, and the waker a future parks on; the glue's,
//! [`runtime/jni.rs`](../runtime/jni.rs), the same on the Rust side.
//!
//! A value crosses JNI as a scalar, a handle as a `long`, bytes passed in as a `byte[]`,
//! bytes returned as their owner, which a `Bytes` lends as a direct `ByteBuffer`, or
//! encoded into a `byte[]` field by field as its C struct holds it, so each call is one
//! crossing. An object or `Bytes` never closed is freed once the GC collects it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::hash::Hasher;

use rustc_data_structures::stable_hash::StableHasher;

use crate::abi::{self, Abi, Ty};
use crate::ir::{Access, Family, Function, Int, Literal, Receiver, Type};

const RUNTIME: &str = include_str!("../runtime/rt.kt");
pub const GLUE_RUNTIME: &str = include_str!("../runtime/jni.rs");

/// What the generator writes: the Kotlin file, the Rust module of JNI functions, and the
/// R8 and ProGuard rules keeping what that module looks up by name.
pub struct Output {
	pub kotlin: String,
	pub glue: String,
	pub rules: String,
}

/// The Kotlin for `abi`, whose header's contract is `contract`, or the names two items
/// claim alike. The Kotlin's own contract hashes the header's with everything it and its
/// glue add, as JNI's signatures and encodings change with no C declaration changing.
pub fn generate(abi: &Abi<'_>, packages: &str, contract: u64) -> Result<Output, String> {
	let mut g = Gen {
		abi,
		types: String::new(),
		top: String::new(),
		natives: String::new(),
		glue: String::new(),
		exceptions: BTreeMap::new(),
		names: BTreeMap::new(),
		errors: Vec::new(),
		fresh: 0,
		tuples: BTreeSet::new(),
		dispatchers: Vec::new(),
	};
	g.write();
	if !g.errors.is_empty() {
		return Err(g.errors.join("\n"));
	}
	let p = &abi.prefix;
	let mut hasher = StableHasher::new();
	hasher.write_u64(contract);
	for part in [&g.types, &g.top, &g.natives, &g.glue, RUNTIME, GLUE_RUNTIME, BYTES] {
		hasher.write(part.as_bytes());
	}
	let contract = Hasher::finish(&hasher);
	let mut kotlin = format!(
		"// Generated by rust2-ffi: Kotlin over the C ABI of the pub API of {packages}. Do not edit.\n\n\
		@file:Suppress(\"ktlint\", \"NAME_SHADOWING\", \"RedundantVisibilityModifier\", \"unused\")\n\n\
		package {p}\n\n"
	);
	for import in IMPORTS {
		let _ = writeln!(kotlin, "import {import}");
	}
	kotlin.push('\n');
	kotlin.push_str(
		"/** Wakes a future's poller. Rust may call [wake] from any thread, any number of times. */\nfun interface Waker {\n\tfun wake()\n}\n\n",
	);
	kotlin.push_str(BYTES);
	kotlin.push_str(&g.types);
	kotlin.push_str(&g.top);
	let _ = write!(
		kotlin,
		"internal object Native {{\n\tinit {{\n\t\tSystem.loadLibrary(\"{p}\")\n\t\t// Checked before any other call: a Kotlin file and a library from different\n\t\t// builds must not mix.\n\t\tkotlin.check(__contract().toULong() == {}) {{ \"{p}.kt and the library are from different builds\" }}\n\t}}\n\n\t@JvmStatic external fun __contract(): Long\n\n\t@JvmStatic external fun __waker_new(waker: Waker): Long\n\n\t@JvmStatic external fun __waker_free(node: Long)\n\n\t@JvmStatic external fun __bytes_buffer(owner: Long): java.nio.ByteBuffer\n\n\t@JvmStatic external fun __bytes_free(owner: Long)\n\n\t@JvmStatic private fun __wake(waker: Any) = (waker as Waker).wake()\n\n\t@JvmStatic private fun __free(implementation: Any) {{\n\t\tif (implementation is AutoCloseable) implementation.close()\n\t}}\n\n{}{}}}\n",
		contract_literal(contract),
		g.natives,
		indent_by(RUNTIME, 1),
	);
	let glue = format!(
		"//! Generated by rust2-ffi: the JNI functions `kotlin/{p}.kt` calls, over the C ABI of {packages}.\n\n\
		#![allow(non_snake_case, non_upper_case_globals, unused_mut, unused_unsafe, clippy::all)]\n\n\
		mod rt;\n\n\
		use std::ffi::c_void;\n\
		use std::mem::MaybeUninit;\n\
		use std::sync::OnceLock;\n\n\
		use rt::*;\n\n\
		#[unsafe(no_mangle)]\n\
		pub unsafe extern \"system\" fn JNI_OnLoad(vm: *mut JavaVM, _: *mut c_void) -> jint {{\n\
		\tunsafe {{ rt::load(vm, c\"{p}/Native\") }}\n\
		}}\n\n\
		#[unsafe(no_mangle)]\n\
		pub extern \"system\" fn Java_{pkg}_Native__1_1contract(_: *mut JNIEnv, _: jclass) -> jlong {{\n\
		\t0x{contract:016x}u64 as jlong\n\
		}}\n\n\
		#[unsafe(no_mangle)]\n\
		pub extern \"system\" fn Java_{pkg}_Native__1_1waker_1new(env: *mut JNIEnv, _: jclass, waker: jobject) -> jlong {{\n\
		\trt::node(env, waker) as usize as jlong\n\
		}}\n\n\
		#[unsafe(no_mangle)]\n\
		pub unsafe extern \"system\" fn Java_{pkg}_Native__1_1waker_1free(_: *mut JNIEnv, _: jclass, node: jlong) {{\n\
		\tunsafe {{ rt::unref(node as usize as _) }}\n\
		}}\n\n\
		#[unsafe(no_mangle)]\n\
		pub unsafe extern \"system\" fn Java_{pkg}_Native__1_1bytes_1buffer(env: *mut JNIEnv, _: jclass, owner: jlong) -> jobject {{\n\
		\tunsafe {{ rt::buffer(env, owner) }}\n\
		}}\n\n\
		#[unsafe(no_mangle)]\n\
		pub unsafe extern \"system\" fn Java_{pkg}_Native__1_1bytes_1free(_: *mut JNIEnv, _: jclass, owner: jlong) {{\n\
		\tunsafe {{ rt::free_bytes(owner) }}\n\
		}}\n\n\
		{}",
		g.glue,
		pkg = mangle(p),
	);
	// JNI_OnLoad finds Native by name, the VM binds its native methods by theirs, and the
	// glue looks up each Kotlin function it calls by its own, which nothing in Kotlin calls.
	// A shrinker still strips Native and its native methods where nothing reaches them.
	let mut rules = format!(
		"# Generated by rust2-ffi: the R8 and ProGuard rules keeping what the JNI glue of {packages} looks up by name. Do not edit.\n\n\
		-keepnames class {p}.Native\n\n\
		-keepclassmembernames class {p}.Native {{\n\tnative <methods>;\n}}\n\n\
		-keepclassmembers class {p}.Native {{\n"
	);
	for name in ["__wake", "__free"]
		.into_iter()
		.chain(g.dispatchers.iter().map(String::as_str))
	{
		let _ = writeln!(rules, "\tstatic *** {name}(...);");
	}
	rules.push_str("}\n");
	Ok(Output { kotlin, glue, rules })
}

const IMPORTS: &[&str] = &["kotlin.coroutines.resume", "kotlin.time.toDuration"];

/// The bytes Rust returns, copied when short and otherwise lent.
const BYTES: &str = "/**
 * Bytes Rust returned: up to 1 KiB copied, and longer ones lent without a copy, which
 * [buffer] reads until [close] frees them, after which reading it is undefined. Unclosed,
 * lent ones are freed once the GC collects [buffer], so keep it, not only a slice or
 * duplicate of it, while reading.
 */
class Bytes private constructor(buffer: java.nio.ByteBuffer, owner: Long) : AutoCloseable {
\t/** Bytes Kotlin holds, as a record Rust takes needs, which [close] leaves readable. */
\tconstructor(bytes: ByteArray) : this(java.nio.ByteBuffer.wrap(bytes), 0L)

\tinternal constructor(owner: Long) : this(Native.__bytes_buffer(owner), owner)

\t/** The bytes, read-only. */
\tval buffer: java.nio.ByteBuffer = buffer.asReadOnlyBuffer()

\t// What the GC collects: a view of [buffer] need not keep it reachable, on the JVM or ART.
\tprivate val free = if (owner == 0L) null else Native.Free(this.buffer, owner)

\tprivate var closed = false

\t/** The bytes, copied. */
\tfun toByteArray(): ByteArray = read { b -> ByteArray(b.remaining()).also { b.get(it) } }

\t/**
\t * Run [block] with a view of the bytes from their start, which throws once closed. Locked,
\t * so this and [buffer] stay reachable, and [close] waits, until it returns.
\t */
\tinternal fun <R> read(block: (java.nio.ByteBuffer) -> R): R = synchronized(this) {
\t\tkotlin.check(!closed) { \"Bytes is closed\" }
\t\tblock(buffer.duplicate().also { it.clear() })
\t}

\toverride fun close() {
\t\tsynchronized(this) {
\t\t\tclosed = true
\t\t\tfree?.free()
\t\t}
\t}
}

";

/// The names the generated code uses unqualified, which no exported type or function may
/// take. The runtime's own are the C ABI's: `Native`, `Waker`, `Bytes`, and `Bound` are
/// claimed as `<prefix>_native`, `<prefix>_waker`, `<prefix>_bytes`, and `<prefix>_bound`.
const TAKEN: &[&str] = &[
	"Any",
	"AutoCloseable",
	"Boolean",
	"Byte",
	"ByteArray",
	"Double",
	"Exception",
	"Float",
	"Int",
	"Long",
	"Short",
	"String",
	"UByte",
	"UInt",
	"ULong",
	"UShort",
	"Unit",
	"check",
	"error",
];

/// How a function's Kotlin form is held.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Place {
	/// A member of a class, whose receiver is `this`.
	Member,
	/// In a companion object, or at the top level.
	Static,
}

/// One C parameter as Kotlin passes it and the glue takes it.
#[derive(Default)]
struct Arg {
	/// The Kotlin native method's parameter types.
	native: Vec<String>,
	/// The glue's JNI parameter types.
	jni: Vec<&'static str>,
	/// The Kotlin expressions passed.
	exprs: Vec<String>,
	/// The lambda the call runs in, holding what it passes until it returns, and the
	/// statements at its start.
	open: Option<String>,
	inside: Vec<String>,
	/// Kotlin statements once the call returns.
	after: Vec<String>,
	/// The glue's statements before the call, and the C arguments it passes.
	rust_pre: Vec<String>,
	rust_args: Vec<String>,
}

struct Gen<'a> {
	abi: &'a Abi<'a>,
	/// Types, then top-level functions and codecs, then the native methods.
	types: String,
	top: String,
	natives: String,
	glue: String,
	/// The exception class of each error type, by name.
	exceptions: BTreeMap<String, Type>,
	/// Each top-level Kotlin name, with what claimed it.
	names: BTreeMap<String, String>,
	errors: Vec<String>,
	/// A counter for fresh Kotlin names.
	fresh: usize,
	/// The arities a tuple class is written for: one, and past `Triple`.
	tuples: BTreeSet<usize>,
	/// The Kotlin functions the glue calls, which the rules keep.
	dispatchers: Vec<String>,
}

impl<'a> Gen<'a> {
	fn fresh(&mut self, base: &str) -> String {
		self.fresh += 1;
		format!("{base}{}", self.fresh)
	}

	/// A C name without the prefix.
	fn bare<'n>(&self, c: &'n str) -> &'n str {
		&c[self.abi.prefix.len() + 1..]
	}

	/// The Kotlin name of the C type `c`.
	fn class(&self, c: &str) -> String {
		pascal(self.bare(c))
	}

	/// Claim the top-level Kotlin name `name` for `what`.
	fn claim(&mut self, name: &str, what: String) {
		if TAKEN.contains(&name) {
			self.errors.push(format!(
				"{what} is `{}.{name}` in Kotlin, which its runtime names: rename it in the config",
				self.abi.prefix
			));
		} else if let Some(first) = self.names.insert(name.to_string(), what.clone()) {
			self.errors.push(format!(
				"{first} and {what} are both `{}.{name}` in Kotlin: rename one in the config",
				self.abi.prefix
			));
		}
	}

	/// The class of a tuple of `n`, of one or past `Triple`, written once, its fields named
	/// as `Triple`'s.
	fn tuple(&mut self, n: usize) -> String {
		let name = format!("Tuple{n}");
		if self.tuples.insert(n) {
			self.claim(&name, format!("a tuple of {n}"));
			let params: Vec<String> = (1..=n).map(|k| format!("T{k}")).collect();
			let fields: Vec<String> = (0..n).map(|k| format!("\tval {}: T{},\n", ordinal(k), k + 1)).collect();
			let _ = write!(
				self.types,
				"/** A tuple of {n}, as `Pair` and `Triple` are of two and three. */\ndata class {name}<{}>(\n{})\n\n",
				params.join(", "),
				fields.concat()
			);
		}
		name
	}

	/// The Kotlin type of a tuple of `elements`.
	fn tuple_of(&mut self, elements: Vec<String>) -> String {
		match elements.len() {
			2 => format!("kotlin.Pair<{}>", elements.join(", ")),
			3 => format!("kotlin.Triple<{}>", elements.join(", ")),
			n => format!("{}<{}>", self.tuple(n), elements.join(", ")),
		}
	}

	/// The Kotlin type of `ty` as a value, owning what it holds.
	fn kt(&mut self, ty: &Type) -> String {
		let abi = self.abi;
		match ty {
			Type::Unit => "Unit".to_string(),
			Type::Bool => "Boolean".to_string(),
			Type::Int(int) => kt_int(*int).to_string(),
			Type::F32 => "Float".to_string(),
			Type::F64 => "Double".to_string(),
			Type::Char => "Int".to_string(),
			Type::Str | Type::String => "String".to_string(),
			Type::Slice | Type::Vec | Type::Bytes => "Bytes".to_string(),
			Type::Path | Type::PathBuf => "String".to_string(),
			Type::Duration => "kotlin.time.Duration".to_string(),
			Type::SocketAddr(_) => "java.net.InetSocketAddress".to_string(),
			Type::List(inner) => format!("kotlin.collections.List<{}>", self.kt(inner)),
			Type::Waker => "Waker".to_string(),
			Type::Option(inner) => format!("{}?", self.kt(inner)),
			Type::Box(inner) | Type::Ref(_, inner) => self.kt(inner),
			Type::Record(i) => self.class(&abi.record(*i)),
			Type::Enum(i) => self.class(&abi.enumeration(*i)),
			Type::Object(i) => self.class(&abi.object(*i)),
			Type::Callback(i, _) => self.class(&abi.callback(*i)),
			Type::Closure(params, ret) => {
				let params: Vec<String> = params.iter().map(|p| self.kt_param(p)).collect();
				format!("({}) -> {}", params.join(", "), self.kt(ret))
			}
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => self.class(&abi.range(ty)),
			Type::Tuple(elements) => {
				let elements: Vec<String> = elements.iter().map(|e| self.kt(e)).collect();
				self.tuple_of(elements)
			}
		}
	}

	/// The Kotlin type of a parameter of type `ty`, either way: its bytes, alone or in an
	/// `Option` or a list, are a `ByteArray`, copied.
	fn kt_param(&mut self, ty: &Type) -> String {
		match ty {
			Type::Slice | Type::Vec | Type::Bytes => "ByteArray".to_string(),
			Type::List(inner) => format!("kotlin.collections.List<{}>", self.kt_param(inner)),
			Type::Option(inner) => format!("{}?", self.kt_param(inner)),
			Type::Box(inner) | Type::Ref(_, inner) => self.kt_param(inner),
			Type::Tuple(elements) => {
				let elements: Vec<String> = elements.iter().map(|e| self.kt_param(e)).collect();
				self.tuple_of(elements)
			}
			_ => self.kt(ty),
		}
	}

	/// Kotlin statements writing the Kotlin value `e` of type `ty` into the writer `w`.
	fn write_value(&mut self, ty: &Type, w: &str, e: &str) -> String {
		let abi = self.abi;
		match ty {
			Type::Bool => format!("{w}.bool({e})"),
			Type::Int(int) => {
				let (method, _) = wire_int(*int);
				format!("{w}.{method}({})", to_signed(*int, e))
			}
			Type::F32 => format!("{w}.f32({e})"),
			Type::F64 => format!("{w}.f64({e})"),
			Type::Char => format!("{w}.i32({e})"),
			Type::Str | Type::String | Type::Path | Type::PathBuf => format!("{w}.string({e})"),
			Type::Slice | Type::Vec | Type::Bytes => format!("{w}.bytes({e})"),
			Type::Duration => format!("{w}.duration({e})"),
			Type::SocketAddr(Family::Any) => format!("{w}.socketAddr({e})"),
			Type::SocketAddr(Family::V4) => format!("{w}.socketAddrV4({e})"),
			Type::SocketAddr(Family::V6) => format!("{w}.socketAddrV6({e})"),
			Type::List(inner) => {
				let (l, v) = (self.fresh("l"), self.fresh("v"));
				let item = self.write_value(inner, w, &v);
				format!("{e}.let {{ {l} -> {w}.i32({l}.size); for ({v} in {l}) {{ {item} }} }}")
			}
			Type::Option(inner) => match inner.base() {
				Type::Object(_) => format!("{w}.handle({e}?.handle)"),
				base if Abi::is_buf(base) => self.write_value(base, w, e),
				// None is a length of -1.
				Type::List(_) => {
					let v = self.fresh("v");
					let some = self.write_value(inner, w, &v);
					format!("{e}.let {{ {v} -> if ({v} == null) {w}.i32(-1) else {some} }}")
				}
				_ => {
					let v = self.fresh("v");
					let some = self.write_value(inner, w, &v);
					format!("{e}.let {{ {v} -> if ({v} == null) {w}.bool(false) else {{ {w}.bool(true); {some} }} }}")
				}
			},
			Type::Box(inner) | Type::Ref(_, inner) => self.write_value(inner, w, e),
			Type::Record(i) => format!("w_{}({w}, {e})", abi.record(*i)),
			Type::Enum(i) => match abi.api.enums[*i].plain() {
				true => format!("{w}.i32({e}.value)"),
				false => format!("w_{}({w}, {e})", abi.enumeration(*i)),
			},
			Type::Object(_) => format!("{w}.handle({e}.handle)"),
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => format!("w_{}({w}, {e})", abi.range(ty)),
			Type::Tuple(elements) => {
				let t = self.fresh("t");
				let writes: Vec<String> = (elements.iter().enumerate())
					.map(|(k, ty)| self.write_value(ty, w, &format!("{t}.{}", ordinal(k))))
					.collect();
				format!("{e}.let {{ {t} -> {} }}", writes.join("; "))
			}
			other => unreachable!("{other:?} is never encoded"),
		}
	}

	/// A Kotlin expression reading a value of type `ty`, owned, from the reader `r`.
	fn read_value(&mut self, ty: &Type, r: &str) -> String {
		self.read(ty, r, true)
	}

	/// [`Self::read_value`], reading bytes as a `Bytes` Rust handed over if `owned`, or as
	/// a parameter's `ByteArray`, copied, if not.
	fn read(&mut self, ty: &Type, r: &str, owned: bool) -> String {
		let abi = self.abi;
		match ty {
			Type::Unit => "Unit".to_string(),
			Type::Bool => format!("{r}.bool()"),
			Type::Int(int) => {
				let (method, _) = wire_int(*int);
				from_signed(*int, &format!("{r}.{method}()"))
			}
			Type::F32 => format!("{r}.f32()"),
			Type::F64 => format!("{r}.f64()"),
			Type::Char => format!("{r}.i32()"),
			Type::Str | Type::String => format!("{r}.string()!!"),
			Type::Path | Type::PathBuf => format!("{r}.path()!!"),
			Type::Slice | Type::Vec | Type::Bytes if owned => format!("{r}.owned()!!"),
			Type::Slice | Type::Vec | Type::Bytes => format!("{r}.bytes()!!"),
			Type::Duration => format!("{r}.duration()"),
			Type::SocketAddr(_) => format!("{r}.socketAddr()"),
			Type::List(inner) => {
				let item = self.read(inner, r, owned);
				format!("kotlin.collections.List({r}.i32()) {{ {item} }}")
			}
			Type::Option(inner) => match inner.base() {
				Type::Object(i) => {
					let class = self.class(&abi.object(*i));
					format!("{r}.i64().let {{ h -> if (h == 0L) null else {class}(h) }}")
				}
				Type::Str | Type::String => format!("{r}.string()"),
				Type::Path | Type::PathBuf => format!("{r}.path()"),
				Type::List(item) => {
					let n = self.fresh("n");
					let item = self.read(item, r, owned);
					format!(
						"{r}.i32().let {{ {n} -> if ({n} < 0) null else kotlin.collections.List({n}) {{ {item} }} }}"
					)
				}
				base if Abi::is_buf(base) && owned => format!("{r}.owned()"),
				base if Abi::is_buf(base) => format!("{r}.bytes()"),
				_ => format!("(if ({r}.bool()) {} else null)", self.read(inner, r, owned)),
			},
			Type::Box(inner) | Type::Ref(_, inner) => self.read(inner, r, owned),
			Type::Record(i) => format!("r_{}({r})", abi.record(*i)),
			Type::Enum(i) => match abi.api.enums[*i].plain() {
				true => format!("{}.of({r}.i32())", self.class(&abi.enumeration(*i))),
				false => format!("r_{}({r})", abi.enumeration(*i)),
			},
			Type::Object(i) => format!("{}({r}.i64())", self.class(&abi.object(*i))),
			Type::Range(_) | Type::Bound(_) | Type::Bounds(_) => format!("r_{}({r})", abi.range(ty)),
			Type::Tuple(elements) => {
				let read: Vec<String> = elements.iter().map(|e| self.read(e, r, owned)).collect();
				match read.len() {
					2 => format!("kotlin.Pair({})", read.join(", ")),
					3 => format!("kotlin.Triple({})", read.join(", ")),
					n => format!("{}({})", self.tuple(n), read.join(", ")),
				}
			}
			other => unreachable!("{other:?} is never decoded"),
		}
	}

	/// The Kotlin value of the JNI scalar or `byte[]` `e`, of IR type `ty` and C type `c`,
	/// which Rust returned or lent. A lent object is wrapped as lent, and lent bytes are a
	/// parameter's, copied; returned bytes cross as their owner, unless text.
	fn lift(&mut self, ty: &Type, c: &Ty, e: &str, lent: bool) -> String {
		match c {
			Ty::Void => e.to_string(),
			Ty::Bool | Ty::F32 | Ty::F64 | Ty::Char => e.to_string(),
			Ty::Int(int) => from_signed(*int, e),
			Ty::Enum(name) => format!("{}.of({e})", self.class(name)),
			Ty::Handle { name, .. } => {
				let class = self.class(name);
				let wrap = |h: &str| match lent {
					true => format!("{class}({h}, true)"),
					false => format!("{class}({h})"),
				};
				match ty {
					Type::Option(_) => format!("{e}.let {{ h -> if (h == 0L) null else {} }}", wrap("h")),
					_ => wrap(e),
				}
			}
			Ty::Buf => match (decode(ty), matches!(ty, Type::Option(_)), lent) {
				(Some(decode), true, _) => format!("{e}?.{decode}"),
				(Some(decode), false, _) => format!("{e}!!.{decode}"),
				(None, true, true) => e.to_string(),
				(None, false, true) => format!("{e}!!"),
				(None, true, false) => format!("Native.owned({e})"),
				(None, false, false) => format!("Native.owned({e})!!"),
			},
			_ => {
				let r = self.fresh("r");
				let read = self.read(&strip_refs(ty), &r, !lent);
				format!("Native.Reader({e}).let {{ {r} -> {read} }}")
			}
		}
	}

	/// The Kotlin expression passing `e` back to Rust, as a callback or closure returns it:
	/// a scalar, as collect allows no other.
	fn lower_ret(c: &Ty, e: &str) -> String {
		match c {
			Ty::Int(int) => to_signed(*int, e),
			_ => e.to_string(),
		}
	}

	/// How Kotlin passes the value `e` of IR type `ty` as the C parameter `c`, named
	/// `name` in C, and how the glue takes it. `callback` names the parameter's closure
	/// trampoline, if one.
	fn arg(&mut self, ty: &Type, c: &Ty, e: &str, n: &mut usize, trampoline: Option<&str>) -> Arg {
		let abi = self.abi;
		let mut arg = Arg::default();
		let p = format!("p{n}");
		*n += 1;
		let (jni, native) = jni_type(c, ty);
		arg.jni.push(jni);
		arg.native.push(native.to_string());
		match c {
			Ty::Bool => {
				arg.exprs.push(e.to_string());
				arg.rust_args.push(p);
			}
			Ty::Int(int) => {
				arg.exprs.push(to_signed(*int, e));
				arg.rust_args.push(format!("{p} as {}", int.rust()));
			}
			Ty::F32 | Ty::F64 => {
				arg.exprs.push(e.to_string());
				arg.rust_args.push(p);
			}
			Ty::Char => {
				arg.exprs.push(e.to_string());
				arg.rust_args.push(format!("{p} as u32"));
			}
			Ty::Enum(_) => {
				arg.exprs.push(format!("{e}.value"));
				arg.rust_args.push(p);
			}
			Ty::Handle { .. } => {
				let h = self.fresh("h");
				let option = matches!(ty, Type::Option(_));
				arg.open = Some(match option {
					true => format!("Native.hold({e}?.handle) {{ {h} ->"),
					false => format!("{e}.handle.hold {{ {h} ->"),
				});
				// Taken by value, the value moves out, leaving the handle only to free.
				if moved(abi, ty) {
					arg.after.push(match option {
						true => format!("{e}?.close()"),
						false => format!("{e}.close()"),
					});
				}
				arg.exprs.push(h);
				arg.rust_args.push(format!("{p} as usize as _"));
			}
			Ty::Buf => {
				arg.exprs.push(match (string(ty), matches!(ty, Type::Option(_))) {
					(true, true) => format!("{e}?.encodeToByteArray()"),
					(true, false) => format!("{e}.encodeToByteArray()"),
					(false, _) => e.to_string(),
				});
				arg.rust_pre.push(format!("let b{p} = rt::bytes(env, {p});"));
				arg.rust_args.push(format!("rt::view(&b{p})"));
			}
			Ty::Struct(name) if matches!(ty.base(), Type::Callback(..)) => {
				arg.exprs.push(e.to_string());
				arg.rust_args.push(format!(
					"crate::{name} {{ vtable: &VTABLE_{name}, data: rt::global(env, {p}) }}"
				));
			}
			Ty::Duration | Ty::SocketAddr | Ty::Struct(_) | Ty::In(_) => {
				let w = self.fresh("w");
				// Taken by value, each object in a list moves out, as one passed alone does.
				if moved(abi, ty) {
					let close = self.close(ty, e);
					arg.after.push(close);
				}
				arg.open = Some(format!("Native.Writer().use {{ {w} ->"));
				let value = self.write_value(ty, &w, e);
				arg.inside.push(value);
				arg.exprs.push(format!("{w}.finish()"));
				arg.rust_pre.push(format!(
					"let b{p} = rt::bytes(env, {p}).unwrap_or_default();\n\t\tlet mut r{p} = rt::Reader::new(&b{p});\n\t\tlet a{p} = r{p}.get();"
				));
				arg.rust_args.push(match c {
					Ty::In(_) => format!("&a{p}"),
					_ => format!("a{p}"),
				});
			}
			Ty::Fn(..) => {
				let trampoline = trampoline.expect("a closure has its trampoline");
				arg.exprs.push(e.to_string());
				arg.rust_pre.push(format!("let g{p} = rt::Global::new(env, {p});"));
				arg.rust_args.push(format!("Some({trampoline})"));
				arg.rust_args.push(format!("g{p}.0"));
			}
			Ty::Waker => {
				arg.exprs.push(e.to_string());
				arg.rust_args.push(format!("rt::waker(env, {p})"));
			}
			Ty::Void | Ty::Future(_) | Ty::Poll | Ty::Out(_) | Ty::Data => {
				unreachable!("{c:?} is no parameter Kotlin passes")
			}
		}
		arg
	}

	fn write(&mut self) {
		let abi = self.abi;
		let api = abi.api;

		if abi.ranges.values().any(|ty| matches!(ty, Type::Bound(_))) {
			self.types.push_str(
				"/** What a range's start or end bound does: nothing, include its value, or exclude it. */\nenum class Bound {\n\tUNBOUNDED,\n\tINCLUDED,\n\tEXCLUDED,\n}\n\n",
			);
		}
		for (c, ty) in &abi.ranges.clone() {
			self.range(c, ty);
		}
		for c in abi.options.clone().keys() {
			self.glue_option(c);
		}
		for (c, elements) in &abi.tuples.clone() {
			self.glue_tuple(c, elements);
		}
		for constant in &api.constants {
			let name = self.bare(&abi.name(&constant.path)).to_uppercase();
			let (ty, value) = match constant.value {
				Literal::Bool(b) => ("Boolean".to_string(), b.to_string()),
				Literal::Int(int, v) => (kt_int(int).to_string(), int_literal(int, v)),
			};
			let _ = write!(
				self.top,
				"{}const val {name}: {ty} = {value}\n\n",
				docs(&constant.docs, "")
			);
		}
		for i in 0..api.records.len() {
			self.record(i);
		}
		for i in 0..api.enums.len() {
			self.enumeration(i);
		}
		for i in 0..api.objects.len() {
			self.object(i);
		}
		for i in 0..api.callbacks.len() {
			self.callback(i);
		}
		let mut top = Vec::new();
		for function in &api.functions {
			if let Some(code) = self.function(function, None, None, Place::Static) {
				top.push(code);
			}
		}
		for code in top {
			self.top.push_str(&code);
			self.top.push('\n');
		}
		for (name, ty) in &self.exceptions.clone() {
			let kt = self.kt(ty);
			let message = match ty {
				Type::Str | Type::String => "error",
				_ => "error.toString()",
			};
			let _ = write!(
				self.types,
				"/** A `{kt}` Rust returned as an error. */\nclass {name}(val error: {kt}) : Exception() {{\n\toverride val message: String\n\t\tget() = {message}\n}}\n\n"
			);
		}
	}

	/// A Kotlin data class for a range, bound, or pair of bounds, and its codec.
	fn range(&mut self, c: &str, ty: &Type) {
		let name = self.class(c);
		self.claim(&name, format!("`{c}`"));
		let (fields, write, read) = match ty {
			Type::Range(int) => {
				let kt = kt_int(*int);
				let (m, _) = wire_int(*int);
				(
					format!("val start: {kt}, val end: {kt}"),
					format!(
						"w.{m}({}); w.{m}({})",
						to_signed(*int, "v.start"),
						to_signed(*int, "v.end")
					),
					format!(
						"{name}({}, {})",
						from_signed(*int, &format!("r.{m}()")),
						from_signed(*int, &format!("r.{m}()"))
					),
				)
			}
			Type::Bound(int) => {
				let kt = kt_int(*int);
				let (m, _) = wire_int(*int);
				(
					format!("val kind: Bound, val value: {kt}"),
					format!("w.i32(v.kind.ordinal); w.{m}({})", to_signed(*int, "v.value")),
					format!(
						"{name}(Bound.entries[r.i32()], {})",
						from_signed(*int, &format!("r.{m}()"))
					),
				)
			}
			Type::Bounds(int) => {
				let bound = abi_bound(self.abi, *int);
				let class = self.class(&bound);
				(
					format!("val start: {class}, val end: {class}"),
					format!("w_{bound}(w, v.start); w_{bound}(w, v.end)"),
					format!("{name}(r_{bound}(r), r_{bound}(r))"),
				)
			}
			other => unreachable!("{other:?} is no range"),
		};
		let _ = write!(self.types, "data class {name}({fields})\n\n");
		let _ = write!(
			self.top,
			"internal fun w_{c}(w: Native.Writer, v: {name}) {{\n\t{write}\n}}\n\ninternal fun r_{c}(r: Native.Reader): {name} = {read}\n\n"
		);
	}

	/// The glue's codec for an option struct.
	fn glue_option(&mut self, c: &str) {
		let _ = write!(
			self.glue,
			"impl Wire for crate::{c} {{\n\tfn read(r: &mut Reader<'_>) -> Self {{\n\t\tlet some: bool = r.get();\n\t\tSelf {{ some, value: if some {{ r.get() }} else {{ unsafe {{ std::mem::zeroed() }} }} }}\n\t}}\n\n\tfn write(self, w: &mut Writer) {{\n\t\tw.put(self.some);\n\t\tif self.some {{\n\t\t\tw.put(self.value);\n\t\t}}\n\t}}\n}}\n\n"
		);
	}

	/// The glue's codec for a tuple struct, field by field.
	fn glue_tuple(&mut self, c: &str, elements: &[Type]) {
		let fields: Vec<String> = (0..elements.len()).map(|n| format!("_{n}: r.get()")).collect();
		let puts: String = (elements.iter().enumerate())
			.map(|(n, ty)| format!("\t\t{};\n", put(ty, &format!("self._{n}"))))
			.collect();
		let _ = write!(
			self.glue,
			"impl Wire for crate::{c} {{\n\tfn read(r: &mut Reader<'_>) -> Self {{\n\t\tSelf {{ {} }}\n\t}}\n\n\tfn write(self, w: &mut Writer) {{\n{puts}\t}}\n}}\n\n",
			fields.join(", ")
		);
	}

	/// The members a type's std traits export beyond Kotlin's own: `toString` from
	/// `Display`, `debug` from `Debug`, and a companion's `default` from `Default`, with
	/// `clone` and `equals` for an object. `this_c` is the C name, and `object` whether
	/// it holds a handle.
	fn traits(&mut self, ty: &Type, c: &str, t: crate::ir::Traits, body: &mut Vec<String>, statics: &mut Vec<String>) {
		let class = self.class(c);
		let bare = self.bare(c).to_string();
		let object = matches!(ty, Type::Object(_));
		// The receiver as the glue takes it: a handle, held for the call, or encoded.
		let (jni_self, native_self, open, arg, rust_self) = match object {
			true => (
				"jlong",
				"Long",
				"handle.hold { h ->".to_string(),
				"h".to_string(),
				"p0 as usize as _".to_string(),
			),
			false => {
				let write = self.write_value(ty, "w", "this");
				(
					"jbyteArray",
					"ByteArray",
					format!("Native.Writer().use {{ w ->\n\t\t{write}"),
					"w.finish()".to_string(),
					"&rt::Reader::new(&rt::bytes(env, p0).unwrap_or_default()).get()".to_string(),
				)
			}
		};
		let unary = |g: &mut Self, suffix: &str, sig: &str| {
			g.native(
				&format!("{bare}_{suffix}"),
				&[(jni_self, native_self)],
				("jbyteArray", "ByteArray?"),
				&format!("rt::owned(env, crate::{c}_{suffix}({rust_self}))"),
			);
			format!("\t{sig} = {open}\n\t\tNative.{bare}_{suffix}({arg})!!.decodeToString()\n\t}}\n")
		};
		if t.display {
			// Final, so a data class variant of a sealed class keeps it rather than making
			// its own.
			body.push(unary(self, "to_string", "final override fun toString(): String"));
		}
		if t.debug {
			body.push(unary(
				self,
				"debug",
				"/** Rust's `Debug` form. */\n\tfun debug(): String",
			));
		}
		if object && t.clone {
			self.native(
				&format!("{bare}_clone"),
				&[("jlong", "Long")],
				("jlong", "Long"),
				&format!("crate::{c}_clone(p0 as usize as _) as usize as jlong"),
			);
			body.push(format!(
				"\t/** A new handle to a clone. */\n\tfun clone(): {class} = handle.hold {{ h -> {class}(Native.{bare}_clone(h)) }}\n"
			));
		}
		if object && t.eq {
			self.native(
				&format!("{bare}_eq"),
				&[("jlong", "Long"), ("jlong", "Long")],
				("jboolean", "Boolean"),
				&format!("crate::{c}_eq(p0 as usize as _, p1 as usize as _)"),
			);
			body.push(format!(
				"\toverride fun equals(other: Any?): Boolean =\n\t\tother is {class} && handle.hold {{ a -> other.handle.hold {{ b -> Native.{bare}_eq(a, b) }} }}\n\n\t/** One for every value: Rust's `PartialEq` comes with no `Hash`. */\n\toverride fun hashCode(): Int = 0\n"
			));
		}
		if t.default {
			let (jni, native, rust, lift) = match ty {
				Type::Object(_) => (
					"jlong",
					"Long",
					format!("crate::{c}_default() as usize as jlong"),
					format!("{class}(Native.{bare}_default())"),
				),
				Type::Enum(i) if self.abi.api.enums[*i].plain() => (
					"jint",
					"Int",
					format!("crate::{c}_default()"),
					format!("{class}.of(Native.{bare}_default())"),
				),
				_ => (
					"jbyteArray",
					"ByteArray",
					format!("let mut w = rt::Writer::default();\n\t\tw.put(crate::{c}_default());\n\t\tw.array(env)"),
					self.read_value(ty, &format!("Native.Reader(Native.{bare}_default())")),
				),
			};
			self.native(&format!("{bare}_default"), &[], (jni, native), &rust);
			statics.push(format!(
				"\t\t/** Rust's `Default`. */\n\t\tfun default(): {class} = {lift}\n"
			));
		}
	}

	fn record(&mut self, i: usize) {
		let abi = self.abi;
		let record = &abi.api.records[i];
		let c = abi.record(i);
		let name = self.class(&c);
		let rust = abi.api.rust(&record.path, &record.args);
		self.claim(&name, format!("struct `{rust}`"));
		let ty = Type::Record(i);
		let fields: Vec<(String, String)> = record
			.fields
			.iter()
			.map(|f| (field_name(&f.name), self.kt(&f.ty)))
			.collect();
		let mut body = Vec::new();
		let mut statics = Vec::new();
		self.traits(&ty, &c, record.traits, &mut body, &mut statics);
		let mut members: Vec<String> = fields.iter().map(|(f, _)| format!("val {f}")).collect();
		let owner = Ty::Struct(c.clone());
		for method in &record.methods {
			let place = match method.receiver {
				Some(_) => Place::Member,
				None => Place::Static,
			};
			if let Some(code) = self.function(method, Some(&owner), Some(&ty), place) {
				match place {
					Place::Member => body.push(code),
					Place::Static => statics.push(indent(&code)),
				}
			}
		}
		members.extend(body.iter().filter_map(|b| member_name(b)));
		self.distinct(&rust, &members);
		if !statics.is_empty() {
			body.push(format!("\tcompanion object {{\n{}\t}}\n", statics.join("\n")));
		}
		let docs = docs(&record.docs, "");
		let body = match body.is_empty() {
			true => String::new(),
			false => format!(" {{\n{}}}", body.join("\n")),
		};
		match fields.is_empty() {
			true => {
				let _ = write!(
					self.types,
					"{docs}class {name} {}\n\n",
					match body.is_empty() {
						true => format!(
							"{{\n\toverride fun equals(other: Any?): Boolean = other is {name}\n\n\toverride fun hashCode(): Int = 0\n}}"
						),
						false => body.replacen(
							" {\n",
							&format!(
								" {{\n\toverride fun equals(other: Any?): Boolean = other is {name}\n\n\toverride fun hashCode(): Int = 0\n\n"
							),
							1
						),
					}
				);
			}
			false => {
				let params: Vec<String> = fields
					.iter()
					.zip(&record.fields)
					.map(|((f, kt), field)| format!("{}\tval {f}: {kt},", docs_inline(&field.docs, "\t")))
					.collect();
				let _ = write!(
					self.types,
					"{docs}data class {name}(\n{}\n){body}\n\n",
					params.join("\n")
				);
			}
		}
		// The codec.
		let writes: Vec<String> = record
			.fields
			.iter()
			.map(|f| {
				let e = format!("v.{}", field_name(&f.name));
				self.write_value(&f.ty, "w", &e)
			})
			.collect();
		let reads: Vec<String> = record.fields.iter().map(|f| self.read_value(&f.ty, "r")).collect();
		let _ = write!(
			self.top,
			"internal fun w_{c}(w: Native.Writer, v: {name}) {{\n{}}}\n\ninternal fun r_{c}(r: Native.Reader): {name} = {name}({})\n\n",
			writes.iter().map(|w| format!("\t{w}\n")).collect::<String>(),
			reads.join(", ")
		);
		let fields: Vec<String> = (0..record.fields.len()).map(|n| format!("f{n}: r.get()")).collect();
		let puts: String = record
			.fields
			.iter()
			.enumerate()
			.map(|(n, f)| format!("\t\t{};\n", put(&f.ty, &format!("self.f{n}"))))
			.collect();
		let _ = write!(
			self.glue,
			"impl Wire for crate::{c} {{\n\tfn read(r: &mut Reader<'_>) -> Self {{\n\t\tlet _ = &r;\n\t\tSelf {{ {} }}\n\t}}\n\n\tfn write(self, w: &mut Writer) {{\n\t\tlet _ = &w;\n{puts}\t}}\n}}\n\n",
			fields.join(", ")
		);
	}

	fn enumeration(&mut self, i: usize) {
		let abi = self.abi;
		let e = &abi.api.enums[i];
		let c = abi.enumeration(i);
		let name = self.class(&c);
		let rust = abi.api.rust(&e.path, &e.args);
		self.claim(&name, format!("enum `{rust}`"));
		let ty = Type::Enum(i);
		let mut body = Vec::new();
		let mut statics = Vec::new();
		self.traits(&ty, &c, e.traits, &mut body, &mut statics);
		let owner = abi.ty(&ty);
		for method in &e.methods {
			let place = match method.receiver {
				Some(_) => Place::Member,
				None => Place::Static,
			};
			if let Some(code) = self.function(method, Some(&owner), Some(&ty), place) {
				match place {
					Place::Member => body.push(code),
					Place::Static => statics.push(indent(&code)),
				}
			}
		}
		let mut members: Vec<String> = body.iter().filter_map(|b| member_name(b)).collect();
		if e.plain() {
			members.push("fun of".to_string());
			members.push("val value".to_string());
			self.distinct(&rust, &members);
			let entries: Vec<String> = e
				.variants
				.iter()
				.map(|v| format!("\t{}({}),", abi::snake(&v.name).to_uppercase(), v.discriminant))
				.collect();
			let cases: Vec<String> = e
				.variants
				.iter()
				.map(|v| format!("\t\t\t{} -> {}", v.discriminant, abi::snake(&v.name).to_uppercase()))
				.collect();
			statics.push(format!(
				"\t\tinternal fun of(value: Int): {name} = when (value) {{\n{}\n\t\t\telse -> error(\"{c}: an invalid value\")\n\t\t}}\n",
				cases.join("\n")
			));
			let entries = entries.join("\n");
			let entries = entries.strip_suffix(',').unwrap_or(&entries);
			let _ = write!(
				self.types,
				"{}enum class {name}(internal val value: Int) {{\n{entries};\n\n{}\tcompanion object {{\n{}\t}}\n}}\n\n",
				docs(&e.docs, ""),
				body.iter().map(|b| format!("{b}\n")).collect::<String>(),
				statics.join("\n")
			);
			return;
		}
		let mut variants = Vec::new();
		let mut writes = Vec::new();
		let mut reads = Vec::new();
		let mut glue_reads = Vec::new();
		let mut glue_writes = Vec::new();
		for (n, variant) in e.variants.iter().enumerate() {
			let vname = pascal(&abi::snake(&variant.name));
			members.push(format!("class {vname}"));
			let fields: Vec<String> = variant
				.fields
				.iter()
				.map(|f| format!("val {}: {}", field_name(&f.name), self.kt(&f.ty)))
				.collect();
			let mut write = vec![format!("w.i32({n})")];
			for f in &variant.fields {
				let e = format!("v.{}", field_name(&f.name));
				write.push(self.write_value(&f.ty, "w", &e));
			}
			let read: Vec<String> = variant.fields.iter().map(|f| self.read_value(&f.ty, "r")).collect();
			match variant.fields.is_empty() {
				true => {
					variants.push(format!("\tdata object {vname} : {name}()\n"));
					writes.push(format!("\t\t{name}.{vname} -> {}", write.join("\n\t\t")));
					reads.push(format!("\t\t{n} -> {name}.{vname}"));
					glue_reads.push(format!(
						"\t\t\t{n} => Self {{ tag, u: unsafe {{ std::mem::zeroed() }} }},"
					));
				}
				false => {
					variants.push(format!("\tdata class {vname}({}) : {name}()\n", fields.join(", ")));
					writes.push(format!(
						"\t\tis {name}.{vname} -> {{\n\t\t\t{}\n\t\t}}",
						write.join("\n\t\t\t")
					));
					reads.push(format!("\t\t{n} -> {name}.{vname}({})", read.join(", ")));
					let payload = format!("{c}_{}", abi::snake(&variant.name));
					let fields: Vec<String> = (0..variant.fields.len()).map(|k| format!("f{k}: r.get()")).collect();
					glue_reads.push(format!(
						"\t\t\t{n} => Self {{ tag, u: crate::{c}_union {{ v{n}: crate::{payload} {{ {} }} }} }},",
						fields.join(", ")
					));
					let puts: Vec<String> = variant
						.fields
						.iter()
						.enumerate()
						.map(|(k, f)| format!("{};", put(&f.ty, &format!("p.f{k}"))))
						.collect();
					glue_writes.push(format!(
						"\t\t\t{n} => {{\n\t\t\t\tlet p = unsafe {{ self.u.v{n} }};\n\t\t\t\t{}\n\t\t\t}}",
						puts.join("\n\t\t\t\t")
					));
				}
			}
		}
		self.distinct(&rust, &members);
		if !statics.is_empty() {
			body.push(format!("\tcompanion object {{\n{}\t}}\n", statics.join("\n")));
		}
		let mut all = variants;
		all.extend(body);
		let _ = write!(
			self.types,
			"{}sealed class {name} {{\n{}}}\n\n",
			docs(&e.docs, ""),
			all.join("\n")
		);
		let _ = write!(
			self.top,
			"internal fun w_{c}(w: Native.Writer, v: {name}) {{\n\twhen (v) {{\n{}\n\t}}\n}}\n\ninternal fun r_{c}(r: Native.Reader): {name} = when (r.i32()) {{\n{}\n\telse -> error(\"{c}: an invalid tag\")\n}}\n\n",
			writes.join("\n"),
			reads.join("\n").replace("\t\t", "\t")
		);
		let _ = write!(
			self.glue,
			"impl Wire for crate::{c} {{\n\tfn read(r: &mut Reader<'_>) -> Self {{\n\t\tlet tag: i32 = r.get();\n\t\tmatch tag {{\n{}\n\t\t\t_ => crate::rt::fail(\"jni\", \"an enum's tag is invalid\"),\n\t\t}}\n\t}}\n\n\tfn write(self, w: &mut Writer) {{\n\t\tw.put(self.tag);\n\t\tmatch self.tag {{\n{}\n\t\t\t_ => {{}}\n\t\t}}\n\t}}\n}}\n\n",
			glue_reads.join("\n"),
			glue_writes.join("\n")
		);
	}

	fn object(&mut self, i: usize) {
		let abi = self.abi;
		let object = &abi.api.objects[i];
		let c = abi.object(i);
		let name = self.class(&c);
		let bare = self.bare(&c).to_string();
		let rust = abi.api.rust(&object.path, &object.args);
		self.claim(&name, format!("type `{rust}`"));
		let ty = Type::Object(i);
		self.native(
			&format!("{bare}_free"),
			&[("jlong", "Long")],
			("()", "Unit"),
			&format!("crate::{c}_free(p0 as usize as _)"),
		);
		let mut body = vec![format!(
			"\tinternal val handle = Native.Handle(this, raw, if (lent) null else Native.Drop {{ Native.{bare}_free(it) }}, \"{name}\")\n\n\t/** Free the handle once no call holds it: a call after this throws. */\n\toverride fun close() = handle.close()\n"
		)];
		let mut statics = Vec::new();
		self.traits(&ty, &c, object.traits, &mut body, &mut statics);
		let owner = Ty::Handle {
			name: c.clone(),
			constant: false,
		};
		for method in &object.methods {
			let place = match method.receiver {
				Some(_) => Place::Member,
				None => Place::Static,
			};
			if let Some(code) = self.function(method, Some(&owner), Some(&ty), place) {
				match place {
					Place::Member => body.push(code),
					Place::Static => statics.push(indent(&code)),
				}
			}
		}
		let mut members: Vec<String> = body.iter().filter_map(|b| member_name(b)).collect();
		members.extend(statics.iter().filter_map(|s| member_name(s)));
		self.distinct(&rust, &members);
		if !statics.is_empty() {
			body.push(format!("\tcompanion object {{\n{}\t}}\n", statics.join("\n")));
		}
		let text = format!("{rust}\n\n{}", object.docs);
		let _ = write!(
			self.types,
			"{}class {name} internal constructor(raw: Long, lent: Boolean = false) : AutoCloseable {{\n{}}}\n\n",
			docs(text.trim(), ""),
			body.join("\n")
		);
	}

	fn callback(&mut self, i: usize) {
		let abi = self.abi;
		let callback = &abi.api.callbacks[i];
		let c = abi.callback(i);
		let name = self.class(&c);
		let bare = self.bare(&c).to_string();
		let rust = callback.path.join("::");
		self.claim(&name, format!("trait `{rust}`"));
		let mut body = Vec::new();
		let mut table = vec!["free: Some(rt::free_callback)".to_string()];
		let mut members = Vec::new();
		for (n, method) in callback.methods.iter().enumerate() {
			let member = member(&abi::snake(method.name()), &[]);
			members.push(format!("fun {member}"));
			let params: Vec<String> = method
				.params
				.iter()
				.map(|p| format!("{}: {}", kw(&camel(&p.name)), self.kt_param(&p.ty)))
				.collect();
			let ret = self.kt(&method.ok);
			body.push(format!(
				"{}\tfun {member}({}){}",
				docs(&method.docs, "\t"),
				params.join(", "),
				match method.ok {
					Type::Unit => String::new(),
					_ => format!(": {ret}"),
				}
			));
			let c_params: Vec<Ty> = method.params.iter().map(|p| abi.ty(&p.ty)).collect();
			let c_ret = abi.ty(&method.ok);
			let lent: Vec<Type> = method.params.iter().map(|p| p.ty.clone()).collect();
			let dispatcher = format!("{bare}__{}", abi::snake(method.name()));
			let trampoline = format!("kt_{c}_{n}");
			self.trampoline(
				&trampoline,
				&dispatcher,
				&format!("{rust}::{}", method.name()),
				(&lent, &method.ok),
				(&c_params, &c_ret),
				(&name, Some(&member)),
			);
			table.push(format!("{}: Some({trampoline})", method.name()));
		}
		self.distinct(&rust, &members);
		let text = format!(
			"{rust}: implemented in Kotlin. Rust calls its methods from any thread, and once it\ndrops the implementation, closes it if it is `AutoCloseable`.\n\n{}",
			callback.docs
		);
		let _ = write!(
			self.types,
			"{}interface {name} {{\n{}\n}}\n\n",
			docs(text.trim(), ""),
			body.join("\n\n")
		);
		let _ = write!(
			self.glue,
			"static VTABLE_{c}: crate::{c}_vtable = crate::{c}_vtable {{ {} }};\n\n",
			table.join(", ")
		);
	}

	/// The Rust function C calls for a callback's method or a closure, named `trampoline`,
	/// which calls the Kotlin dispatcher `dispatcher` with the Kotlin value Rust holds:
	/// for a callback, an implementation of the interface `cast` whose method `method` it
	/// calls, and for a closure, a value of the function type `cast`.
	fn trampoline(
		&mut self,
		trampoline: &str,
		dispatcher: &str,
		what: &str,
		(lent, ret): (&[Type], &Type),
		(c_params, c_ret): (&[Ty], &Ty),
		(cast, method): (&str, Option<&str>),
	) {
		self.dispatchers.push(dispatcher.to_string());
		let mut rust_params = vec!["data: *mut c_void".to_string()];
		let mut jvalues = vec!["jvalue { l: data.cast() }".to_string()];
		let mut kt_params = vec!["o: Any".to_string()];
		let mut sig = String::from("(Ljava/lang/Object;");
		let mut pre = Vec::new();
		let mut args = Vec::new();
		let mut finally = Vec::new();
		for (k, (ty, c)) in lent.iter().zip(c_params).enumerate() {
			let rust_ty = rust_c(self.abi, c);
			rust_params.push(format!("p{k}: {rust_ty}"));
			let (jni, native) = jni_type(c, ty);
			sig.push_str(descriptor(jni));
			kt_params.push(format!("p{k}: {native}"));
			let (field, value) = match c {
				Ty::Bool => ("z", format!("p{k}")),
				Ty::Int(int) => (jvalue_field(jni), format!("p{k} as {}", jni_int(*int))),
				Ty::F32 => ("f", format!("p{k}")),
				Ty::F64 => ("d", format!("p{k}")),
				Ty::Char => ("i", format!("p{k} as jint")),
				Ty::Enum(_) => ("i", format!("p{k}")),
				Ty::Handle { .. } => ("j", format!("p{k} as usize as jlong")),
				Ty::Buf => ("l", format!("unsafe {{ rt::lent(env, p{k}) }}")),
				_ => (
					"l",
					format!("{{ let mut w = rt::Writer::default(); w.put(p{k}); w.array(env) }}"),
				),
			};
			jvalues.push(format!("jvalue {{ {field}: {value} }}"));
			match c {
				Ty::Handle { .. } => {
					let l = format!("l{k}");
					let lifted = self.lift(ty, c, &format!("p{k}"), true);
					pre.push(format!("val {l} = {lifted}"));
					finally.push(format!("{l}.handle.close()"));
					args.push(l);
				}
				_ => args.push(self.lift(ty, c, &format!("p{k}"), true)),
			}
		}
		sig.push(')');
		let (ret_jni, ret_native) = jni_type(c_ret, ret);
		sig.push_str(descriptor(ret_jni));
		let call_kind = call_method(ret_jni);
		let rust_ret = rust_c(self.abi, c_ret);
		let back = match c_ret {
			Ty::Void => String::new(),
			Ty::Bool => "ret".to_string(),
			Ty::Int(int) => format!("ret as {}", int.rust()),
			Ty::F32 | Ty::F64 => "ret".to_string(),
			Ty::Char => "ret as u32".to_string(),
			_ => unreachable!("a callback returns only scalars"),
		};
		let invoke = format!(
			"let ret = unsafe {{ ((**env).v1_2.CallStatic{call_kind}MethodA)(env, rt::class(), id, args.as_ptr()) }};"
		);
		let _ = write!(
			self.glue,
			"static M_{trampoline}: OnceLock<usize> = OnceLock::new();\n\nunsafe extern \"C\" fn {trampoline}({}) -> {rust_ret} {{\n\trt::upcall(\"{what}\", |env| {{\n\t\tlet id = rt::method(env, &M_{trampoline}, c\"{dispatcher}\", c\"{sig}\");\n\t\tlet args = [{}];\n\t\t{invoke}\n\t\tlet _ = &ret;\n\t\t{back}\n\t}})\n}}\n\n",
			rust_params.join(", "),
			jvalues.join(", ")
		);
		let call = match method {
			Some(method) => format!("o.{method}"),
			None => "o".to_string(),
		};
		let result = format!("{call}({})", args.join(", "));
		let lowered = Self::lower_ret(c_ret, &result);
		let ret_decl = match c_ret {
			Ty::Void => String::new(),
			_ => format!(": {ret_native}"),
		};
		// A closure's function type is erased, so the cast cannot check it.
		let cast_line = match method {
			Some(_) => format!("\t\tval o = o as {cast}\n"),
			None => format!("\t\t@Suppress(\"UNCHECKED_CAST\")\n\t\tval o = o as {cast}\n"),
		};
		let body = match finally.is_empty() {
			true => format!("{cast_line}\t\treturn {lowered}"),
			false => format!(
				"{cast_line}\t\t{}\n\t\ttry {{\n\t\t\treturn {lowered}\n\t\t}} finally {{\n\t\t\t{}\n\t\t}}",
				pre.join("\n\t\t"),
				finally.join("\n\t\t\t")
			),
		};
		let body = match c_ret {
			Ty::Void => body.replacen("return ", "", 1),
			_ => body,
		};
		let _ = write!(
			self.natives,
			"\t@JvmStatic private fun {dispatcher}({}){ret_decl} {{\n{body}\n\t}}\n\n",
			kt_params.join(", ")
		);
	}

	/// A native method `bare`, taking `params` and returning `ret` (JNI type, Kotlin
	/// type), whose glue runs `body` with each parameter named `p0`, `p1`, ...
	fn native(&mut self, bare: &str, params: &[(&str, &str)], ret: (&str, &str), body: &str) {
		let kt: Vec<String> = params
			.iter()
			.enumerate()
			.map(|(n, (_, k))| format!("p{n}: {k}"))
			.collect();
		let _ = write!(
			self.natives,
			"\t@JvmStatic external fun {bare}({}): {}\n\n",
			kt.join(", "),
			ret.1
		);
		let rust: Vec<String> = params
			.iter()
			.enumerate()
			.map(|(n, (j, _))| format!("p{n}: {j}"))
			.collect();
		let mut all = vec!["env: *mut JNIEnv".to_string(), "_: jclass".to_string()];
		all.extend(rust);
		let _ = write!(
			self.glue,
			"#[unsafe(no_mangle)]\npub unsafe extern \"system\" fn Java_{}_Native_{}({}) -> {} {{\n\tlet _ = env;\n\tunsafe {{\n\t\t{body}\n\t}}\n}}\n\n",
			mangle(&self.abi.prefix),
			mangle(bare),
			all.join(", "),
			ret.0
		);
	}

	/// Check that no two members of the type `rust` share a Kotlin name.
	fn distinct(&mut self, rust: &str, members: &[String]) {
		let mut seen = BTreeSet::new();
		for member in members {
			if !seen.insert(member) {
				let name = member.split(' ').next_back().unwrap_or(member);
				self.errors.push(format!(
					"two members of `{rust}` are both `{name}` in Kotlin: rename one in the config"
				));
			}
		}
	}

	/// `function`'s Kotlin form, a member of `owner` (whose IR type is `owner_ty`) if it
	/// has one, with its native methods and glue.
	fn function(
		&mut self,
		function: &Function,
		owner: Option<&Ty>,
		owner_ty: Option<&Type>,
		place: Place,
	) -> Option<String> {
		let abi = self.abi;
		let export = abi.export(function, owner);
		let c_name = export.call.name.clone();
		let bare = self.bare(&c_name).to_string();
		let owner_c = match owner {
			Some(Ty::Struct(n) | Ty::Enum(n) | Ty::Handle { name: n, .. }) => Some(n.clone()),
			_ => None,
		};
		let own = match &owner_c {
			Some(o) => c_name.strip_prefix(o.as_str()).and_then(|r| r.strip_prefix('_')),
			None => None,
		};
		let reserved: &[&str] = match owner_ty {
			Some(Type::Object(_)) => &["close", "equals", "hashCode", "toString", "handle"],
			Some(Type::Record(_)) => &["copy", "equals", "hashCode", "toString"],
			// A plain enum is a Kotlin enum, which has its own.
			Some(Type::Enum(i)) if abi.api.enums[*i].plain() => &[
				"equals",
				"hashCode",
				"toString",
				"of",
				"value",
				"name",
				"ordinal",
				"compareTo",
			],
			Some(_) => &["equals", "hashCode", "toString"],
			None => &[],
		};
		let snake = own.unwrap_or(&bare);
		let member = member(snake, reserved);

		let mut n = 0;
		let mut args: Vec<Arg> = Vec::new();
		let mut c_params = export.call.params.iter();
		let receiver = function.receiver.filter(|_| owner.is_some());
		if let Some(receiver) = receiver {
			let (_, c) = c_params.next().expect("a method has its receiver");
			let ty = owner_ty.expect("a method has its type").clone();
			let mut arg = match c {
				Ty::Handle { .. } => {
					let mut arg = Arg::default();
					let p = format!("p{n}");
					n += 1;
					arg.jni.push("jlong");
					arg.native.push("Long".to_string());
					arg.open = Some("handle.hold { h ->".to_string());
					arg.exprs.push("h".to_string());
					arg.rust_args.push(format!("{p} as usize as _"));
					let copy = matches!(ty, Type::Object(i) if abi.api.objects[i].copy);
					if receiver == Receiver::Owned && !copy {
						arg.after.push("close()".to_string());
					}
					arg
				}
				_ => self.arg(&ty, c, "this", &mut n, None),
			};
			arg.native.truncate(1);
			args.push(arg);
		}
		let mut kt_params = Vec::new();
		let mut closures = Vec::new();
		for param in &function.params {
			let (_, c) = c_params.next().expect("each parameter has its C one");
			let name = kw(&camel(&param.name));
			kt_params.push(format!("{name}: {}", self.kt_param(&param.ty)));
			let trampoline = match (&param.ty, c) {
				(Type::Closure(..), Ty::Fn(..)) => {
					c_params.next().expect("a closure has its data");
					let t = format!("kt_{c_name}_{}", abi::escape(&param.name));
					closures.push((param, c.clone(), t.clone()));
					Some(t)
				}
				_ => None,
			};
			args.push(self.arg(&param.ty, c, &name, &mut n, trampoline.as_deref()));
		}
		for (param, c, trampoline) in closures {
			let (Type::Closure(lent, ret), Ty::Fn(c_lent, c_ret)) = (&param.ty, &c) else {
				unreachable!()
			};
			let kt = self.kt(&param.ty);
			let dispatcher = format!("{bare}__{}", abi::snake(&param.name));
			self.trampoline(
				&trampoline,
				&dispatcher,
				&c_name,
				(lent, ret),
				(c_lent, c_ret),
				(&kt, None),
			);
		}
		let outs: Vec<(String, Ty)> = c_params.cloned().collect();

		let native_params: Vec<(&str, String)> = args
			.iter()
			.flat_map(|a| a.jni.iter().copied().zip(a.native.iter().cloned()))
			.collect();
		let mut exprs: Vec<String> = args.iter().flat_map(|a| a.exprs.clone()).collect();
		// A future's call also takes the signal its waker parks, if its first poll pends.
		let signal = export.future.is_some().then(|| self.fresh("s"));
		exprs.extend(signal.clone());
		let rust_pre: Vec<String> = args.iter().flat_map(|a| a.rust_pre.clone()).collect();
		let rust_args: Vec<String> = args.iter().flat_map(|a| a.rust_args.clone()).collect();
		let after: Vec<String> = args.iter().flat_map(|a| a.after.clone()).collect();

		// A tuple of one returned whole is its element, written through its one out pointer;
		// one behind a reference or `Box` is returned as a struct, so stays a tuple.
		let ok = match &function.ok {
			Type::Tuple(elements) if elements.len() == 1 => strip_refs(&elements[0]),
			ok => strip_refs(ok),
		};
		let ret_kt = self.kt(&ok);
		let err = function.err.as_ref().map(strip_refs);
		let exception = err.as_ref().map(|e| {
			let kt = self.kt(e);
			let name = format!("{}Exception", kt.replace(['?', '<', '>', ',', ' ', '.'], ""));
			if !self.exceptions.contains_key(&name) {
				self.claim(&name, format!("the exception of `{kt}`"));
				self.exceptions.insert(name.clone(), e.clone());
			}
			name
		});
		// The native call, closing what it moves out once it returns.
		let call = match after.is_empty() {
			true => format!("Native.{bare}({})", exprs.join(", ")),
			false => format!("Native.{bare}({}).also {{ {} }}", exprs.join(", "), after.join("; ")),
		};
		// The value the function returns, or, returning nothing, its statement.
		let value;
		// The C call, with the out pointers after its arguments.
		let rust_call = |outs: &[String]| {
			let args: Vec<&String> = rust_args.iter().chain(outs).collect();
			let args: Vec<&str> = args.iter().map(|a| a.as_str()).collect();
			format!("crate::{c_name}({})", args.join(", "))
		};
		if let Some((_, poll, free)) = &export.future {
			// The call makes the future and polls it once, returning its result if ready, or
			// else the future, which a native poll and free take.
			let poll_bare = self.bare(&poll.name).to_string();
			let free_bare = self.bare(&free.name).to_string();
			let poll_outs: Vec<(String, Ty)> = poll.params[2..].to_vec();
			let (decl, ptrs, write) = self.glue_outs(&poll_outs, &function.ok, function.err.as_ref());
			let ok_set = match function.err.is_some() {
				true => "let ok = ret == 1;\n\t",
				false => "",
			};
			let _ = write!(
				self.glue,
				"unsafe fn jni_{}(f: *mut c_void, waker: crate::rt::Waker, w: &mut rt::Writer) -> bool {{\n\tlet _ = &w;\n\tunsafe {{\n\t{decl}\n\tlet ret = crate::{}(f as _, waker{});\n\tif ret == 0 {{\n\t\treturn false;\n\t}}\n\t{ok_set}{write}\n\ttrue\n\t}}\n}}\n\nunsafe fn jni_{}(f: *mut c_void) {{\n\tunsafe {{ crate::{}(f as _) }}\n}}\n\n",
				poll.name,
				poll.name,
				ptrs.iter().map(|p| format!(", {p}")).collect::<String>(),
				free.name,
				free.name,
			);
			let mut params: Vec<(&str, &str)> = native_params.iter().map(|(j, k)| (*j, k.as_str())).collect();
			params.push(("jobject", "Waker"));
			let p_signal = format!("p{}", params.len() - 1);
			self.native(
				&bare,
				&params,
				("jbyteArray", "ByteArray"),
				&format!(
					"{}\n\t\tlet f = {};\n\t\trt::start(env, f.cast(), {p_signal}, jni_{}, jni_{})",
					rust_pre.join("\n\t\t"),
					rust_call(&[]),
					poll.name,
					free.name,
				),
			);
			self.native(
				&poll_bare,
				&[("jlong", "Long"), ("jlong", "Long")],
				("jbyteArray", "ByteArray?"),
				&format!("rt::poll(env, p0 as usize as _, p1 as usize as _, jni_{})", poll.name),
			);
			self.native(
				&free_bare,
				&[("jlong", "Long")],
				("()", "Unit"),
				&format!("jni_{}(p0 as usize as _)", free.name),
			);
			let lines = self.lift_result(&ok, err.as_ref(), exception.as_deref(), "r");
			let lambda = match lines.is_empty() {
				true => "{}".to_string(),
				false => format!(
					"{{ r ->\n{}}}",
					lines.iter().map(|l| format!("\t{l}\n")).collect::<String>()
				),
			};
			value = format!(
				"Native.Signal().let {{ {s} ->\n\tNative.await({call}, {s}, {{ f, n -> Native.{poll_bare}(f, n) }}, {{ Native.{free_bare}(it) }}) {}\n}}",
				lambda.replace('\n', "\n\t"),
				s = signal.as_deref().expect("a future takes a signal"),
			);
		} else if !outs.is_empty() {
			let (decl, ptrs, write) = self.glue_outs(&outs, &function.ok, function.err.as_ref());
			let params: Vec<(&str, &str)> = native_params.iter().map(|(j, k)| (*j, k.as_str())).collect();
			// Only a result's write reads whether it returned ok.
			let ret_set = match function.err.is_some() {
				true => "let ok = ",
				false => "",
			};
			self.native(
				&bare,
				&params,
				("jbyteArray", "ByteArray"),
				&format!(
					"{}\n\t\t{decl}\n\t\t{ret_set}{};\n\t\tlet mut w = rt::Writer::default();\n\t\t{write}\n\t\tw.array(env)",
					rust_pre.join("\n\t\t"),
					rust_call(&ptrs)
				),
			);
			let lines = self.lift_result(&ok, err.as_ref(), exception.as_deref(), "r");
			value = match lines.is_empty() {
				true => call,
				false => format!(
					"Native.Reader({call}).let {{ r ->\n{}}}",
					lines.iter().map(|l| format!("\t{l}\n")).collect::<String>()
				),
			};
		} else {
			let c_ret = export.call.ret.clone();
			let (jni, native) = match c_ret {
				// Bytes cross copied or as their owner.
				Ty::Buf if !string(&ok) => ("jobject", "Any?"),
				_ => jni_type(&c_ret, &ok),
			};
			let params: Vec<(&str, &str)> = native_params.iter().map(|(j, k)| (*j, k.as_str())).collect();
			let ret_expr = match &c_ret {
				Ty::Void => "ret".to_string(),
				Ty::Bool => "ret".to_string(),
				Ty::Int(int) => format!("ret as {}", jni_int(*int)),
				Ty::F32 | Ty::F64 => "ret".to_string(),
				Ty::Char => "ret as jint".to_string(),
				Ty::Enum(_) => "ret".to_string(),
				Ty::Handle { .. } => "ret as usize as jlong".to_string(),
				Ty::Buf if string(&ok) => "rt::owned(env, ret)".to_string(),
				Ty::Buf => "rt::hand(env, ret)".to_string(),
				_ => format!(
					"{{ let mut w = rt::Writer::default(); {}; w.array(env) }}",
					put(&ok, "ret")
				),
			};
			self.native(
				&bare,
				&params,
				(jni, native),
				&format!(
					"{}\n\t\tlet ret = {};\n\t\t{ret_expr}",
					rust_pre.join("\n\t\t"),
					rust_call(&[])
				),
			);
			value = match ok {
				Type::Unit => call,
				_ => self.lift(&ok, &c_ret, &call, false),
			};
		}

		// Wrap the value in each argument's holds, innermost last.
		let mut code = value;
		for arg in args.iter().rev() {
			let mut inner = arg.inside.clone();
			inner.push(code);
			code = match &arg.open {
				Some(open) => format!("{open}\n{}\n}}", indent_by(&inner.join("\n"), 1)),
				None => inner.join("\n"),
			};
		}

		let mut text = function.docs.clone();
		for param in &function.params {
			if let Type::Closure(lent, _) = &param.ty {
				let name = kw(&camel(&param.name));
				text.push_str(&format!(
					"\n\nRust calls `{name}` only during the call, from any thread."
				));
				if lent.iter().any(|p| matches!(p.base(), Type::Object(_))) {
					text.push_str(&format!(
						"\nAn object it lends lives only for that call of `{name}`: keep none past it."
					));
				}
			}
		}
		let suspend = match export.future {
			Some(_) => "suspend ",
			None => "",
		};
		let ret = match ok {
			Type::Unit => String::new(),
			_ => format!(": {ret_kt}"),
		};
		let (head, member, getter) = match (function.access, place, receiver) {
			(Access::Field { .. }, Place::Member, _) | (Access::Const, _, None) if function.params.is_empty() => {
				let prop = match function.access {
					Access::Const => member.to_uppercase(),
					_ => member,
				};
				(format!("val {prop}{ret}\n\tget()"), format!("val {prop}"), true)
			}
			_ => (
				format!("{suspend}fun {member}({}){ret}", kt_params.join(", ")),
				format!("fun {member}"),
				false,
			),
		};
		let top = owner.is_none();
		if top {
			self.claim(
				&member.replace("fun ", "").replace("val ", ""),
				format!("fn `{}`", function.path.join("::")),
			);
		}
		let indent_level = match top {
			true => 0,
			false => 1,
		};
		let code = match ok {
			Type::Unit => format!("{head} {{\n{}\n}}", indent_by(&code, 1)),
			// A getter's body continues a line below its property's.
			_ if getter => format!("{head} = {}", code.replace('\n', "\n\t")),
			_ => format!("{head} = {code}"),
		};
		let code = format!("{}{code}\n", docs(text.trim(), ""));
		Some(indent_by(&code, indent_level))
	}

	/// The Kotlin statement closing each object the value `e` of type `ty` holds, once a
	/// call moved them out.
	fn close(&mut self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Option(inner) => {
				let v = self.fresh("v");
				let close = self.close(inner, &v);
				format!("{e}?.let {{ {v} -> {close} }}")
			}
			Type::Box(inner) => self.close(inner, e),
			Type::Tuple(elements) => {
				let t = self.fresh("t");
				let closes: Vec<String> = (elements.iter().enumerate())
					.filter(|(_, ty)| moved(self.abi, ty))
					.map(|(k, ty)| self.close(ty, &format!("{t}.{}", ordinal(k))))
					.collect();
				format!("{e}.let {{ {t} -> {} }}", closes.join("; "))
			}
			Type::List(inner) => {
				let v = self.fresh("v");
				let close = self.close(inner, &v);
				format!("{e}.forEach {{ {v} -> {close} }}")
			}
			_ => format!("{e}.close()"),
		}
	}

	/// The glue's out values for `outs`, of a function returning `ok` or `err`, the
	/// pointers the C call takes after its parameters, and the statements writing them,
	/// `ok` saying whether it returned ok.
	fn glue_outs(&mut self, outs: &[(String, Ty)], ok: &Type, err_ty: Option<&Type>) -> (String, Vec<String>, String) {
		let mut decl = Vec::new();
		let mut ptrs = Vec::new();
		let mut oks = Vec::new();
		let mut err = String::new();
		// Each out's type, in the order the C ABI lists them.
		let types: Vec<&Type> = match ok {
			Type::Unit => Vec::new(),
			Type::Tuple(elements) => elements.iter().collect(),
			ok => vec![ok],
		};
		let types = types.into_iter().chain(err_ty);
		for ((name, _), ty) in outs.iter().zip(types) {
			decl.push(format!("let mut o_{name} = MaybeUninit::zeroed();"));
			ptrs.push(format!("o_{name}.as_mut_ptr()"));
			let put = format!("{};", put(ty, &format!("o_{name}.assume_init()")));
			match name.as_str() {
				"err" => err = put,
				_ => oks.push(put),
			}
		}
		let write = match err_ty.is_some() {
			true => format!(
				"w.put(ok);\n\t\tif ok {{\n\t\t\t{}\n\t\t}} else {{\n\t\t\t{err}\n\t\t}}",
				oks.join("\n\t\t\t")
			),
			false => oks.join("\n\t\t"),
		};
		(decl.join("\n\t\t"), ptrs, write)
	}

	/// Kotlin statements reading a result from the reader `r`: throwing its error, then
	/// reading its value.
	fn lift_result(&mut self, ok: &Type, err: Option<&Type>, exception: Option<&str>, r: &str) -> Vec<String> {
		let mut lines = Vec::new();
		if let (Some(err), Some(exception)) = (err, exception) {
			let e = self.read_value(err, r);
			lines.push(format!("if (!{r}.bool()) throw {exception}({e})"));
		}
		if *ok != Type::Unit {
			lines.push(self.read_value(ok, r));
		}
		lines
	}
}

/// The glue's statement writing the C value `e` of IR type `ty`, which Rust returns: its
/// bytes cross as their owner.
fn put(ty: &Type, e: &str) -> String {
	match bytes(ty) {
		true => format!("w.put(rt::Owned({e}))"),
		false => format!("w.put({e})"),
	}
}

/// Whether `ty` is bytes, alone or in an `Option` or a list.
fn bytes(ty: &Type) -> bool {
	match ty {
		Type::Slice | Type::Vec | Type::Bytes => true,
		Type::Option(inner) | Type::Box(inner) | Type::Ref(_, inner) | Type::List(inner) => bytes(inner),
		_ => false,
	}
}

/// Whether passing `ty` moves an object's value out: by value, boxed, or in an `Option`,
/// unless `Copy`, and never through a reference.
fn moved(abi: &Abi<'_>, ty: &Type) -> bool {
	match ty {
		Type::Object(i) => !abi.api.objects[*i].copy,
		Type::Option(inner) | Type::Box(inner) | Type::List(inner) => moved(abi, inner),
		Type::Tuple(elements) => elements.iter().any(|ty| moved(abi, ty)),
		_ => false,
	}
}

/// Whether `ty` crosses as a buffer of UTF-8 text, or none.
fn string(ty: &Type) -> bool {
	decode(ty).is_some()
}

/// How Kotlin decodes the buffer of text `ty` crosses as, if it is text: a path, which on
/// Unix may hold any bytes, throws on those no `String` holds.
fn decode(ty: &Type) -> Option<&'static str> {
	match ty {
		Type::Option(inner) => decode(inner),
		ty => match ty.base() {
			Type::Str | Type::String => Some("decodeToString()"),
			Type::Path | Type::PathBuf => Some("decodeToString(throwOnInvalidSequence = true)"),
			_ => None,
		},
	}
}

/// The bound struct of `int`'s pairs of bounds.
fn abi_bound(abi: &Abi<'_>, int: Int) -> String {
	abi.range(&Type::Bound(int))
}

/// The JNI type and the Kotlin native type of the C type `c`, of IR type `ty`.
fn jni_type(c: &Ty, ty: &Type) -> (&'static str, &'static str) {
	match c {
		Ty::Void => ("()", "Unit"),
		Ty::Bool => ("jboolean", "Boolean"),
		Ty::Int(int) => match jni_int(*int) {
			"jbyte" => ("jbyte", "Byte"),
			"jshort" => ("jshort", "Short"),
			"jint" => ("jint", "Int"),
			_ => ("jlong", "Long"),
		},
		Ty::F32 => ("jfloat", "Float"),
		Ty::F64 => ("jdouble", "Double"),
		Ty::Char | Ty::Enum(_) => ("jint", "Int"),
		Ty::Handle { .. } | Ty::Future(_) => ("jlong", "Long"),
		Ty::Buf => ("jbyteArray", "ByteArray?"),
		Ty::Struct(_) if matches!(ty.base(), Type::Callback(..)) => ("jobject", "Any"),
		Ty::Duration | Ty::SocketAddr | Ty::Struct(_) | Ty::In(_) => ("jbyteArray", "ByteArray"),
		Ty::Fn(..) => ("jobject", "Any"),
		Ty::Waker => ("jobject", "Waker"),
		Ty::Poll | Ty::Out(_) | Ty::Data => unreachable!("{c:?} never crosses JNI"),
	}
}

/// The JVM descriptor of a JNI type.
