/// The Rust type the C ABI's Rust side spells the C type `c` as, for a trampoline.
pub(crate) fn rust_c(abi: &Abi<'_>, c: &Ty) -> String {
	match c {
		Ty::Void => "()".to_string(),
		Ty::Bool => "bool".to_string(),
		Ty::Int(int) => int.rust().to_string(),
		Ty::F32 => "f32".to_string(),
		Ty::F64 => "f64".to_string(),
		Ty::Char => "u32".to_string(),
		Ty::Enum(_) => "i32".to_string(),
		Ty::Buf => "crate::rt::Buf".to_string(),
		Ty::Duration => "crate::rt::Duration".to_string(),
		Ty::SocketAddr => "crate::rt::SocketAddr".to_string(),
		Ty::Struct(name) => format!("crate::{name}"),
		Ty::Handle { .. } => "*const c_void".to_string(),
		other => {
			let _ = abi;
			unreachable!("{other:?} is never lent to a trampoline")
		}
	}
}

