//! MIR to Go: every function instance the roots reach, monomorphized, becomes a Go
//! function of one package, its body the MIR's blocks as labels and its locals as
//! variables. Types become Go types, generic where Rust's are, and std's functions
//! translate from their own MIR down to the bindings that stand in for what Go does
//! itself, such as a `Vec`'s growth or UTF-8 validation.

mod body;
mod consts;
mod library;
mod names;
mod ty;

use std::collections::{BTreeMap, HashMap, HashSet, VecDeque};
use std::path::Path;

use rustc_hir::def::DefKind;
use rustc_hir::def_id::{CrateNum, DefId, LOCAL_CRATE};
use rustc_middle::ty::{Instance, Ty, TyCtxt, TypingEnv};
use rustc_span::Span;

use crate::config::Config;

/// The runtime's files, copied into the package beside the translation.
const RUNTIME: &[(&str, &str)] = &[
	("rt.go", include_str!("../../runtime/rt.go")),
	("rt_fmt.go", include_str!("../../runtime/rt_fmt.go")),
];

/// Translate the crate from the config's roots, or `None` after reporting what it
/// refuses. Each file is a name and its text.
pub fn translate(tcx: TyCtxt<'_>, config: &Config) -> Option<Vec<(String, String)>> {
	let mut t = Translator::new(tcx);
	for root in &config.roots {
		t.root(root);
	}
	while let Some((instance, span)) = t.queue.pop_front() {
		let text = body::function(&mut t, instance, span);
		let crate_num = instance.def_id().krate;
		if let Some(text) = text {
			t.out
				.entry(crate_num)
				.or_default()
				.funcs
				.push((t.funcs[&instance].clone(), text));
		}
	}
	if t.failed {
		return None;
	}
	let package = tcx.crate_name(LOCAL_CRATE).to_string();
	let mut files = Vec::new();
	for (krate, out) in std::mem::take(&mut t.out) {
		let mut text = format!(
			"// Generated by rust2-go from crate {}.\n\npackage {package}\n\n",
			tcx.crate_name(krate)
		);
		let mut decls = out.types;
		decls.sort();
		for (_, decl) in decls {
			text.push_str(&decl);
			text.push('\n');
		}
		let mut funcs = out.funcs;
		funcs.sort();
		for (_, func) in funcs {
			text.push_str(&func);
			text.push('\n');
		}
		files.push((format!("{}.go", tcx.crate_name(krate)), text));
	}
	for (name, text) in RUNTIME {
		files.push((
			name.to_string(),
			text.replacen("package rt", &format!("package {package}"), 1),
		));
	}
	Some(files)
}

/// Write the files into `out`, which is replaced, and format them with `gofmt`.
pub fn write(out: &Path, files: &[(String, String)]) -> Result<(), String> {
	if out.exists() {
		std::fs::remove_dir_all(out).map_err(|err| format!("removing {}: {err}", out.display()))?;
	}
	std::fs::create_dir_all(out).map_err(|err| format!("creating {}: {err}", out.display()))?;
	for (name, text) in files {
		let path = out.join(name);
		std::fs::write(&path, text).map_err(|err| format!("writing {}: {err}", path.display()))?;
	}
	// gofmt parses what it formats, so output it rejects is a bug in the translation.
	let output = std::process::Command::new("gofmt")
		.arg("-w")
		.arg(out)
		.output()
		.map_err(|err| format!("running gofmt, which Go's toolchain provides: {err}"))?;
	if !output.status.success() {
		return Err(format!(
			"gofmt rejected the output:\n{}",
			String::from_utf8_lossy(&output.stderr)
		));
	}
	Ok(())
}

/// What one crate's file holds.
#[derive(Default)]
struct CrateOut {
	/// Type declarations, by name.
	types: Vec<(String, String)>,
	/// Functions, by name.
	funcs: Vec<(String, String)>,
}

pub struct Translator<'tcx> {
	tcx: TyCtxt<'tcx>,
	/// Each function instance reached, by its Go name.
	funcs: HashMap<Instance<'tcx>, String>,
	/// Instances whose bodies are still to translate, and the span of what first reached each.
	queue: VecDeque<(Instance<'tcx>, Span)>,
	/// Every name declared at the package level.
	taken: HashSet<String>,
	/// Each type declared, by what it declares: an ADT's definition, or a closure's or a
	/// trait object adapter's monomorphic type.
	types: HashMap<TypeKey<'tcx>, String>,
	/// Every local ADT's name, to tell which names must be qualified by their module.
	local_names: HashMap<String, usize>,
	out: BTreeMap<CrateNum, CrateOut>,
	/// Each refusal reported, so a construct met again at the same place is reported once.
	reported: HashSet<(Span, String)>,
	failed: bool,
}

#[derive(Clone, Copy, PartialEq, Eq, Hash)]
enum TypeKey<'tcx> {
	Adt(DefId),
	Mono(Ty<'tcx>),
}

impl<'tcx> Translator<'tcx> {
	fn new(tcx: TyCtxt<'tcx>) -> Self {
		let mut local_names = HashMap::new();
		for def_id in tcx.hir_crate_items(()).definitions() {
			if matches!(tcx.def_kind(def_id), DefKind::Struct | DefKind::Enum | DefKind::Union) {
				*local_names
					.entry(tcx.item_name(def_id.to_def_id()).to_string())
					.or_default() += 1;
			}
		}
		let mut taken: HashSet<String> = library::RUNTIME_NAMES.iter().map(|s| s.to_string()).collect();
		taken.extend(names::PREDECLARED.iter().map(|s| s.to_string()));
		Self {
			tcx,
			funcs: HashMap::new(),
			queue: VecDeque::new(),
			taken,
			types: HashMap::new(),
			local_names,
			out: BTreeMap::new(),
			reported: HashSet::new(),
			failed: false,
		}
	}

	fn env(&self) -> TypingEnv<'tcx> {
		TypingEnv::fully_monomorphized()
	}

	/// Report a construct translation refuses.
	fn err(&mut self, span: Span, msg: impl Into<String>) {
		self.failed = true;
		let msg = msg.into();
		if self.reported.insert((span, msg.clone())) {
			self.tcx.dcx().span_err(span, format!("rust2-go: {msg}"));
		}
	}

	/// A root function, by its path from the crate root, exported to Go callers.
	fn root(&mut self, path: &str) {
		let tcx = self.tcx;
		let Some(def_id) = names::resolve(tcx, path) else {
			tcx.dcx().err(format!("rust2-go: no item `{path}` in the crate"));
			self.failed = true;
			return;
		};
		if tcx.def_kind(def_id) != DefKind::Fn {
			self.err(tcx.def_span(def_id), "a root must be a function");
			return;
		}
		if tcx.generics_of(def_id).requires_monomorphization(tcx) {
			self.err(tcx.def_span(def_id), "a root must not be generic");
			return;
		}
		let instance = Instance::mono(tcx, def_id);
		let name = names::exported(path);
		self.claim(&name, tcx.def_span(def_id));
		self.funcs.insert(instance, name);
		self.queue.push_back((instance, tcx.def_span(def_id)));
	}

	/// Claim a package-level name, refusing one already taken.
	fn claim(&mut self, name: &str, span: Span) {
		if !self.taken.insert(name.to_string()) {
			self.err(span, format!("two items translate to the Go name `{name}`"));
		}
	}

	/// A fresh package-level name based on `base`.
	fn fresh(&mut self, base: &str) -> String {
		let base = names::ident(base);
		if self.taken.insert(base.clone()) {
			return base;
		}
		for n in 2.. {
			let name = format!("{base}_{n}");
			if self.taken.insert(name.clone()) {
				return name;
			}
		}
		unreachable!()
	}

	/// The Go name of a function instance's translation, queueing its body if new.
	fn func(&mut self, instance: Instance<'tcx>, span: Span) -> String {
		if let Some(name) = self.funcs.get(&instance) {
			return name.clone();
		}
		let base = names::func_base(self.tcx, instance);
		let name = self.fresh(&base);
		self.funcs.insert(instance, name.clone());
		self.queue.push_back((instance, span));
		name
	}

	/// Declare a type in the file of `krate`.
	fn declare(&mut self, krate: CrateNum, name: &str, decl: String) {
		self.out.entry(krate).or_default().types.push((name.to_string(), decl));
	}
}
