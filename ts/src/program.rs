/// The first line of every generated file, which also marks it as safe to replace.
pub const HEADER: &str = "// Generated by rust2-ts. Do not edit.";

/// A Rust module path, from the crate root.
pub type ModPath = Vec<String>;

#[derive(Debug)]
pub struct Symbol {
	pub module: ModPath,
	/// Its item's name, which its instances share.
	pub base: String,
	/// Appended after a `$`, whether or not another instance of its item is reached:
	/// what tells the instance apart, such as `fmt_Display_copy_Pair`. Empty for none.
	pub suffix: String,
	/// The class a method belongs to.
	pub owner: Option<SymId>,
	pub kind: SymKind,
	/// Its source position in rustc's source map, which numbers files in the order it
	/// loads them.
	pub order: u32,
	/// Where it is defined, or first reached for what translation makes, which a collision
	/// of its name reports.
	pub span: rustc_span::Span,
	/// The function instance it is, printed in full; empty for anything else.
	pub instance: String,
	/// The final name, set by [`Program::name`].
	pub name: String,
	/// The name it is exported as, where `name` had to escape a reserved word: `new` for
	/// `new_`. Set by [`Program::name`].
	pub alias: Option<String>,
}

impl Symbol {
	/// Where it sorts among its module's items or its owner's methods: in source order,
	/// and the instances of one generic item by their suffix, then in full. None of it
	/// depends on the order translation reaches them in.
	pub fn key(&self) -> (u32, &str, &str, &str) {
		(self.order, &self.base, &self.suffix, &self.instance)
	}
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SymKind {
	Struct,
	/// A type alias, which has no value.
	Union,
	Function,
	/// A module's value, as `Item::Value`.
	Value,
	/// A class's method, called on its receiver: drop glue's `[Symbol.dispose]`, and a
	/// coroutine's `poll`.
	Method,
}

#[derive(Debug)]
pub struct FieldInfo {
	pub owner: SymId,
	pub base: String,
	pub name: String,
}

/// A Rust source file, for source maps.
#[derive(Debug)]
pub struct Source {
	pub path: PathBuf,
	pub text: String,
	/// Where rustc's source map starts it, which spans count from.
	pub start: rustc_span::BytePos,
}

#[derive(Debug, Default)]
pub struct Program {
	pub syms: Vec<Symbol>,
	pub fields: Vec<FieldInfo>,
	/// Module-level items, by the symbol each defines.
	pub items: Vec<Item>,
	/// The methods of each class, by owner.
	pub methods: HashMap<SymId, Vec<Function>>,
	/// The structs whose values are plain objects; the others are classes.
	pub plain: HashSet<SymId>,
	/// The instances of std's functions, which [`Program::merge`] merges.
	pub std: HashSet<SymId>,
	/// Those merged into another, which have no name of their own.
	merged: HashSet<SymId>,
	pub sources: Vec<Source>,
	/// The hand-written files that bindings reach, copied into the output, by module.
	pub bound: BTreeMap<ModPath, Bound>,
	/// What `tsc` checks each binding against: a function of the check module each.
	pub checks: Vec<Check>,
	/// What import bindings avoid.
	pub names: Names,
}

/// The census import bindings are chosen by: each name a module could declare at its top
/// level, as far as its first `$`, as [`Program::name`] names the symbol, and every module
/// of the crate graph that could, whether or not translation reaches it. An import binds
/// by its plain name where no other module could declare one of it, so whether it does
/// depends on the crate graph alone, as rustc's trimmed paths do.
#[derive(Debug, Default)]
pub struct Names(HashMap<String, BTreeMap<ModPath, ModPath>>);

impl Names {
	/// Note that `module` could declare `name`, which importers qualify by `path`.
	pub fn declare(&mut self, name: &str, module: ModPath, path: ModPath) {
		self.0.entry(root(name).to_string()).or_default().insert(module, path);
	}

	/// What an importer prefixes `name` from `module` with, after an `_`: the shortest end
	/// of its module path no other module that could declare it shares, or `None` where no
	/// other could. `always` qualifies it even so, where the importer declares the name
	/// itself.
	pub fn qualifier(&self, name: &str, module: &ModPath, always: bool) -> Result<Option<String>, String> {
		let root = root(name);
		let path = self
			.0
			.get(root)
			.and_then(|modules| modules.get(module))
			.ok_or_else(|| {
				format!(
					"the census of names misses `{name}`, which {} declares",
					module_file(module).display()
				)
			})?;
		let modules = &self.0[root];
		if !always && modules.len() == 1 {
			return Ok(None);
		}
		let others: Vec<&ModPath> = (modules.iter())
			.filter(|(other, _)| *other != module)
			.map(|(_, path)| path)
			.collect();
		let len = (1..path.len())
			.find(|&len| (others.iter()).all(|other| *other == path || !other.ends_with(&path[path.len() - len..])))
			.unwrap_or(path.len());
		let mut qualifier = path[path.len() - len..].join("_");
		// A type and a value of one Rust module, in their two namespaces: the type's module
		// adds its name, as its file does.
		if others.contains(&path) && module.last().is_some_and(|last| last.contains('.')) {
			qualifier = format!("{qualifier}_{root}");
		}
		Ok(Some(qualifier))
	}

	/// Fail where two qualified bindings, or one and a plain name, would be one name, so
	/// that no translation can bind two items alike.
	pub fn check(&self) -> Result<(), String> {
		let mut bindings: HashMap<String, &ModPath> = HashMap::new();
		for (name, modules) in &self.0 {
			for module in modules.keys() {
				let Some(qualifier) = self.qualifier(name, module, false)? else {
					continue;
				};
				let binding = format!("{qualifier}_{name}");
				if self.0.contains_key(&binding) {
					return Err(format!(
						"`{name}` of {} would bind as `{binding}`, which is another item's name",
						module_file(module).display()
					));
				}
				if let Some(other) = bindings.insert(binding.clone(), module) {
					return Err(format!(
						"{} and {} would each bind an item as `{binding}`",
						module_file(other).display(),
						module_file(module).display()
					));
				}
			}
		}
		Ok(())
	}
}

/// A name as far as its first `$`, which the suffix after it only tells apart within one
/// module.
pub fn root(name: &str) -> &str {
	name.split('$').next().unwrap_or(name)
}

/// A binding's file, which callers import whole, as they do a type's module.
#[derive(Debug)]
pub struct Bound {
	/// The file it is copied from.
	pub source: PathBuf,
	pub text: String,
	/// What callers import it as: the type bound to it, or else its file's name.
	pub namespace: String,
	/// Its file's name as an identifier, which callers prefix the namespace with where it
	/// is taken.
	pub prefix: String,
}

/// A function that type-checks only if a binding is what translated code takes it for.
#[derive(Debug)]
pub struct Check {
	pub item: Item,
	/// The Rust item, which a failed check reports.
	pub span: rustc_span::Span,
	pub what: String,
}

impl Program {
	pub fn sym(&mut self, sym: Symbol) -> SymId {
		self.syms.push(sym);
		self.syms.len() - 1
	}

	pub fn field(&mut self, owner: SymId, base: String) -> FieldId {
		self.fields.push(FieldInfo {
			owner,
			base,
			name: String::new(),
		});
		self.fields.len() - 1
	}

	/// Mark each parameter of every function that nothing reads, as [`ts::mark_unread`] does.
	pub fn mark_unread(&mut self) {
		for item in &mut self.items {
			match item {
				Item::Function(f) => ts::mark_unread(&mut f.params, &mut f.body),
				Item::Struct { fields, .. } => {
					for field in fields {
						if let ts::FieldInit::Value(e) = &mut field.init {
							e.mark_unread();
						}
					}
				}
				Item::Value { value, .. } => value.mark_unread(),
				Item::Union { .. } => {}
			}
		}
		for f in self.methods.values_mut().flatten() {
			ts::mark_unread(&mut f.params, &mut f.body);
		}
	}

	/// Make one function of the instances of a std function whose output is the same, as
	/// those over closures of one signature are: the first in order, which the others'
	/// callers then call. Each merge can make their callers the same too.
	pub fn merge(&mut self) {
		loop {
			let mut same: HashMap<SymId, SymId> = HashMap::new();
			let mut kept: HashMap<Output, SymId> = HashMap::new();
			let mut functions: Vec<&Function> = (self.items.iter())
				.filter_map(|item| match item {
					Item::Function(f) if self.std.contains(&f.sym) => Some(f),
					_ => None,
				})
				.collect();
			functions.sort_by_key(|f| self.syms[f.sym].key());
			for f in functions {
				let sym = &self.syms[f.sym];
				let key = (&sym.module, sym.base.as_str(), &f.params[..], &f.ret, &f.body[..]);
				let first = *kept.entry(key).or_insert(f.sym);
				if first != f.sym {
					same.insert(f.sym, first);
				}
			}
			if same.is_empty() {
				return;
			}
			self.items
				.retain(|item| !matches!(item, Item::Function(f) if same.contains_key(&f.sym)));
			let mut rename = |id: &mut SymId| {
				if let Some(&to) = same.get(id) {
					*id = to;
				}
			};
			let functions = self.items.iter_mut().filter_map(|item| match item {
				Item::Function(f) => Some(f),
				_ => None,
			});
			for f in functions.chain(self.methods.values_mut().flatten()) {
				ts::syms_mut(&mut f.body, &mut rename);
			}
			for item in &mut self.items {
				match item {
					Item::Struct { fields, .. } => {
						for field in fields {
							if let ts::FieldInit::Value(e) = &mut field.init {
								e.syms_mut(&mut rename);
							}
						}
					}
					Item::Value { value, .. } => value.syms_mut(&mut rename),
					_ => {}
				}
			}
			self.std.retain(|id| !same.contains_key(id));
			self.merged.extend(same.into_keys());
		}
	}

	/// Put every item and method in order, and name every symbol and field: each symbol by
	/// its base and suffix alone, failing where two in one scope would share a name, and a
	/// field by its own, numbered where it clashes in its class.
	pub fn name(&mut self) -> Result<(), (rustc_span::Span, String)> {
		let syms = &self.syms;
		self.items
			.sort_by(|a, b| syms[item_sym(a)].key().cmp(&syms[item_sym(b)].key()));
		for methods in self.methods.values_mut() {
			methods.sort_by(|a, b| syms[a.sym].key().cmp(&syms[b.sym].key()));
		}

		let mut scopes: BTreeMap<Scope, Vec<SymId>> = BTreeMap::new();
		for (id, sym) in self.syms.iter().enumerate() {
			if self.merged.contains(&id) {
				continue;
			}
			let scope = match sym.owner {
				Some(owner) => Scope::Owner(owner),
				None => Scope::Module(sym.module.clone()),
			};
			scopes.entry(scope).or_default().push(id);
		}
		for field in &self.fields {
			scopes.entry(Scope::Owner(field.owner)).or_default();
		}

		for (scope, mut ids) in scopes {
			// A binding's names are its file's exports, which lowering named already.
			if matches!(&scope, Scope::Module(module) if self.bound.contains_key(module)) {
				continue;
			}
			ids.sort_by(|&a, &b| self.syms[a].key().cmp(&self.syms[b].key()));
			// What a class already defines, and else the runtime's import binding.
			let defined: &[&str] = match &scope {
				Scope::Module(_) => &["rt"],
				Scope::Owner(_) => &["constructor", "prototype"],
			};
			let mut named: HashMap<String, Option<SymId>> =
				defined.iter().map(|name| (name.to_string(), None)).collect();
			for id in ids {
				let sym = &self.syms[id];
				if self.by_text(id) {
					continue;
				}
				let base = match sym.suffix.is_empty() {
					true => sym.base.clone(),
					false => format!("{}${}", sym.base, sym.suffix),
				};
				let name = match sym.kind {
					SymKind::Function | SymKind::Value => crate::lower::escape(&base),
					_ => base.clone(),
				};
				if let Some(other) = named.insert(name.clone(), Some(id)) {
					let what = |sym: &Symbol| match sym.instance.is_empty() {
						true => format!("`{}`", sym.base),
						false => format!("`{}`", sym.instance),
					};
					let file = module_file(&sym.module);
					let msg = match other {
						Some(other) => format!(
							"{} and {} would both be named `{name}` in {}",
							what(&self.syms[other]),
							what(sym),
							file.display()
						),
						None => format!(
							"{} would be named `{name}`, which {} defines",
							what(sym),
							file.display()
						),
					};
					return Err((sym.span, msg));
				}
				self.syms[id].alias = (name != base).then_some(base);
				self.syms[id].name = name;
			}
			let mut taken: HashSet<String> = named.into_keys().collect();
			if let Scope::Owner(owner) = scope {
				for field in self.fields.iter_mut().filter(|f| f.owner == owner) {
					let base = match field.base.strip_prefix('#') {
						// The one private name JS forbids.
						Some("constructor") => "#_constructor".to_string(),
						// Any other can only clash with another field's, which `unique` numbers.
						Some(_) => field.base.clone(),
						// A name a class already defines: the field gives way.
						None if taken.contains(&field.base) => format!("_{}", field.base),
						None => field.base.clone(),
					};
					field.name = unique(&mut taken, &base);
				}
			}
		}
		self.name_by_text()
	}

	/// Whether `id` is an instance of a std function that another could have merged into,
	/// which is named for its text rather than for its type arguments.
	fn by_text(&self, id: SymId) -> bool {
		self.std.contains(&id) && !self.syms[id].suffix.is_empty()
	}

	/// Name each instance [`Program::by_text`] picks `base$hash`, a hash of its text with
	/// what it calls by name, so the name is the same whichever of the instances that merged
	/// into it translation reaches. Those it calls are named first; instances that call each
	/// other read each other's calls alike.
	fn name_by_text(&mut self) -> Result<(), (rustc_span::Span, String)> {
		let functions: BTreeMap<SymId, &Function> = (self.items.iter())
			.filter_map(|item| match item {
				Item::Function(f) if self.by_text(f.sym) => Some((f.sym, f)),
				_ => None,
			})
			.collect();
		let path = |sym: &Symbol| format!("{}/{}", sym.module.join("/"), sym.name);
		let mut texts = print::Texts::new(
			(self.syms.iter().enumerate())
				.filter(|(_, sym)| !sym.name.is_empty())
				.map(|(id, sym)| (id, path(sym)))
				.collect(),
		);
		let hash = |texts: &print::Texts, f: &Function| {
			let mut hasher = StableHasher::new();
			hasher.write(texts.text(self, f).as_bytes());
			let hash: Hash64 = hasher.finish();
			(hash.as_u64() as u32).to_base_fixed_len(CASE_INSENSITIVE).to_string()
		};
		let mut names = Vec::new();
		for group in callees_first(&functions) {
			for &id in &group {
				texts.set(id, "recursive".into());
			}
			let mut hashes: Vec<String> = group.iter().map(|id| hash(&texts, functions[id])).collect();
			if group.len() > 1 {
				for (&id, h) in group.iter().zip(&hashes) {
					texts.set(id, h.clone());
				}
				hashes = group.iter().map(|id| hash(&texts, functions[id])).collect();
			}
			for (id, h) in group.into_iter().zip(hashes) {
				let sym = &self.syms[id];
				let name = format!("{}${h}", sym.base);
				texts.set(id, format!("{}/{name}", sym.module.join("/")));
				names.push((id, name));
			}
		}
		for (id, name) in names {
			let module = &self.syms[id].module;
			if self.syms.iter().any(|s| &s.module == module && s.name == name) {
				return Err((
					self.syms[id].span,
					format!(
						"two functions of {} hash to one name, {name}",
						module_file(module).display()
					),
				));
			}
			self.syms[id].name = name;
		}
		Ok(())
	}

	/// Write every module, the runtime, and their source maps to `out`, returning each
	/// module as printed, by its file.
	pub fn write(&self, out: &Path) -> Result<Vec<(PathBuf, print::Printed)>, String> {
		// A copy, or a clean, would replace or remove the source.
		if let Ok(dir) = out.canonicalize()
			&& let Some(bound) = self
				.bound
				.values()
				.find(|b| b.source.canonicalize().is_ok_and(|s| s.starts_with(&dir)))
		{
			return Err(format!(
				"the binding {} is inside the output, {}, which a translation replaces",
				bound.source.display(),
				out.display()
			));
		}
		clean(out)?;
		let mut modules: BTreeMap<&ModPath, Vec<&Item>> = BTreeMap::new();
		for item in &self.items {
			modules.entry(&self.syms[item_sym(item)].module).or_default().push(item);
		}
		if modules
			.keys()
			.any(|module| module.first().is_some_and(|name| name == "rt"))
		{
			return Err("a top-level module named `rt` would replace the runtime, rt.ts and rt/".into());
		}

		for (path, text) in RUNTIME {
			write_file(&out.join(path), &format!("{HEADER}\n{text}"))?;
		}
		// Two types whose names differ only in case would share a file where file names
		// ignore case, as on macOS and Windows.
		let mut files = HashMap::new();
		for module in modules.keys().copied().chain(self.bound.keys()) {
			let file = module_file(module);
			let folded = file.to_string_lossy().to_lowercase();
			if let Some(other) = files.insert(folded, file.clone()) {
				if other == file {
					return Err(format!(
						"{} is a binding's file, which would replace a translated module's",
						file.display()
					));
				}
				return Err(format!(
					"{} and {} differ only in case, which a case-insensitive file system can't tell apart",
					other.display(),
					file.display()
				));
			}
		}
		let mut written = Vec::new();
		for (module, items) in modules {
			let file = module_file(module);
			let path = out.join(&file);
			let printed = print::module(self, module, &items, &path)?;
			write_file(&path, &printed.code)?;
			write_file(&path.with_extension("ts.map"), &printed.map)?;
			written.push((file, printed));
		}
		for (module, bound) in &self.bound {
			write_file(&out.join(module_file(module)), &format!("{HEADER}\n{}", bound.text))?;
		}
		Ok(written)
	}

	/// How a module's importers bind it whole, if they do: a type's module, or a binding's
	/// file. The name its importers give it, and what they prefix that with where it is taken.
	pub fn namespace<'p>(&'p self, module: &'p ModPath) -> Option<(&'p str, &'p str)> {
		if let Some(bound) = self.bound.get(module) {
			return Some((&bound.prefix, &bound.namespace));
		}
		// `decode.Decoder` binds `Decoder`, or `decode_Decoder` if that is taken.
		module.last()?.split_once('.')
	}
}

/// The strongly connected components of the calls among `functions`, each after those it
/// calls, by Tarjan's algorithm.
fn callees_first(functions: &BTreeMap<SymId, &Function>) -> Vec<Vec<SymId>> {
	#[derive(Default)]
	struct Walk {
		index: HashMap<SymId, usize>,
		low: HashMap<SymId, usize>,
		stack: Vec<SymId>,
		on_stack: HashSet<SymId>,
		groups: Vec<Vec<SymId>>,
	}
	fn visit(walk: &mut Walk, calls: &BTreeMap<SymId, Vec<SymId>>, id: SymId) {
		let index = walk.index.len();
		walk.index.insert(id, index);
		walk.low.insert(id, index);
		walk.stack.push(id);
		walk.on_stack.insert(id);
		for &callee in &calls[&id] {
			if !walk.index.contains_key(&callee) {
				visit(walk, calls, callee);
				let low = walk.low[&id].min(walk.low[&callee]);
				walk.low.insert(id, low);
			} else if walk.on_stack.contains(&callee) {
				let low = walk.low[&id].min(walk.index[&callee]);
				walk.low.insert(id, low);
			}
		}
		if walk.low[&id] == index {
			let mut group = Vec::new();
			while let Some(member) = walk.stack.pop() {
				walk.on_stack.remove(&member);
				group.push(member);
				if member == id {
					break;
				}
			}
			walk.groups.push(group);
		}
	}
	let calls: BTreeMap<SymId, Vec<SymId>> = (functions.iter())
		.map(|(&id, f)| {
			let mut callees = Vec::new();
			ts::syms_mut(&mut f.body.clone(), &mut |callee| {
				if functions.contains_key(callee) {
					callees.push(*callee);
				}
			});
			(id, callees)
		})
		.collect();
	let mut walk = Walk::default();
	for &id in calls.keys() {
		if !walk.index.contains_key(&id) {
			visit(&mut walk, &calls, id);
		}
	}
	walk.groups
}

/// What a function of a module prints as, but for its own name: its item, parameters,
/// return type, and body.
type Output<'a> = (&'a ModPath, &'a str, &'a [ts::Param], &'a ts::Type, &'a [ts::Stmt]);

#[derive(PartialEq, Eq, PartialOrd, Ord)]
enum Scope {
	Module(ModPath),
	Owner(SymId),
}

/// `base`, or the first of `base$2`, `base$3`, and on that is not taken.
pub(crate) fn unique(taken: &mut HashSet<String>, base: &str) -> String {
	let mut name = base.to_string();
	let mut n = 2;
	while taken.contains(&name) {
		name = format!("{base}${n}");
		n += 1;
	}
	taken.insert(name.clone());
	name
}

pub fn item_sym(item: &Item) -> SymId {
	match item {
		Item::Struct { sym, .. } | Item::Union { sym, .. } => *sym,
		Item::Function(f) => f.sym,
		Item::Value { sym, .. } => *sym,
	}
}

/// The module of a type and its functions, beside the Rust module that defines it:
/// `coding/decode.Decoder.ts` for `coding::decode::Decoder`, which callers import whole,
/// `import * as Decoder`. A Rust module's name has no `.`, so neither can collide.
pub fn type_module(module: &[String], ty: &str) -> ModPath {
	let (parents, last) = match module {
		[] => (&[][..], "lib"),
		[parents @ .., last] => (parents, last.as_str()),
	};
	let mut path = parents.to_vec();
	path.push(format!("{last}.{ty}"));
	path
}

/// The file a module is written to, relative to the output directory.
pub fn module_file(module: &[String]) -> PathBuf {
	match module {
		[] => PathBuf::from("lib.ts"),
		[parents @ .., last] => parents.iter().collect::<PathBuf>().join(format!("{last}.ts")),
	}
}

/// Remove what an earlier run generated, and nothing else.
pub fn clean(out: &Path) -> Result<(), String> {
	let Ok(entries) = std::fs::read_dir(out) else {
		return Ok(());
	};
	for entry in entries {
		let path = entry.map_err(|err| format!("reading {}: {err}", out.display()))?.path();
		if path.is_dir() {
			clean(&path)?;
			// Only succeeds once nothing else is left in it.
			let _ = std::fs::remove_dir(&path);
			continue;
		}
		let generated = match path.extension().and_then(|e| e.to_str()) {
			Some("ts") => std::fs::read_to_string(&path).is_ok_and(|text| text.starts_with(HEADER)),
			Some("map") => path
				.file_stem()
				.is_some_and(|stem| stem.to_string_lossy().ends_with(".ts")),
			_ => false,
		};
		if generated {
			std::fs::remove_file(&path).map_err(|err| format!("removing {}: {err}", path.display()))?;
		}
	}
	Ok(())
}

/// Write `text` to `path`, creating its directory.
pub fn write_file(path: &Path, text: &str) -> Result<(), String> {
	if let Some(dir) = path.parent() {
		std::fs::create_dir_all(dir).map_err(|err| format!("creating {}: {err}", dir.display()))?;
	}
	std::fs::write(path, text).map_err(|err| format!("writing {}: {err}", path.display()))
}
